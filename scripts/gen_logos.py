"""MACHINE SEL's logos (RIFT v0.16, owner 2026-11-21): src/dnfw/waverider/logos/*.png -> csrc/waverider/logos.h.

    python3 scripts/gen_logos.py [--check]

Each logo is 46 x 32 pixels, 1 bit, drawn in MACHINE SEL's picture (x 0..45, rows 10..41 from the top)
when the machine under the cursor is one of RIFT's; the sample machines' column label reads SAMP and
DIGIDRUM's DRUM, in the stock label's own 8-row letters (copied by eye from its SYN).
"""
from __future__ import annotations

import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "src/dnfw/waverider/logos"
OUT = ROOT / "csrc/waverider/logos.h"
W, H = 46, 32
ORDER = ("organ", "fascia", "silt", "ligature", "digidrum", "dt2")
# the label's letters, 5 x 8, as the stock SYN's (rows top to bottom)
GLYPHS = {
    "S": (".####", "#####", "##...", "####.", ".####", "...##", "#####", "####."),
    "A": (".###.", "#####", "##.##", "##.##", "#####", "#####", "##.##", "##.##"),
    "M": ("##.##", "#####", "#####", "#.#.#", "##.##", "##.##", "##.##", "##.##"),
    "P": ("####.", "#####", "##.##", "##.##", "#####", "####.", "##...", "##..."),
    "D": ("####.", "#####", "##.##", "##.##", "##.##", "##.##", "#####", "####."),
    "R": ("####.", "#####", "##.##", "##.##", "####.", "#####", "##.##", "##.##"),
    "U": ("##.##", "##.##", "##.##", "##.##", "##.##", "##.##", "#####", ".###."),
}
LABELS = ("SAMP", "DRUM")


def logo_rows(name: str) -> list[int]:
    im = Image.open(SRC / f"{name}.png").convert("1")
    if im.size != (W, H):
        raise SystemExit(f"{name}.png is {im.size}, not {W} x {H}")
    px = im.load()
    out = []
    for y in range(H):
        for b in range((W + 7) // 8):
            v = 0
            for k in range(8):
                x = 8 * b + k
                if x < W and px[x, y]:
                    v |= 0x80 >> k
            out.append(v)
    return out


def text() -> str:
    L = ["/* generated by scripts/gen_logos.py from the PNGs in src/dnfw/waverider/logos: do not edit */",
         f"#define LOGO_W {W}", f"#define LOGO_H {H}", f"#define LOGO_N {len(ORDER)}",
         f"#define LOGO_BPR {(W + 7) // 8}"]
    L.append("static const unsigned char ms_logos[LOGO_N][LOGO_H * LOGO_BPR] = {")
    for n in ORDER:
        L.append(f"    /* {n} */ {{" + ",".join(f"0x{v:02x}" for v in logo_rows(n)) + "},")
    L.append("};")
    for i, n in enumerate(ORDER):
        L.append(f"#define LOGO_{n.upper()} {i}")
    L.append("/* the labels' letters: each row a byte, bit 4 the leftmost of five */")
    L.append("static const unsigned char ms_label[2][4][8] = {")
    for lab in LABELS:
        L.append("    {" + ", ".join("{" + ",".join(f"0x{int(r.replace('#', '1').replace('.', '0'), 2):02x}" for r in GLYPHS[c]) + "}"
                               for c in lab) + "},   /* " + lab + " */")
    L.append("};")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    t = text()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == t else "csrc/waverider/logos.h is stale: run scripts/gen_logos.py")
    OUT.write_text(t)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(ORDER)} logos, {len(ORDER) * H * ((W + 7) // 8)} bytes")
