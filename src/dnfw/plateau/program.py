"""PLATEAU's DSP program (machine type 24, RIFT v0.17's first FX machine): `dnfw.plateau.live.Voice`
on the SHARC, in FASCIA's expression compiler with ORGAN's leaves (exp2f, expf, sin_turns, recip).
The same calls are the assembly text and, run in Python, its exact model; test_plateau_program holds
the run mode to live.Voice bit for bit.

**Where it runs.** Inside FASCIA's program (fascia.asm), as ORGAN, SILT, LIGATURE and DIGIDRUM do:
FASCIA's walk renders a slot whose frame type word is 23 with this, under the same guard.

**Its input, the bus.** The tracks in its mask (three records, six bits each: the BUS page), each
track's block as Overbridge's TRK streams read it (`SM.TRK_BUF + 0x100 t`, L and R, the block
before), summed; the slot's own track (the frame's slot -> track word, `0xa5a + 2 t`) never.

**Its lines.** One instance (`live.Shared`): PLATEAU_DDR's owner word, then the lines (83,968
words). The newest voice to start owns them; a fresh instance clears them, CHUNK words a block.
"""
