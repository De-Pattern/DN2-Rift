F = np.float32
TYPE = 24                              # RIFT v0.17: after THOLET's 23 (gone: a saved THOLET track loads as FM Tone)
NK = 16
MAGIC = 0x504C5421                     # 'PLT!'
assert BLOCK == LV.SUB
CTRL = LV.CONTROLS
TRACK_OF = 0xA5A                       # the frame's slot -> track words (docs/link-research.md)
LINES_AT = 0x100                       # the lines, after the owner word

# -- the voice's words (in the slot's FASCIA state) ------------------------------------------------
VOICE = St().w("on", "pending", "fading")
assert [VOICE[x] for x in ("on", "pending", "fading")] == [FP_.VOICE[x] for x in ("on", "pending", "fading")]
VOICE.w("magic", "wp", "clr", "quiet", "ph", "lp_in", "hp_in").w("sd", n=6)   # sides A, B: damp, hp, end
VOICE_WORDS = VOICE.n
assert 4 * VOICE_WORDS <= STRIDE

# -- the tables (DDR): the knobs' records, then the mask's ------------------------------------------
# KREC: the knobs' records; MREC: the mask's; LCON: each length's (constant, floor) as floats, the
# tank's eight and the fourteen taps (by SIZE), then the four input allpasses (by SIZE x 1.6);
# TDES: each tap's line (its first word's address, its mask) and sign; IDES: each input allpass's
NLS = len(LV.TANK) + len(LV.TAPS)              # the lengths set by the scale
NLEN = NLS + len(LV.IN_AP)
TAB = {"KREC": (0, 4 * NK), "MREC": (4 * NK, 3), "LCON": (4 * NK + 3, 2 * NLEN),
       "TDES": (4 * NK + 3 + 2 * NLEN, 3 * len(LV.TAPS)),
       "IDES": (4 * NK + 3 + 2 * NLEN + 3 * len(LV.TAPS), 2 * len(LV.IN_AP))}
TAB["HDES"] = (TAB["IDES"][0] + TAB["IDES"][1], 16)    # sides A, B: ap, d1, ap2, d2 (base, mask)
TABLE_WORDS = TAB["HDES"][0] + TAB["HDES"][1]


def _krec() -> list[int]:
    from . import machines as PM
    from ..fascia import machines as FM
    out = []
    for cn in PM.CONTROLS:
        _rid, slot, lo, top = FM.SLOTS[PM.RIDES[cn]]
        assert lo == 0 and top == 127, cn
        n = 2 if cn in LV.SWITCHES else 0
        out += [168 + 2 * slot, top, n, 0]
    for ride in PM.MASK_RIDES:
        _rid, slot, lo, top = FM.SLOTS[ride]
        assert lo == 0 and top == 127
        out.append(168 + 2 * slot)
    return out


def _consts(lines: int) -> list[int]:
    out = []
    for n, _l, _s in LV.TANK:
        out += [bits(LV.LK[n]), bits(F(2.0))]
    for tk in LV.TK:
        out += [bits(tk), bits(F(1.0))]
    for n, _l, _s in LV.IN_AP:
        out += [bits(LV.LK[n]), bits(F(1.0))]
    for line, _t, sg in LV.TAPS:
        out += [lines + LINES_AT + 4 * LV.OFF[line], LV.SIZE[line] - 1, bits(F(float(sg)))]
    for n, _l, _s in LV.IN_AP:
        out += [lines + LINES_AT + 4 * LV.OFF[n], LV.SIZE[n] - 1]
    for n, _l, _s in LV.TANK:
        out += [lines + LINES_AT + 4 * LV.OFF[n], LV.SIZE[n] - 1]
    return out


def tables_bytes(lines: int | None = None) -> bytes:
    if lines is None:
        from ..waverider import dsp
        lines = dsp.PLATEAU_DDR
    ws = _krec() + _consts(lines)
    assert len(ws) == TABLE_WORDS
    return struct.pack(f"<{TABLE_WORDS}I", *ws)


def write_ddr_json() -> None:
    import json
    from . import ddr
    words = [f"{x:08x}" for x in struct.unpack(f"<{TABLE_WORDS}I", tables_bytes())]   # (PLATEAU_DDR's lines)
    ddr.DDR_JSON.write_text(json.dumps({"note": "generated by scripts/gen_fascia_asm.py from dnfw.plateau; do not edit",
                                        "words": words}) + "\n", encoding="utf-8", newline="\n")


def k(x) -> Kc:
    return Kc(float(F(x)))


# -- the block's words (FASCIA's transient arrays) --------------------------------------------------
_SRC = pathlib.Path(__file__).read_text(encoding="utf-8")
LEN_WORDS = tuple("L_" + n for n, _l, _s in LV.TANK) + tuple("I_" + n for n, _l, _s in LV.IN_AP)
TAP_WORDS = tuple(f"tap{j}" for j in range(len(LV.TAPS)))
WORDS = tuple(sorted((set(re.findall(r'\bc\("([A-Za-z_0-9]+)"\)', _SRC)) - {"ma", "mb", "dma", "dmb", "na", "nb"})
                     | {"trig", "nn", "k146", "cnt0", "cnt1", "cnt2", "krp", "kep", "vba", "outp", "bp",
                        "mask", "mine", "tbit", "tsrc", "wi", "di", "pred", "hold", "tund", "x2", "lcp", "lep",
                        "dp", "lb", "lm", "dw", "sc", "sp", "op", "hp_", "lp_", "mp", "np_"}
))
ARRAYS = {"eff": NK, "inb": BLOCK, "len": NLEN, "tapd": 3 * len(LV.TAPS), "iapd": 2 * len(LV.IN_AP),
          "hd": 16, "mm": 2, "dm": 2, "ne": 2}
LEN_ORDER = tuple("L_" + n for n, _l, _s in LV.TANK) + TAP_WORDS + tuple("I_" + n for n, _l, _s in LV.IN_AP)


class Layout:
    def __init__(self, fascia: FP_.Layout, tables: int, lines: int):
        self.fl = fascia
        self.state, self.state2 = fascia.state, fascia.state2
        self.t_word = fascia.C["t"]
        self.stolen, self.strikes = fascia.stolen, fascia.strikes
        self.tables = tables
        self.ddr = lines                       # the owner word; the lines at + LINES_AT
        at = fascia.arrays
        self.C = {}
        for name in WORDS:
            self.C[name] = at
            at += 4
        self.A = {}
        for name, n in ARRAYS.items():
            self.A[name] = at
            at += 4 * n
        for j, name in enumerate(LEN_ORDER):   # the lengths are the "len" array's words
            self.C[name] = self.A["len"] + 4 * j
        for j, name in enumerate(("ma", "mb")):  # the sides' modulation, its step, their new ends
            self.C[name] = self.A["mm"] + 4 * j
            self.C["d" + name] = self.A["dm"] + 4 * j
            self.C["n" + name[1]] = self.A["ne"] + 4 * j
        self.words_end = at
        assert at <= fascia.scratch_end, (at - fascia.scratch_end, "PLATEAU's words must fit in FASCIA's arrays")
        self.scratch, self.scratch_end, self.base5 = fascia.scratch, fascia.scratch_end, fascia.base5
        self.rets = fascia.rets

    def line(self, name: str) -> int:
        return self.ddr + LINES_AT + 4 * LV.OFF[name]


INV12 = float(F(F(1.0) / F(12.0)))


def note_hz(n) -> E:
    return k(440.0) * exp2f((n - k(69.0)) * k(INV12))


def onepole(hz) -> E:
    return k(1.0) - expf(k(0.0) - k(LV.TWOPI_FS) * mn(hz, k(LV.HMAX)))


class PG(OP.OG):
    """FASCIA's compiler with ORGAN's leaves, and PLATEAU's lines"""

    def c(self, name) -> Mv:
        return Mv("a", self.L.C[name])

    def V(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j)

    def Vi(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j, isint=True)

    def a(self, arr, j) -> Mv:
        return Mv("a", self.L.A[arr] + 4 * j)

    def e(self, cn) -> Mv:
        return self.a("eff", CTRL.index(cn))

    def q(self, cn) -> E:
        return self.e(cn) * k(LV.INV127)

    def bump(self, word: str, by: int) -> None:
        p, C = self.p, self.L.C
        p.ld(13, C[word])
        p.iconst(12, by)
        p.iop(13, 12, "+", 13)
        p.st(C[word], 13)

    def ptr(self, ireg: int, word: str) -> None:
        self.p.ld(12, self.L.C[word])
        self.p.seti(ireg, 12)

    def ivloop(self, cnt: str, body) -> None:
        FP_.FP.ivloop(self, cnt, body)

    def trunc_to(self, word: str, e) -> None:
        """the int word = trunc(e)"""
        self.ev(w(e), 0)
        self.p.trunc(0, 0)
        self.p.st(self.L.C[word], 0)

    # -- the lines: buf[(wp - d) & mask] ------------------------------------------------------------
    def _addr(self, line: str, ireg: int = 1) -> None:
        """I<ireg> = the line's word at index R9 (R9 is masked here)"""
        p = self.p
        p.iconst(12, LV.SIZE[line] - 1)
        p.iop(9, 9, "AND", 12)
        p.lsh(9, 9, 2)
        p.iconst(12, self.L.line(line))
        p.iop(9, 9, "+", 12)
        p.seti(ireg, 9)

    def rd_to(self, d: int, line: str, dword: str) -> None:
        """Fd = live.rd(line, the int word dword)"""
        p, C = self.p, self.L.C
        p.ld(9, C["wi"])
        p.ld(10, C[dword])
        p.iop(9, 9, "-", 10)
        self._addr(line)
        p.ldi(d, 0, 1)

    def wr_from(self, line: str, s: int) -> None:
        """live.wr(line, Fs) (R9, R12 and I1 clobbered)"""
        p, C = self.p, self.L.C
        p.ld(9, C["wi"])
        self._addr(line)
        p.sti(0, 1, s)

    def ap(self, line: str, x: E, dword: str, g: E) -> None:
        """c('apo') = live.ap(line, x, d, g): the routine p_ap on the line's (lb, lm) and dw"""
        p, C, c = self.p, self.L.C, self.c
        self.set(c("apx"), x)
        self.set(c("apg"), g)
        p.iconst(0, self.L.line(line))
        p.st(C["lb"], 0)
        p.iconst(0, LV.SIZE[line] - 1)
        p.st(C["lm"], 0)
        p.ld(0, C[dword])
        p.st(C["dw"], 0)
        self.rt("p_ap", self.ap_body)

    def ap_body(self) -> None:
        """apo = live.ap on the line at (lb, lm), delay dw, of apx with apg"""
        p, C, c = self.p, self.L.C, self.c
        p.ld(9, C["wi"])
        p.ld(10, C["dw"])
        p.iop(9, 9, "-", 10)
        self._addr_w()
        p.ldi(0, 0, 1)
        self.st(c("z"), 0)
        self.set(c("v"), c("apx") - c("apg") * c("z"))
        p.ld(9, C["wi"])
        self._addr_w()
        self.ld(0, c("v"))
        p.sti(0, 1, 0)
        self.set(c("apo"), c("z") + c("apg") * c("v"))

    def _addr_w(self) -> None:
        """I1 = the word at index R9 of the line at (lb, lm)"""
        p, C = self.p, self.L.C
        p.ld(12, C["lm"])
        p.iop(9, 9, "AND", 12)
        p.lsh(9, 9, 2)
        p.ld(12, C["lb"])
        p.iop(9, 9, "+", 12)
        p.seti(1, 9)

    def lengths(self) -> None:
        """live's lengths: trunc(max(const x scale, floor)), the first NLS by scale, the rest by sci"""
        p, C, L, c = self.p, self.L.C, self.L, self.c
        p.iconst(0, L.tables + 4 * TAB["LCON"][0])
        p.st(C["lcp"], 0)
        p.iconst(0, L.A["len"])
        p.st(C["lep"], 0)
        self.set(c("sc"), c("scale"))

        def one():
            self.ptr(3, "lcp")
            self.set(c("t1"), mx(Mv("i", 3, 0) * c("sc"), Mv("i", 3, 1)))
            self.ld(0, c("t1"))
            p.trunc(0, 0)
            self.ptr(3, "lep")
            p.sti(0, 3, 0)
            self.bump("lcp", 8)
            self.bump("lep", 4)
        p.loop(C["cnt1"], NLS, one)
        self.set(c("sc"), c("sci"))
        p.loop(C["cnt1"], NLEN - NLS, one)
        # the taps' and the input allpasses' descriptors into DM
        for name, arr in (("TDES", "tapd"), ("IDES", "iapd"), ("HDES", "hd")):
            p.iconst(9, L.tables + 4 * TAB[name][0])
            p.seti(1, 9)
            p.iconst(9, L.A[arr])
            p.seti(4, 9)
            p.loop_r(15, TAB[name][1], lambda: (p.ldpost(0, 1), p.stpost(4, 0)))

    def inaps(self) -> None:
        """the four input allpasses, x through each (gi1, gi1, gi2, gi2)"""
        p, C, L, c = self.p, self.L.C, self.L, self.c
        p.iconst(0, L.A["iapd"])
        p.st(C["dp"], 0)
        p.iconst(0, L.C["I_" + LV.IN_AP[0][0]])
        p.st(C["lep"], 0)
        self.set(c("apg"), c("gi1"))

        def one():
            self.ptr(3, "dp")
            p.ldi(0, 0, 3)
            p.st(C["lb"], 0)
            p.ldi(0, 1, 3)
            p.st(C["lm"], 0)
            self.ptr(3, "lep")
            p.ldi(0, 0, 3)
            p.st(C["dw"], 0)
            self.set(c("apx"), c("x"))
            self.rt("p_ap", self.ap_body)
            self.set(c("x"), c("apo"))
            self.bump("dp", 8)
            self.bump("lep", 4)
        p.loop(C["cnt1"], 2, one)
        self.set(c("apg"), c("gi2"))
        p.loop(C["cnt1"], 2, one)

    def taps(self) -> None:
        """y = Table 2's fourteen taps, each + or - in order (a sign's product is exact)"""
        p, C, L, c = self.p, self.L.C, self.L, self.c
        self.fz(c("y"))
        p.iconst(0, L.A["tapd"])
        p.st(C["dp"], 0)
        p.iconst(0, L.C[TAP_WORDS[0]])
        p.st(C["lep"], 0)

        def one():
            self.ptr(3, "dp")
            p.ldi(0, 0, 3)
            p.st(C["lb"], 0)
            p.ldi(0, 1, 3)
            p.st(C["lm"], 0)
            self.ptr(4, "lep")
            p.ld(9, C["wi"])
            p.ldi(10, 0, 4)
            p.iop(9, 9, "-", 10)
            self._addr_w()
            p.ldi(1, 0, 1)
            p.ldi(2, 2, 3)
            p.fop(1, 1, "*", 2)
            self.ld(0, c("y"))
            p.fop(0, 0, "+", 1)
            self.st(c("y"), 0)
            self.bump("dp", 12)
            self.bump("lep", 4)
        p.loop(C["cnt1"], len(LV.TAPS), one)

    def halves(self) -> None:
        """the tank's two halves, A then B (live.Voice.block's, in one body): side j's lines from hd,
        its lengths from len (4 j..), its state sd[3 j..], the other's end its input, its new end in ne"""
        p, C, L, c = self.p, self.L.C, self.L, self.c
        p.iconst(0, L.A["hd"])
        p.st(C["dp"], 0)
        p.iconst(0, L.A["len"])
        p.st(C["lep"], 0)
        p.ld(12, C["vba"])
        p.iconst(9, 4 * VOICE["sd"])
        p.iop(9, 9, "+", 12)
        p.st(C["sp"], 9)
        p.iconst(9, 4 * (VOICE["sd"] + 5))
        p.iop(9, 9, "+", 12)
        p.st(C["op"], 9)
        p.iconst(0, L.A["mm"])
        p.st(C["mp"], 0)
        p.iconst(0, L.A["ne"])
        p.st(C["np_"], 0)
        S = lambda j: Mv("i", 3, j)            # noqa: E731  (I3 = the side's state, set before each use)

        def desc(j):
            self.ptr(3, "dp")
            p.ldi(0, 2 * j, 3)
            p.st(C["lb"], 0)
            p.ldi(0, 2 * j + 1, 3)
            p.st(C["lm"], 0)

        def length(j):
            self.ptr(3, "lep")
            p.ldi(0, j, 3)
            p.st(C["dw"], 0)

        def one():
            desc(0)
            length(0)
            p.ld(0, C["dw"])
            p.iconst(12, 0)
            p.float_(0, 0, 12)
            self.ptr(3, "mp")
            p.ldi(1, 0, 3)
            p.fop(0, 0, "+", 1)
            self.st(c("dd"), 0)
            self.ptr(3, "op")
            self.set(c("apx"), c("x") + c("gdec") * S(0))
            self.set(c("apg"), c("gd1"))
            self.rt("p_apf", self.apf_body)
            desc(1)
            p.ld(9, C["wi"])
            self._addr_w()
            self.ld(0, c("apo"))
            p.sti(0, 1, 0)
            length(1)
            p.ld(9, C["wi"])
            p.ld(10, C["dw"])
            p.iop(9, 9, "-", 10)
            self._addr_w()
            p.ldi(0, 0, 1)
            self.st(c("t1"), 0)
            self.ptr(3, "sp")
            self.set(S(0), S(0) + c("c_dp") * (c("t1") - S(0)))
            self.set(S(1), S(1) + c("c_tl") * (S(0) - S(1)))
            self.set(c("t1"), (S(0) - S(1)) * c("gdec"))

            def driven():
                self.set(c("sx"), c("t1") * c("dg"))
                self.sat(c("sy"), c("sx"))
                self.set(c("t1"), c("sy") * c("rdg"))
            self.cmp(c("drv"), "GT", k(0.0), driven)
            desc(2)
            length(2)
            self.set(c("apx"), c("t1"))
            self.set(c("apg"), c("gd2"))
            self.rt("p_ap", self.ap_body)
            desc(3)
            p.ld(9, C["wi"])
            self._addr_w()
            self.ld(0, c("apo"))
            p.sti(0, 1, 0)
            length(3)
            p.ld(9, C["wi"])
            p.ld(10, C["dw"])
            p.iop(9, 9, "-", 10)
            self._addr_w()
            p.ldi(0, 0, 1)
            self.ptr(3, "np_")
            p.sti(0, 3, 0)
            self.bump("dp", 32)
            self.bump("lep", 16)
            self.bump("sp", 12)
            self.bump("op", -12)
            self.bump("mp", 4)
            self.bump("np_", 4)
        p.loop(C["cnt2"], 2, one)
        self.ptr(3, "sp")                     # (sp is past B's record: the ends at -4 and -1 words)
        self.ld(0, c("na"))
        p.sti(-4, 3, 0)
        self.ld(0, c("nb"))
        p.sti(-1, 3, 0)

    def apf_body(self) -> None:
        """apo = live.apf on the line at (lb, lm), delay dd (a float), of apx with apg"""
        p, C, c = self.p, self.L.C, self.c
        self.trunc_to("di", c("dd"))
        p.ld(0, C["di"])
        p.iconst(12, 0)
        p.float_(1, 0, 12)
        self.ld(0, c("dd"))
        p.fop(0, 0, "-", 1)
        self.st(c("fr"), 0)
        p.ld(9, C["wi"])
        p.ld(10, C["di"])
        p.iop(9, 9, "-", 10)
        self._addr_w()
        p.ldi(0, 0, 1)
        self.st(c("b0"), 0)
        p.ld(9, C["wi"])
        p.ld(10, C["di"])
        p.iop(9, 9, "-", 10)
        p.iconst(12, 1)
        p.iop(9, 9, "-", 12)
        self._addr_w()
        p.ldi(0, 0, 1)
        self.st(c("b1"), 0)
        self.set(c("z"), c("b0") + (c("b1") - c("b0")) * c("fr"))
        self.set(c("v"), c("apx") - c("apg") * c("z"))
        p.ld(9, C["wi"])
        self._addr_w()
        self.ld(0, c("v"))
        p.sti(0, 1, 0)
        self.set(c("apo"), c("z") + c("apg") * c("v"))

    # -- the voice's block --------------------------------------------------------------------------
    def voice(self, t: int | None) -> None:
        p, C, L = self.p, self.L.C, self.L
        V = self.V
        if p.run:
            p.iconst(9, t)
            p.st(L.t_word, 9)
        self.vbase()
        self.read_note()
        self.ld(0, V("magic"))
        p.iconst(1, MAGIC)
        p.if_(0, "NE", 1, self.fresh, kind="i")
        self.stolen_check()

        def on_trig():
            self.new_note()
            self.iset(V("on"), 1)
            self.iset(V("quiet"), 0)
            self.own()
        p.ld(0, C["trig"])
        p.ifz(0, "NE", on_trig)
        self.icmp(V("on"), "EQ", 0, self.zeros, self.owned)

    def vbase(self) -> None:
        OP.OG.vbase(self)
        self.p.st(self.L.C["vba"], 12)

    def own(self) -> None:
        """the owner word = t + 1"""
        p, L = self.p, self.L
        p.ld(9, L.t_word)
        p.iconst(12, 1)
        p.iop(9, 9, "+", 12)
        p.iconst(12, L.ddr)
        p.seti(1, 12)
        p.sti(0, 1, 9)

    def fresh(self) -> None:
        """live.Voice's fresh start: every word zero, the lines to clear, the owner, the magic"""
        p, L = self.p, self.L
        p.ld(12, L.C["vba"])
        p.seti(4, 12)
        p.iconst(5, 0)
        p.loop_r(10, VOICE_WORDS, lambda: p.stpost(4, 5), one=11)
        p.iconst(0, MAGIC)
        self.st(self.V("magic"), 0)
        self.own()

    def stolen_check(self) -> None:
        p = self.p
        self._slot_word(self.L.stolen)
        p.ldi(0, 0, 1)

        def rest():
            p.iconst(0, 0)
            p.sti(0, 1, 0)
            self.iset(self.V("on"), 0)
        p.ifz(0, "NE", rest)

    def owned(self) -> None:
        """on: the owner's voice plays (after the lines' clearing); another goes off"""
        p, L = self.p, self.L
        p.iconst(12, L.ddr)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.ld(9, L.t_word)
        p.iconst(12, 1)
        p.iop(9, 9, "+", 12)

        def other():
            self.iset(self.V("on"), 0)
            self.zeros()

        def mine():
            self.icmp(self.Vi("clr"), "LT", LV.TOTAL, self.clearing, lambda: self.rt("p_render", self.render))
        p.if_(0, "EQ", 9, mine, other, kind="i")

    def clearing(self) -> None:
        p, L = self.p, self.L
        self.ld(9, self.Vi("clr"))
        p.lsh(9, 9, 2)
        p.iconst(12, L.ddr + LINES_AT)
        p.iop(9, 9, "+", 12)
        p.seti(4, 9)
        p.iconst(5, 0)
        p.loop_r(10, LV.CHUNK, lambda: p.stpost(4, 5), one=11)
        self.ld(9, self.Vi("clr"))
        p.iconst(12, LV.CHUNK)
        p.iop(9, 9, "+", 12)
        self.st(self.Vi("clr"), 9)
        self.zeros()

    def read_knobs(self) -> None:
        """the sixteen knobs: DIGIDRUM's loop over KREC (HOLD, TUND options of two)"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, L.t_word)
        PP.t146(p, 10, 9)
        p.st(C["k146"], 10)
        p.iconst(0, NK)
        p.st(C["cnt1"], 0)
        p.iconst(0, L.tables + 4 * TAB["KREC"][0])
        p.st(C["krp"], 0)
        p.iconst(0, L.A["eff"])
        p.st(C["kep"], 0)

        def one():
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(10, 0, 3)
            p.ld(12, C["k146"])
            p.iop(10, 12, "+", 10)
            PP.half(p, 4, 0, 10)
            p.lsh(4, 4, -8)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 1, 3)
            p.iop(4, 4, "MIN", 12)
            p.ldi(12, 2, 3)

            def opt():
                p.mul_ssi(4, 4, 12)
                p.lsh(4, 4, -7)
                p.iconst(13, 1)
                p.iop(12, 12, "-", 13)
                p.iop(4, 4, "MIN", 12)
            p.ifz(12, "NE", opt)
            p.iconst(12, 0)
            p.float_(4, 4, 12)
            p.ld(12, C["kep"])
            p.seti(3, 12)
            p.sti(0, 3, 4)
            self.bump("krp", 16)
            self.bump("kep", 4)
        self.ivloop("cnt1", one)

    def read_mask(self) -> None:
        """c('mask') = the three mask records' six, six and four bits; c('mine') = the slot's track"""
        p, C, L = self.p, self.L.C, self.L
        p.iconst(0, 0)
        p.st(C["mask"], 0)
        for j, (bits_, at) in enumerate(((63, 0), (63, 6), (15, 12))):
            p.iconst(12, L.tables + 4 * (TAB["MREC"][0] + j))
            p.seti(3, 12)
            p.ldi(10, 0, 3)
            p.ld(12, C["k146"])
            p.iop(10, 12, "+", 10)
            PP.half(p, 4, 0, 10)
            p.lsh(4, 4, -8)
            p.iconst(12, bits_)
            p.iop(4, 4, "AND", 12)
            if at:
                p.lsh(4, 4, at)
            p.ld(12, C["mask"])
            p.iop(4, 4, "OR", 12)
            p.st(C["mask"], 4)
        p.ld(9, L.t_word)
        p.iop(10, 9, "+", 9)
        PP.half(p, 4, TRACK_OF, 10)
        p.st(C["mine"], 4)

    def bus(self) -> None:
        """inb = live.bus_sum: each track in the mask but the slot's own, in order, L + R"""
        p, C, L = self.p, self.L.C, self.L
        p.iconst(9, L.A["inb"])
        p.seti(4, 9)
        p.iconst(0, 0)
        p.loop_r(15, BLOCK, lambda: p.stpost(4, 0))
        p.iconst(0, 1)
        p.st(C["tbit"], 0)
        p.iconst(0, SM.TRK_BUF)
        p.st(C["tsrc"], 0)
        p.iconst(0, 0)
        p.st(C["cnt2"], 0)

        def one():
            p.ld(9, C["mask"])
            p.ld(10, C["tbit"])
            p.iop(9, 9, "AND", 10)

            def maybe():
                p.ld(9, C["cnt2"])
                p.ld(10, C["mine"])

                def add():
                    p.ld(9, C["tsrc"])
                    p.seti(1, 9)
                    p.iconst(9, L.A["inb"])
                    p.seti(4, 9)

                    def acc():
                        p.ldi(0, 0, 1)
                        p.ldi(1, 32, 1)
                        p.fop(0, 0, "+", 1)
                        p.ldi(3, 0, 4)
                        p.fop(3, 3, "+", 0)
                        p.stpost(4, 3)
                        p.ldpost(0, 1)
                    p.loop_r(15, BLOCK, acc)
                p.if_(9, "NE", 10, add, kind="i")
            p.ifz(9, "NE", maybe)
            p.ld(10, C["tbit"])
            p.iop(10, 10, "+", 10)
            p.st(C["tbit"], 10)
            p.ld(9, C["tsrc"])
            p.iconst(12, SM.TRK_STRIDE)
            p.iop(9, 12, "+", 9)
            p.st(C["tsrc"], 9)
            p.ld(9, C["cnt2"])
            p.iconst(12, 1)
            p.iop(9, 9, "+", 12)
            p.st(C["cnt2"], 9)
        p.loop(C["cnt0"], 16, one)

    def zeros(self) -> None:
        OP.OG.zeros(self)

    # -- live.Voice.block's settings, then its 32 samples -------------------------------------------------
    def render(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c, q, e = self.V, self.c, self.q, self.e
        self.read_knobs()
        self.read_mask()
        self.trunc_to("hold", e("HOLD"))
        self.trunc_to("tund", e("TUND"))

        def tuned():
            self.set(c("s"), k(LV.C8) * FP_.recip(note_hz(c("nn"))))
            self.set(c("scale"), mn(mx(c("s"), k(0.002)), k(1.0)))
        self.icmp(self.ci("tund"), "NE", 0, tuned,
                  lambda: self.set(c("scale"), k(0.02) + k(0.98) * (q("SIZE") * q("SIZE"))))
        self.set(c("sci"), mn(c("scale") * k(1.6), k(1.0)))
        self.lengths()
        self.trunc_to("pred", q("PRED") * k(LV.PRED_K))
        self.set(c("c_band"), onepole(k(200.0) * exp2f(q("BAND") * k(6.6))))
        self.set(c("c_lc"), onepole(k(10.0) * exp2f(q("LCUT") * k(9.0))))
        self.set(c("c_tl"), onepole(k(10.0) * exp2f(q("TLOW") * k(9.0))))
        self.set(c("c_dp"), onepole(k(19000.0) * exp2f(k(0.0) - q("DAMP") * k(6.6))))

        def decaying():
            self.set(c("u"), k(1.0) - q("DCAY"))
            self.set(c("gdec"), mn(k(0.1) + k(0.9) * (k(1.0) - c("u") * c("u")), k(0.9999)))
        self.icmp(self.ci("hold"), "NE", 0, lambda: self.set(c("gdec"), k(1.0)), decaying)
        self.set(c("d2"), mn(mx(c("gdec") + k(0.15), k(0.25)), k(0.5)))
        self.set(c("diff"), q("DIFF"))
        self.set(c("gi1"), k(0.75) * c("diff"))
        self.set(c("gi2"), k(0.625) * c("diff"))
        self.set(c("gd1"), k(0.0) - k(0.7) * c("diff"))
        self.set(c("gd2"), c("d2") * c("diff"))
        self.set(c("inc"), (k(0.05) * exp2f(q("MSPD") * k(8.0))) * k(float(F(F(LV.SUB) / F(LV.FS)))))
        self.set(c("exc"), (k(LV.EXCK) * c("scale")) * q("MDEP"))
        self.set(c("ph0"), V("ph"))
        self.set(c("ph1"), c("ph0") + c("inc"))
        self.cmp(c("ph1"), "GE", k(1.0), lambda: self.set(c("ph1"), c("ph1") - k(1.0)))
        self.set(c("ma"), c("exc") * (k(1.0) + sin_turns(c("ph0"))))
        self.set(c("mb"), c("exc") * (k(1.0) + sin_turns(c("ph0") + k(0.25))))
        self.set(c("dma"), ((c("exc") * (k(1.0) + sin_turns(c("ph1")))) - c("ma")) * k(LV.INV_SUB))
        self.set(c("dmb"), ((c("exc") * (k(1.0) + sin_turns(c("ph1") + k(0.25)))) - c("mb")) * k(LV.INV_SUB))
        self.set(c("ig"), q("IGN"))
        self.set(c("hig"), k(2.0) * (c("ig") * c("ig")))
        self.set(c("drv"), q("DRV"))
        self.set(c("dg"), k(1.0) + k(8.0) * (c("drv") * c("drv")))
        self.set(c("rdg"), FP_.recip(c("dg")))
        self.set(c("erly"), q("ERLY"))
        self.set(c("lev"), e("LEV") * k(LV.INV100))
        self.fz(c("peak"))
        self.fz(c("ipk"))
        self.bus()
        self.ld(0, self.Vi("wp"))
        p.st(C["wi"], 0)
        p.ld(9, L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, BUFFERS)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.st(C["outp"], 0)
        p.iconst(0, L.A["inb"])
        p.st(C["bp"], 0)
        p.loop(C["cnt0"], BLOCK, self.sample)
        self.ld(0, c("ph1"))
        self.st(V("ph"), 0)
        p.ld(0, C["wi"])
        self.st(self.Vi("wp"), 0)

        def quiet():
            self.ld(9, self.Vi("quiet"))
            p.iconst(12, 1)
            p.iop(9, 9, "+", 12)
            self.st(self.Vi("quiet"), 9)
            self.icmp(self.Vi("quiet"), "GT", LV.QUIET_BLOCKS, lambda: self.iset(V("on"), 0))
        self.cmp(c("peak"), "LT", k(LV.IDLE),
                 lambda: self.cmp(c("ipk"), "LT", k(LV.IDLE), quiet, lambda: self.iset(V("quiet"), 0)),
                 lambda: self.iset(V("quiet"), 0))

    def sample(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c = self.V, self.c

        def heard():
            self.ptr(4, "bp")
            self.set(c("x"), Mv("i", 4, 0) * c("hig"))
        self.icmp(self.ci("hold"), "NE", 0, lambda: self.fz(c("x")), heard)
        self.set(c("ipk"), mx(c("ipk"), ab(c("x"))))
        self.ld(0, c("x"))
        self.wr_from("pre", 0)

        def delayed():
            self.rd_to(0, "pre", "pred")
            self.st(c("x"), 0)
        self.icmp(self.ci("pred"), "GT", 0, delayed)
        self.set(V("lp_in"), V("lp_in") + c("c_band") * (c("x") - V("lp_in")))
        self.set(V("hp_in"), V("hp_in") + c("c_lc") * (V("lp_in") - V("hp_in")))
        self.set(c("x"), V("lp_in") - V("hp_in"))
        self.inaps()
        self.halves()
        self.taps()
        self.set(c("y"), c("y") * k(LV.OUT_K))
        self.cmp(c("erly"), "GT", k(0.0), lambda: self.set(c("y"), c("y") + c("erly") * c("x")))
        self.set(c("y"), c("y") * c("lev"))
        self.ptr(4, "outp")
        self.ld(0, c("y"))
        p.sti(0, 4, 0)
        self.set(c("peak"), mx(c("peak"), ab(c("y"))))
        self.set(c("ma"), c("ma") + c("dma"))
        self.set(c("mb"), c("mb") + c("dmb"))
        p.ld(9, C["wi"])
        p.iconst(12, 1)
        p.iop(9, 9, "+", 12)
        p.iconst(12, LV.WMASK)
        p.iop(9, 9, "AND", 12)
        p.st(C["wi"], 9)
        self.bump("bp", 4)
        self.bump("outp", 4)

    def sat(self, dst: Mv, x: Mv) -> None:
        """dst = live.sat(x)"""
        c = self.c

        def mid():
            self.set(c("x2"), x * x)
            self.set(dst, (x * (k(27.0) + c("x2"))) * FP_.recip(k(27.0) + k(9.0) * c("x2")))
        self.cmp(x, "GE", k(3.0), lambda: self.set(dst, k(1.0)),
                 lambda: self.cmp(x, "LE", k(-3.0), lambda: self.set(dst, k(-1.0)), mid))


def voice(p, L: Layout, t: int | None = None) -> PG:
    g = PG(p, L)
    saved = p.scr_on
    p.iconst(0, L.base5)
    p.seti(5, 0, "the scratch's base + WIN words")
    p.scr_on = True
    g.voice(t)
    p.scr_on = saved
    return g


def run_voice(L: Layout, read, t: int, mem=None):
    mem = mem or Mem(read)
    p = FP_.FProg("run", mem=mem)
    p.pool = {}
    p.spill = None
    p.scr = (L.scratch, L.scratch_end, L.base5)
    voice(p, L, t)
    return p, mem


def layout() -> Layout:
    from ..waverider import dsp
    return Layout(FP_.layout(), dsp.PLATEAU_TABLES_DDR, dsp.PLATEAU_DDR)
