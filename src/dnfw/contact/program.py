"""CONTACT's DSP program (machine type 27, the FX machine's phase 0: THRU): `dnfw.contact.live.block` on the
SHARC, in PERC's two-backend DSL on FASCIA's expression compiler with ORGAN's leaves, as SPALL's is. The
same calls are the assembly text and, run in Python, its exact model; test_contact_program holds the run
mode to live.block bit for bit.

**Where it runs.** Inside FASCIA's program (fascia.asm): FASCIA's walk renders a slot whose frame type word
is 27 with this, under the guard (its own call: it is never stolen, so a held effect is not lost; a block
left out is tried again the next). Its voice lives in the slot's FASCIA state.

**The block.** The sixteen knobs (KREC; SRC, EXC and BODY options); at a trig, the track claimed (OWN, a
word a track in DDR: the slot that last struck it); a voice whose track another slot has claimed goes off.
Then 32 samples from the source (IN_BUF, or SM.TRK_BUF + 0x100 k; L at +0, R at +0x80), x (g lev).
"""
from __future__ import annotations

import pathlib
import re
import struct

from ..fascia import program as FP_
from ..fascia.program import Kc, Mv, St, STRIDE, BLOCK, BUFFERS
from ..organ import program as OP
from ..organ.program import exp2f
from ..perc import program as PP
from ..perc.dsl import Mem, f32, bits
from ..sampler import machines as SM
from . import live as LV

TYPE = 27
NK = 16
MAGIC = 0x434E5421                     # 'CNT!'
TRACK_OF = 0xA5A                       # the frame's slot -> track words (as PLATEAU's)
assert BLOCK == LV.BLOCK
CTRL = LV.CONTROLS

VOICE = St().w("on", "pending", "fading")
assert [VOICE[x] for x in ("on", "pending", "fading")] == [FP_.VOICE[x] for x in ("on", "pending", "fading")]
VOICE.w("magic")
VOICE_WORDS = VOICE.n
assert 4 * VOICE_WORDS <= STRIDE

TAB = {"KREC": (0, 4 * NK)}
TABLE_WORDS = 4 * NK
OPTIONS = {"SRC": LV.NSRC, "EXC": 1, "BODY": 1}


def _krec() -> list[int]:
    from . import machines as CM
    from ..fascia import machines as FM
    out = []
    for cn in CM.CONTROLS:
        _rid, slot, lo, top = FM.SLOTS[CM.RIDES[cn]]
        assert lo == 0
        scale = 0 if top == 127 else bits(f32(254.0 / (200 if top == 100 else 240)))
        out += [168 + 2 * slot, top, OPTIONS.get(cn, 0), scale]
    return out


def tables_bytes() -> bytes:
    ws = _krec()
    assert len(ws) == TABLE_WORDS
    return struct.pack(f"<{TABLE_WORDS}I", *ws)


def write_ddr_json() -> None:
    import json
    from . import ddr
    words = [f"{x:08x}" for x in struct.unpack(f"<{TABLE_WORDS}I", tables_bytes())]
    ddr.DDR_JSON.write_text(json.dumps({"note": "generated by scripts/gen_fascia_asm.py from dnfw.contact; do not edit",
                                        "words": words}) + "\n", encoding="utf-8", newline="\n")


def k(x) -> Kc:
    return Kc(float(LV.F(x)))


_SRC = pathlib.Path(__file__).read_text(encoding="utf-8")
WORDS = tuple(sorted(set(re.findall(r'\bc\("([A-Za-z_0-9]+)"\)', _SRC))
                     | {"trig", "nn", "vv", "k146", "cnt1", "krp", "kep", "vba", "outp", "src", "mine", "sp"}))
ARRAYS = {"eff": NK}


class Layout:
    def __init__(self, fascia: FP_.Layout, tables: int, own: int):
        self.fl = fascia
        self.state, self.state2 = fascia.state, fascia.state2
        self.t_word = fascia.C["t"]
        self.stolen, self.strikes = fascia.stolen, fascia.strikes
        self.tables = tables
        self.own = own                         # 16 words (DDR): the slot that last struck each track
        at = fascia.arrays
        self.C = {}
        for name in WORDS:
            self.C[name] = at
            at += 4
        self.A = {}
        for name, n in ARRAYS.items():
            self.A[name] = at
            at += 4 * n
        self.words_end = at
        assert at <= fascia.scratch_end, (at - fascia.scratch_end, "CONTACT's words must fit in FASCIA's arrays")
        self.scratch, self.scratch_end, self.base5 = fascia.scratch, fascia.scratch_end, fascia.base5
        self.rets = fascia.rets


class CG(OP.OG):
    """FASCIA's compiler with ORGAN's leaves"""

    def c(self, name) -> Mv:
        return Mv("a", self.L.C[name])

    def V(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j)

    def Vi(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j, isint=True)

    def e(self, cn) -> Mv:
        return Mv("a", self.L.A["eff"] + 4 * CTRL.index(cn))

    def bump(self, word: str, by: int) -> None:
        p, C = self.p, self.L.C
        p.ld(13, C[word])
        p.iconst(12, by)
        p.iop(13, 12, "+", 13)
        p.st(C[word], 13)

    def ivloop(self, cnt: str, body) -> None:
        FP_.FP.ivloop(self, cnt, body)

    # -- the voice's block ---------------------------------------------------------------------------
    def voice(self, t: int | None) -> None:
        p, C, L = self.p, self.L.C, self.L
        V = self.V
        if p.run:
            p.iconst(9, t)
            p.st(L.t_word, 9)
        self.vbase()
        self.read_note()
        self.ld(0, V("magic"))
        p.iconst(1, MAGIC)
        p.if_(0, "NE", 1, self.fresh, kind="i")
        self.stolen_check()
        self.read_knobs()
        self.mine()

        def note_on():
            self.new_note()
            self.iset(V("on"), 1)
            self.own_ptr()
            p.ld(9, L.t_word)
            p.sti(0, 1, 9)                     # OWN[track] = this slot
        p.ld(0, C["trig"])
        p.ifz(0, "NE", note_on)

        def owned():
            self.own_ptr()
            p.ldi(0, 0, 1)
            p.ld(9, L.t_word)
            p.if_(0, "EQ", 9, lambda: self.rt("cn_render", self.render),
                  lambda: (self.iset(V("on"), 0), self.zeros()), kind="i")
        self.icmp(V("on"), "EQ", 0, self.zeros, owned)

    def vbase(self) -> None:
        OP.OG.vbase(self)
        self.p.st(self.L.C["vba"], 12)

    def stolen_check(self) -> None:
        p = self.p
        self._slot_word(self.L.stolen)
        p.ldi(0, 0, 1)

        def rest():
            p.iconst(0, 0)
            p.sti(0, 1, 0)
            self.iset(self.V("on"), 0)
        p.ifz(0, "NE", rest)

    def fresh(self) -> None:
        """every word zero, then the magic"""
        p, L = self.p, self.L
        p.ld(12, L.C["vba"])
        p.seti(4, 12)
        p.fconst(5, 0.0)
        p.loop_r(10, VOICE_WORDS, lambda: p.stpost(4, 5), one=11)
        p.iconst(0, MAGIC)
        self.st(self.V("magic"), 0)

    def mine(self) -> None:
        """C[mine] = the slot's track (the frame's slot -> track word, as PLATEAU's), 0..15"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, L.t_word)
        p.iop(10, 9, "+", 9)
        PP.half(p, 4, TRACK_OF, 10)
        p.iconst(12, 15)
        p.iop(4, 4, "AND", 12)
        p.st(C["mine"], 4)

    def own_ptr(self) -> None:
        """I1 = OWN + 4 track"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, C["mine"])
        p.lsh(12, 9, 2)
        p.iconst(11, L.own)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)

    def read_knobs(self) -> None:
        """the sixteen knobs: SPALL's loop over KREC (SRC, EXC and BODY options)"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, L.t_word)
        PP.t146(p, 10, 9)
        p.st(C["k146"], 10)
        p.iconst(0, NK)
        p.st(C["cnt1"], 0)
        p.iconst(0, L.tables + 4 * TAB["KREC"][0])
        p.st(C["krp"], 0)
        p.iconst(0, L.A["eff"])
        p.st(C["kep"], 0)

        def one():
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(10, 0, 3)
            p.ld(12, C["k146"])
            p.iop(10, 12, "+", 10)
            PP.half(p, 4, 0, 10)
            p.lsh(4, 4, -8)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 1, 3)
            p.iop(4, 4, "MIN", 12)
            p.ldi(5, 3, 3)

            def scaled():
                p.iconst(12, 0)
                p.float_(4, 4, 12)
                p.fop(4, 4, "*", 5)
                p.fconst(6, 0.502)
                p.fop(4, 4, "+", 6)
                p.trunc(4, 4)
            p.ifz(5, "NE", scaled)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 2, 3)

            def opt():
                p.mul_ssi(4, 4, 12)
                p.lsh(4, 4, -7)
                p.iconst(13, 1)
                p.iop(12, 12, "-", 13)
                p.iop(4, 4, "MIN", 12)
            p.ifz(12, "NE", opt)
            p.iconst(12, 0)
            p.float_(4, 4, 12)
            p.ld(12, C["kep"])
            p.seti(3, 12)
            p.sti(0, 3, 4)
            self.bump("krp", 16)
            self.bump("kep", 4)
        self.ivloop("cnt1", one)

    def zeros(self) -> None:
        OP.OG.zeros(self)

    # -- live.block ------------------------------------------------------------------------------------
    def render(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        c, e = self.c, self.e
        # the source: SRC (an option, 0..18) as an int; its block's address (C[sp]) and (cl, cr)
        self.set(c("tf"), e("SRC"))
        self.ld(0, c("tf"))
        p.trunc(0, 0)
        p.st(C["src"], 0)
        self.set(c("lev"), (e("LEV") * k(LV.INV127)) * k(LV.LEVK))
        self.set(c("gl"), k(0.0))
        self.cmp(e("GAIN"), "GT", k(0.5), lambda: self.set(c("gl"), exp2f((e("GAIN") - k(96.0)) * k(LV.GK)) * c("lev")))
        self.set(c("cl"), k(0.5))
        self.set(c("cr"), k(0.5))
        p.iconst(0, SM.IN_BUF)
        p.st(C["sp"], 0)
        p.ld(0, C["src"])
        p.iconst(12, 1)
        p.if_(0, "EQ", 12, lambda: (self.set(c("cl"), k(1.0)), self.set(c("cr"), k(0.0))), kind="i")
        p.ld(0, C["src"])
        p.iconst(12, 2)
        p.if_(0, "EQ", 12, lambda: (self.set(c("cl"), k(0.0)), self.set(c("cr"), k(1.0))), kind="i")

        def track():
            p.ld(0, C["src"])
            p.iconst(12, 3)
            p.iop(9, 0, "-", 12)               # k = SRC - 3
            p.lsh(10, 9, 8)                    # x 0x100 (SM.TRK_STRIDE)
            p.iconst(12, SM.TRK_BUF)
            p.iop(10, 12, "+", 10)
            p.st(C["sp"], 10)
            p.ld(10, C["mine"])
            p.if_(9, "EQ", 10, lambda: self.set(c("gl"), k(0.0)), kind="i")   # its own track: x 0
        p.ld(0, C["src"])
        p.iconst(12, 3)
        p.if_(0, "GE", 12, track, kind="i")
        # 32 samples: out = (L cl + R cr) gl
        p.ld(9, L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, BUFFERS)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.seti(4, 0, "the slot's buffer")
        p.ld(12, C["sp"])
        p.seti(1, 12)
        p.ld(5, C["cl"])
        p.ld(6, C["cr"])
        p.ld(7, C["gl"])

        def sample():
            p.ldi(0, 0, 1)                     # L
            p.ldi(1, 32, 1)                    # R (+0x80)
            p.fop(0, 0, "*", 5)
            p.fop(1, 1, "*", 6)
            p.fop(0, 0, "+", 1)
            p.fop(0, 0, "*", 7)
            p.stpost(4, 0)
            p.ldpost(2, 1)                     # (I1 on a word)
        p.loop_r(10, BLOCK, sample, one=11)


def voice(p, L: Layout, t: int | None = None) -> CG:
    g = CG(p, L)
    saved = p.scr_on
    p.iconst(0, L.base5)
    p.seti(5, 0, "the scratch's base + WIN words")
    p.scr_on = True
    g.voice(t)
    p.scr_on = saved
    return g


def run_voice(L: Layout, read, t: int, mem=None):
    mem = mem or Mem(read)
    p = FP_.FProg("run", mem=mem)
    p.pool = {}
    p.spill = None
    p.scr = (L.scratch, L.scratch_end, L.base5)
    voice(p, L, t)
    return p, mem


def layout() -> Layout:
    from ..waverider import dsp
    return Layout(FP_.layout(), dsp.CONTACT_TABLES_DDR, dsp.CONTACT_DDR)
