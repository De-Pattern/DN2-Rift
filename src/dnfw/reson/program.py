from ..perc import program as PP
from ..perc.dsl import Mem, f32, bits
from . import live as LV

F = np.float32
TYPE = 22
NK = len(LV.CONTROLS)
M = LV.MODES
MAGIC = LV.MAGIC
assert BLOCK == LV.SUB

# -- the voice's words (in the slot's FASCIA state) ------------------------------------------------
VOICE = St().w("on", "pending", "fading")
assert [VOICE[x] for x in ("on", "pending", "fading")] == [FP_.VOICE[x] for x in ("on", "pending", "fading")]
VOICE.w("magic", "rng", "exc", "nenv", "nlp", "note").w("y1", n=M).w("y2", n=M)
VOICE_WORDS = VOICE.n
assert VOICE.n < FP_.VOICE["FO"] + FP_.FORM["wetok"]          # fascia.program.off's other word is past ours
assert 4 * VOICE_WORDS <= STRIDE

# -- the tables (DDR) ----------------------------------------------------------------------------
TAB = {"KREC": (0, 4 * NK)}
TAB["ANCH"] = (TAB["KREC"][1], 3 * M)
TABLE_WORDS = TAB["ANCH"][0] + TAB["ANCH"][1]


def _krec() -> list[int]:
    from . import machines as RM
    from ..fascia import machines as FM
    out = []
    for cn in LV.CONTROLS:
        _rid, slot, lo, top = FM.SLOTS[RM.RIDES[cn]]
        assert lo == 0
        scale = 0 if top == 127 else bits(f32(254.0 / (200 if top == 100 else 240)))
        out += [168 + 2 * slot, top, 0, scale]
    return out


def tables_bytes() -> bytes:
    ws = _krec() + [bits(f32(float(x))) for x in LV.ANCH.reshape(-1)]
    assert len(ws) == TABLE_WORDS
    return struct.pack(f"<{TABLE_WORDS}I", *ws)


def write_ddr_json() -> None:
    import json
    from . import ddr
    words = [f"{w:08x}" for w in struct.unpack(f"<{TABLE_WORDS}I", tables_bytes())]
    ddr.DDR_JSON.write_text(json.dumps({"note": "generated by scripts/gen_fascia_asm.py from dnfw.reson.live; do not edit",
                                        "words": words}) + "\n", encoding="utf-8", newline="\n")


def k(x) -> Kc:
    return Kc(float(F(x)))


# -- the block's words (FASCIA's transient arrays): every c("...") of this file -----------------
_SRC = pathlib.Path(__file__).read_text(encoding="utf-8")
WORDS = tuple(sorted(set(re.findall(r'\bc\("([A-Za-z_0-9]+)"\)', _SRC)) | set(re.findall(r'\bci\("([A-Za-z_0-9]+)"\)', _SRC))
                     | set(re.findall(r'\bC\["([A-Za-z_0-9]+)"\]', _SRC))
                     | {"trig", "nn", "k146", "tmp0", "tmp1", "cnt0", "cnt1", "cnt2", "krp", "kep", "vba", "outp"}))
ARRAYS = {"eff": NK, "ex": BLOCK, "acc": BLOCK, "mc": 3 * M}


class Layout:
    def __init__(self, fascia: FP_.Layout, tables: int):
        self.fl = fascia
        self.state, self.state2 = fascia.state, fascia.state2
        self.t_word = fascia.C["t"]
        self.stolen, self.strikes = fascia.stolen, fascia.strikes
        self.tables = tables
        at = fascia.arrays
        self.C = {}
        for name in WORDS:
            self.C[name] = at
            at += 4
        self.A = {}
        for name, n in ARRAYS.items():
            self.A[name] = at
            at += 4 * n
        self.words_end = at
        assert at <= fascia.scratch_end, (at - fascia.scratch_end, "RESONATOR's words must fit in FASCIA's arrays")
        self.scratch, self.scratch_end, self.base5 = fascia.scratch, fascia.scratch_end, fascia.base5
        self.rets = fascia.rets


RLEAF = {"rbi": _xs_leaf("rbi", 2, VOICE["rng"], "bi")}


def u_bi() -> E:
    return Fn("rbi", Kc(0.0))


INV12 = float(LV.INV12)
TWO_PI_DT = float(F(F(6.28318530717958647692) * LV.DT))
HALF_ROOM = float(F(F(0.5) / LV.KNEE_ROOM))
INV24 = float(F(1.0 / 24.0))


class RG(OP.OG):
    """FASCIA's compiler with ORGAN's leaves and RESONATOR's noise"""

    def c(self, name) -> Mv:
        return Mv("a", self.L.C[name])

    def call_at(self, name: str, r: int) -> None:
        if name not in RLEAF:
            return super().call_at(name, r)
        p = self.p
        if r == 0:
            RLEAF[name](self)
            return
        p.fpass(r + 1, 0)
        p.fpass(0, r)
        RLEAF[name](self)
        p.fpass(r, 0)
        p.fpass(0, r + 1)

    def V(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j)

    def a(self, arr, j) -> Mv:
        return Mv("a", self.L.A[arr] + 4 * j)

    def bump(self, word: str, by: int) -> None:
        p, C = self.p, self.L.C
        p.ld(13, C[word])
        p.iconst(12, by)
        p.iop(13, 12, "+", 13)
        p.st(C[word], 13)

    def ptr(self, ireg: int, word: str) -> None:
        self.p.ld(12, self.L.C[word])
        self.p.seti(ireg, 12)

    def ivloop(self, cnt: str, body) -> None:
        FP_.FP.ivloop(self, cnt, body)

    # -- the voice's block ----------------------------------------------------------------------
    def voice(self, t: int | None) -> None:
        p, C, L = self.p, self.L.C, self.L
        V = self.V
        if p.run:
            p.iconst(9, t)
            p.st(L.t_word, 9)
        self.vbase()
        self.read_note()
        self.ld(0, V("magic"))
        p.iconst(1, MAGIC)
        p.if_(0, "NE", 1, self.fresh, kind="i")
        self.stolen_check()

        def note_on():
            self.new_note()
            self.iset(V("on"), 1)
            self.iset(V("exc"), 0)
            p.fconst(0, 1.0)
            self.st(V("nenv"), 0)
            self.fz(V("nlp"))
            p.ld(0, C["nn"])
            self.st(V("note"), 0)
        p.ld(0, C["trig"])
        p.ifz(0, "NE", note_on)
        self.icmp(V("on"), "EQ", 0, self.zeros, lambda: (self.read_knobs(), self.rt("r_render", self.render)))

    def vbase(self) -> None:
        OP.OG.vbase(self)
        self.p.st(self.L.C["vba"], 12)

    def stolen_check(self) -> None:
        """the guard left this voice out twice in one note (perc.guard.around): it rests"""
        p = self.p
        self._slot_word(self.L.stolen)
        p.ldi(0, 0, 1)

        def rest():
            p.iconst(0, 0)
            p.sti(0, 1, 0)
            self.iset(self.V("on"), 0)
        p.ifz(0, "NE", rest)

    def fresh(self) -> None:
        """live.Voice(t): every word zero, the noise's seed 0x2545F491 + t, the magic"""
        p, L = self.p, self.L
        p.ld(12, L.C["vba"])
        p.seti(4, 12)
        p.fconst(5, 0.0)
        p.loop_r(10, VOICE_WORDS, lambda: p.stpost(4, 5), one=11)
        p.ld(9, L.t_word)
        p.iconst(12, 0x2545F491)
        p.iop(0, 9, "+", 12)
        self.st(self.V("rng"), 0)
        p.iconst(0, MAGIC)
        self.st(self.V("magic"), 0)

    def read_knobs(self) -> None:
        """the eight knobs (organ.live.knob_of): SILT's loop over KREC"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, L.t_word)
        PP.t146(p, 10, 9)
        p.st(C["k146"], 10)
        p.iconst(0, NK)
        p.st(C["cnt1"], 0)
        p.iconst(0, L.tables + 4 * TAB["KREC"][0])
        p.st(C["krp"], 0)
        p.iconst(0, L.A["eff"])
        p.st(C["kep"], 0)

        def one():
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(10, 0, 3)
            p.ld(12, C["k146"])
            p.iop(10, 12, "+", 10)
            PP.half(p, 4, 0, 10)
            p.lsh(4, 4, -8)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 1, 3)
            p.iop(4, 4, "MIN", 12)
            p.ldi(5, 3, 3)

            def scaled():
                p.iconst(12, 0)
                p.float_(4, 4, 12)
                p.fop(4, 4, "*", 5)
                p.fconst(6, 0.502)
                p.fop(4, 4, "+", 6)
                p.trunc(4, 4)
            p.ifz(5, "NE", scaled)
            p.iconst(12, 0)
            p.float_(4, 4, 12)
            p.ld(12, C["kep"])
            p.seti(3, 12)
            p.sti(0, 3, 4)
            self.bump("krp", 16)
            self.bump("kep", 4)
        self.ivloop("cnt1", one)

    def zeros(self) -> None:
        OP.OG.zeros(self)

    # -- live.Voice.block, when on ----------------------------------------------------------------
    def render(self) -> None:
        self.controls()
        self.exciter()
        self.coefs()
        self.modes()
        self.output()

    def controls(self) -> None:
        """live.controls"""
        p, C, L = self.p, self.L.C, self.L
        c, e = self.c, lambda j: self.a("eff", j)
        self.set(c("pitch"), mn(mx(self.V("note") + (e(0) - k(64.0)), k(0.0)), k(127.0)))
        self.set(c("st"), e(2) * k(LV.INV127))
        self.set(c("b"), k(0.15) + k(0.8) * (e(3) * k(LV.INV127)))
        self.set(c("kd"), e(4) * k(LV.INV127))
        self.set(c("l0"), k(LV.L_DAMP0) - c("kd") * k(LV.L_DAMP1))
        self.set(c("kexp"), (k(1.0) - c("b")) * k(1.3) + k(0.2))
        self.set(c("pos"), k(0.02) + k(0.48) * (e(5) * k(LV.INV127)))
        self.set(c("mix"), e(6) * k(LV.INV127))
        self.set(c("hit"), e(7) * k(LV.INV100))
        self.set(c("lev"), e(1) * k(LV.INV100))

        def low():
            self.set(c("frac"), c("st") * k(2.0))
            p.iconst(0, L.tables + 4 * TAB["ANCH"][0])
            p.st(C["ap"], 0)

        def high():
            self.set(c("frac"), c("st") * k(2.0) - k(1.0))
            p.iconst(0, L.tables + 4 * (TAB["ANCH"][0] + M))
            p.st(C["ap"], 0)
        self.cmp(c("st"), "LE", k(0.5), low, high)
        self.set(c("tilt_g"), k(0.6) + k(0.4) * c("b"))
        self.set(c("d"), k(1.0) - c("b"))
        self.set(c("width"), k(0.0004 * 48000) + k(0.008 * 48000) * (c("d") * c("d")))
        self.set(c("rw"), recip(c("width")))
        self.set(c("minc"), k(0.5) * c("rw"))
        self.set(c("mnorm"), mn(k(24.0) * c("rw"), k(1.0)))
        self.set(c("nlp_a"), mn(((c("b") * c("b")) * k(12000.0) + k(300.0)) * k(TWO_PI_DT), k(1.0)))

    def exciter(self) -> None:
        """live's exciter: the block's 32 samples into ex"""
        p, C, L = self.p, self.L.C, self.L
        c, V = self.c, self.V
        p.iconst(0, L.A["ex"])
        p.st(C["xp"], 0)

        def one():
            def live_():
                self.set(c("ph"), fi(V("exc")) * c("minc"))
                self.cmp(c("ph"), "LT", k(0.5), lambda: self.set(c("mal"), sin_turns(c("ph")) * c("mnorm")),
                         lambda: self.fz(c("mal")))
                self.set(c("nz"), u_bi())

                def burst():
                    self.set(c("nz"), c("nz") * V("nenv"))
                    self.set(V("nenv"), V("nenv") * k(LV.NOISE_DECAY))
                self.icmp(V("exc"), "LT", LV.NOISE_LEN, burst, lambda: self.fz(c("nz")))
                self.set(V("nlp"), V("nlp") + c("nlp_a") * (c("nz") - V("nlp")))
                self.set(c("xx"), ((k(1.0) - c("mix")) * c("mal")) + c("mix") * (k(0.5) * V("nlp")))
                self.set(c("xs"), c("xx") * c("hit"))
                self.ld(13, V("exc"))
                p.iconst(12, 1)
                p.iop(13, 12, "+", 13)
                self.st(V("exc"), 13)

            self.icmp(V("exc"), "LT", LV.EXC_END, live_, lambda: self.fz(c("xs")))
            self.ptr(4, "xp")
            self.ld(0, c("xs"))
            p.sti(0, 4, 0)
            self.bump("xp", 4)
        p.loop(C["cnt0"], BLOCK, one)

    def coefs(self) -> None:
        """live.coefs: the 24 modes' (a1, a2, b0) into mc, their count (mm), asum; a mode from the top
        on has its state cleared"""
        p, C, L = self.p, self.L.C, self.L
        c, V = self.c, self.V
        self.fz(c("asum"))
        p.fconst(0, 1.0)
        self.st(c("tilt"), 0)
        self.st(c("nf"), 0)
        self.iset(c("mm"), 0)
        self.iset(c("top"), 0)
        p.iconst(0, L.A["mc"])
        p.st(C["mp"], 0)
        p.ld(13, C["vba"])
        p.iconst(12, 4 * VOICE["y1"])
        p.iop(13, 12, "+", 13)
        p.st(C["yp"], 13)
        p.iconst(0, M)
        p.st(C["cnt2"], 0)

        def sounding():
            self.set(c("ft"), (k(440.0) * exp2f((c("q") - k(69.0)) * k(INV12))) * k(LV.DT))
            self.set(c("cw"), sin_turns(c("ft") + k(0.25)))
            self.set(c("sw"), sin_turns(c("ft")))
            self.set(c("lm"), c("l0") + c("kexp") * (c("semi") * k(INV12)))
            self.set(c("rr"), expf(k(0.0) - exp2f(c("lm"))))
            self.set(c("amp"), sin_turns((c("nf") * c("pos")) * k(0.5)) * c("tilt"))
            self.ptr(4, "mp")
            self.set(Mv("i", 4, 0), k(2.0) * (c("rr") * c("cw")))
            self.set(Mv("i", 4, 1), c("rr") * c("rr"))
            self.set(Mv("i", 4, 2), c("amp") * c("sw"))
            self.set(c("asum"), c("asum") + FP_.ab(c("amp")))
            self.set(c("tilt"), c("tilt") * c("tilt_g"))
            self.bump("mm", 1)

        def top():
            self.iset(c("top"), 1)

        def one():
            def go():
                self.ptr(3, "ap")
                self.set(c("semi"), Mv("i", 3, 0) + c("frac") * (Mv("i", 3, M) - Mv("i", 3, 0)))
                self.set(c("q"), c("pitch") + c("semi"))
                self.cmp(c("q"), "GE", k(LV.TOP_NOTE), top, sounding)

            def clear():                        # live: a mode past the top rests
                self.ptr(3, "yp")
                p.fconst(0, 0.0)
                p.sti(0, 3, 0)
                p.sti(M, 3, 0)
            self.icmp(c("top"), "EQ", 0, go)
            self.icmp(c("top"), "NE", 0, clear)
            self.bump("ap", 4)
            self.bump("mp", 12)
            self.bump("yp", 4)
            self.set(c("nf"), c("nf") + k(1.0))
        self.ivloop("cnt2", one)

    def modes(self) -> None:
        """the sounding modes' 32 samples each, summed into acc (live's mode loop)"""
        p, C, L = self.p, self.L.C, self.L
        c = self.c
        p.iconst(12, L.A["acc"])
        p.seti(4, 12)
        p.fconst(5, 0.0)
        p.loop_r(10, BLOCK, lambda: p.stpost(4, 5), one=11)

        def run():
            p.iconst(0, L.A["mc"])
            p.st(C["mp"], 0)
            p.ld(13, C["vba"])
            p.iconst(12, 4 * VOICE["y1"])
            p.iop(13, 12, "+", 13)
            p.st(C["yp"], 13)
            p.ld(0, C["mm"])
            p.st(C["cnt2"], 0)

            def one():
                self.ptr(3, "mp")
                p.ldi(2, 0, 3)                 # a1
                p.ldi(3, 1, 3)                 # a2
                p.ldi(4, 2, 3)                 # b0
                self.ptr(3, "yp")
                p.ldi(0, 0, 3)                 # y1
                p.ldi(1, M, 3)                 # y2
                p.iconst(12, L.A["ex"])
                p.seti(1, 12)
                p.iconst(12, L.A["acc"])
                p.seti(4, 12)

                def smp():
                    p.ldpost(5, 1)             # x
                    p.fop(6, 2, "*", 0)
                    p.fop(7, 3, "*", 1)
                    p.fop(6, 6, "-", 7)
                    p.fop(7, 4, "*", 5)
                    p.fop(6, 6, "+", 7)        # y
                    p.fpass(1, 0)
                    p.fpass(0, 6)
                    p.ldi(8, 0, 4)
                    p.fop(8, 8, "+", 6)
                    p.stpost(4, 8)
                p.loop_r(10, BLOCK, smp, one=11)
                self.ptr(3, "yp")
                p.sti(0, 3, 0)
                p.sti(M, 3, 1)
                self.bump("mp", 12)
                self.bump("yp", 4)
            self.ivloop("cnt2", one)
        self.icmp(c("mm"), "NE", 0, run)

    def output(self) -> None:
        """the range check, the level, PING's knee into the slot's buffer, the peak; the rest"""
        p, C, L = self.p, self.L.C, self.L
        c, V = self.c, self.V
        self.iset(c("bad"), 0)
        for j in range(BLOCK):
            self.cmp(self.a("acc", j), "GT", k(-LV.GUARD),
                     lambda j=j: self.cmp(self.a("acc", j), "LT", k(LV.GUARD), None, lambda: self.iset(c("bad"), 1)),
                     lambda: self.iset(c("bad"), 1))

        def blown():                           # live: Voice(t) again (the next block's fresh), silence
            self.iset(V("on"), 0)
            self.iset(V("magic"), 0)
            self.zeros()

        def fine():
            self.set(c("tilt_p"), exp2f((c("pitch") - k(60.0)) * k(INV24)))
            self.set(c("g"), ((c("lev") * k(LV.OUT_GAIN)) * recip(k(1.0) + k(LV.NORM) * c("asum"))) * c("tilt_p"))
            self.fz(c("peak"))
            p.ld(9, L.t_word)
            p.lsh(12, 9, 2)
            p.iconst(11, BUFFERS)
            p.iop(12, 11, "+", 12)
            p.seti(1, 12)
            p.ldi(0, 0, 1)
            p.st(C["outp"], 0)
            p.iconst(0, L.A["acc"])
            p.st(C["xp"], 0)

            def one():
                self.ptr(4, "xp")
                self.set(c("v"), Mv("i", 4, 0))
                self.set(c("o"), c("v") * c("g"))
                self.set(c("oa"), FP_.ab(c("o")))

                def bend():
                    self.set(c("ok"), mn(c("oa") - k(LV.KNEE_K), k(LV.KNEE_ROOM)))
                    self.set(c("oy"), k(LV.KNEE_K) + (c("ok") - (c("ok") * c("ok")) * k(HALF_ROOM)))
                    self.cmp(c("o"), "GT", k(0.0), lambda: self.set(c("o"), c("oy")),
                             lambda: self.set(c("o"), k(0.0) - c("oy")))
                self.cmp(c("oa"), "LE", k(LV.KNEE_K), None, bend)
                self.ptr(4, "outp")
                self.ld(0, c("o"))
                p.sti(0, 4, 0)
                self.set(c("peak"), mx(c("peak"), FP_.ab(c("v"))))
                self.bump("xp", 4)
                self.bump("outp", 4)
            p.loop(C["cnt0"], BLOCK, one)

            def rest():
                self.iset(V("on"), 0)
                p.ld(12, C["vba"])
                p.iconst(13, 4 * VOICE["y1"])
                p.iop(12, 12, "+", 13)
                p.seti(4, 12)
                p.fconst(5, 0.0)
                p.loop_r(10, 2 * M, lambda: p.stpost(4, 5), one=11)
            self.icmp(V("exc"), "GE", LV.EXC_END, lambda: self.cmp(c("peak"), "LT", k(LV.IDLE), rest))
        self.icmp(c("bad"), "NE", 0, blown, fine)


def voice(p, L: Layout, t: int | None = None) -> RG:
    g = RG(p, L)
    saved = p.scr_on
    p.iconst(0, L.base5)
    p.seti(5, 0, "the scratch's base + WIN words")
    p.scr_on = True
    g.voice(t)
    p.scr_on = saved
    return g


def run_voice(L: Layout, read, t: int, mem=None):
    mem = mem or Mem(read)
    p = FP_.FProg("run", mem=mem)
    p.pool = {}
    p.spill = None
    p.scr = (L.scratch, L.scratch_end, L.base5)
    voice(p, L, t)
    return p, mem


def layout() -> Layout:
    from ..waverider import dsp
    return Layout(FP_.layout(), dsp.RESON_TABLES_DDR)
