"""RESONATOR's DSP program (machine type 22): `dnfw.reson.live.Voice` on the SHARC, in PERC's two-backend
DSL on FASCIA's expression compiler with ORGAN's leaves (exp2f, expf, sin_turns): the same calls are the
assembly text and, run in Python, its exact model. test_reson_program holds the run mode to live.Voice
bit for bit; the SHARC runner's `reson` part holds the assembled code to the run mode.

**Where it runs.** Inside FASCIA's program (fascia.asm, `wr_fsc`), as ORGAN, SILT and LIGATURE do:
FASCIA's walk renders a slot whose frame type word is 22 with this, under the same frame guard and steal
bookkeeping. Its voice lives in the slot's FASCIA state (the life words FASCIA's first three); the walk's
type change clears its magic, so the next block is a fresh voice.

**The block.** The eight knobs (SILT's loop over KREC); the controls; the exciter's 32 samples into `ex`;
the modes' coefficients in a loop of 24 (a mode at or above note 135 ends it, its state cleared); the
sounding modes' 32 samples each, summed into `acc` (a register loop); the level, PING's knee, into the
slot's buffer. The knobs' records and the modes' anchors are in DDR (RESON_TABLES).
"""
