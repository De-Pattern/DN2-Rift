F = np.float32
TYPE = 25
NK = 16
MAGIC = 0x43545221                     # 'CTR!'
assert BLOCK == LV.BLOCK
CTRL = LV.CONTROLS

VOICE = St().w("on", "pending", "fading")
assert [VOICE[x] for x in ("on", "pending", "fading")] == [FP_.VOICE[x] for x in ("on", "pending", "fading")]
VOICE.w("magic", "px", "py", "pd", "z", "hold", "gc", "dcx", "dcy")
VOICE_WORDS = VOICE.n
assert 4 * VOICE_WORDS <= STRIDE

# -- the tables (DDR): the knobs' records, then RATIO's ratios ---------------------------------------
TAB = {"KREC": (0, 4 * NK), "RAT": (4 * NK, 16)}
TABLE_WORDS = 4 * NK + 16


def _krec() -> list[int]:
    from . import machines as CM
    from ..fascia import machines as FM
    out = []
    for cn in CM.CONTROLS:
        _rid, slot, lo, top = FM.SLOTS[CM.RIDES[cn]]
        assert lo == 0
        scale = 0 if top == 127 else bits(f32(254.0 / (200 if top == 100 else 240)))
        out += [168 + 2 * slot, top, 0, scale]          # (SURF is read as a knob: s0 = SURF / 16)
    return out


def tables_bytes() -> bytes:
    ws = _krec() + [bits(r) for r in LV.RATIOS]
    assert len(ws) == TABLE_WORDS
    return struct.pack(f"<{TABLE_WORDS}I", *ws)


def write_ddr_json() -> None:
    import json
    from . import ddr
    words = [f"{x:08x}" for x in struct.unpack(f"<{TABLE_WORDS}I", tables_bytes())]
    ddr.DDR_JSON.write_text(json.dumps({"note": "generated by scripts/gen_fascia_asm.py from dnfw.contour; do not edit",
                                        "words": words}) + "\n", encoding="utf-8", newline="\n")


def k(x) -> Kc:
    return Kc(float(F(x)))


_SRC = pathlib.Path(__file__).read_text(encoding="utf-8")
WORDS = tuple(sorted(set(re.findall(r'\bc\("([A-Za-z_0-9]+)"\)', _SRC))
                     | {"trig", "nn", "vv", "k146", "cnt0", "cnt1", "krp", "kep", "vba", "outp", "s0", "s1", "nsi"}))
ARRAYS = {"eff": NK}


class Layout:
    def __init__(self, fascia: FP_.Layout, tables: int):
        self.fl = fascia
        self.state, self.state2 = fascia.state, fascia.state2
        self.t_word = fascia.C["t"]
        self.stolen, self.strikes = fascia.stolen, fascia.strikes
        self.tables = tables
        at = fascia.arrays
        self.C = {}
        for name in WORDS:
            self.C[name] = at
            at += 4
        self.A = {}
        for name, n in ARRAYS.items():
            self.A[name] = at
            at += 4 * n
        self.words_end = at
        assert at <= fascia.scratch_end, (at - fascia.scratch_end, "CONTOUR's words must fit in FASCIA's arrays")
        self.scratch, self.scratch_end, self.base5 = fascia.scratch, fascia.scratch_end, fascia.base5
        self.rets = fascia.rets


INV12 = float(F(F(1.0) / F(12.0)))


def note_hz(n) -> E:
    return k(440.0) * OP.exp2f((n - k(69.0)) * k(INV12))


class CG(OP.OG):
    """FASCIA's compiler with ORGAN's leaves"""

    def c(self, name) -> Mv:
        return Mv("a", self.L.C[name])

    def V(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j)

    def Vi(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j, isint=True)

    def e(self, cn) -> Mv:
        return Mv("a", self.L.A["eff"] + 4 * CTRL.index(cn))

    def q(self, cn) -> E:
        return self.e(cn) * k(LV.INV127)

    def bump(self, word: str, by: int) -> None:
        p, C = self.p, self.L.C
        p.ld(13, C[word])
        p.iconst(12, by)
        p.iop(13, 12, "+", 13)
        p.st(C[word], 13)

    def ptr(self, ireg: int, word: str) -> None:
        self.p.ld(12, self.L.C[word])
        self.p.seti(ireg, 12)

    def ivloop(self, cnt: str, body) -> None:
        FP_.FP.ivloop(self, cnt, body)

    # -- the voice's block ---------------------------------------------------------------------------
    def voice(self, t: int | None) -> None:
        p, C, L = self.p, self.L.C, self.L
        V = self.V
        if p.run:
            p.iconst(9, t)
            p.st(L.t_word, 9)
        self.vbase()
        self.read_note()
        self.ld(0, V("magic"))
        p.iconst(1, MAGIC)
        p.if_(0, "NE", 1, self.fresh, kind="i")
        self.stolen_check()
        self.read_knobs()

        def note_on():
            self.new_note()
            self.iset(V("on"), 1)
            for wd in ("px", "py", "z", "hold", "gc", "dcx", "dcy"):
                self.fz(V(wd))
        p.ld(0, C["trig"])
        p.ifz(0, "NE", note_on)
        self.icmp(V("on"), "EQ", 0, self.zeros, lambda: self.rt("c_render", self.render))

    def vbase(self) -> None:
        OP.OG.vbase(self)
        self.p.st(self.L.C["vba"], 12)

    def stolen_check(self) -> None:
        p = self.p
        self._slot_word(self.L.stolen)
        p.ldi(0, 0, 1)

        def rest():
            p.iconst(0, 0)
            p.sti(0, 1, 0)
            self.iset(self.V("on"), 0)
        p.ifz(0, "NE", rest)

    def fresh(self) -> None:
        """live.Voice(): every word zero, the magic"""
        p, L = self.p, self.L
        p.ld(12, L.C["vba"])
        p.seti(4, 12)
        p.fconst(5, 0.0)
        p.loop_r(10, VOICE_WORDS, lambda: p.stpost(4, 5), one=11)
        p.iconst(0, MAGIC)
        self.st(self.V("magic"), 0)

    def read_knobs(self) -> None:
        """the sixteen knobs: DIGIDRUM's loop over KREC (no choices: SURF is a knob, / 16 a surface)"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, L.t_word)
        PP.t146(p, 10, 9)
        p.st(C["k146"], 10)
        p.iconst(0, NK)
        p.st(C["cnt1"], 0)
        p.iconst(0, L.tables + 4 * TAB["KREC"][0])
        p.st(C["krp"], 0)
        p.iconst(0, L.A["eff"])
        p.st(C["kep"], 0)

        def one():
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(10, 0, 3)
            p.ld(12, C["k146"])
            p.iop(10, 12, "+", 10)
            PP.half(p, 4, 0, 10)
            p.lsh(4, 4, -8)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 1, 3)
            p.iop(4, 4, "MIN", 12)
            p.ldi(5, 3, 3)

            def scaled():
                p.iconst(12, 0)
                p.float_(4, 4, 12)
                p.fop(4, 4, "*", 5)
                p.fconst(6, 0.502)
                p.fop(4, 4, "+", 6)
                p.trunc(4, 4)
            p.ifz(5, "NE", scaled)
            p.iconst(12, 0)
            p.float_(4, 4, 12)
            p.ld(12, C["kep"])
            p.seti(3, 12)
            p.sti(0, 3, 4)
            self.bump("krp", 16)
            self.bump("kep", 4)
        self.ivloop("cnt1", one)

    def zeros(self) -> None:
        OP.OG.zeros(self)

    # -- the surfaces: z1 = surface(s, x, y), x and y in words -----------------------------------------
    def surf(self, s: int) -> None:
        c = self.c
        x, y = c("x"), c("y")
        H, Q = k(0.5), k(0.25)
        if s == 0:
            self.set(c("z1"), sin_turns(x * H) * sin_turns(y * H + Q))
        elif s == 1:
            self.set(c("t"), frac((x + y) * k(0.75) + Q))
            self.set(c("z1"), k(4.0) * ab(c("t") - H) - k(1.0))
        elif s == 2:
            self.set(c("x2"), x * x)
            self.set(c("t3"), x * (k(4.0) * c("x2") - k(3.0)))
            self.set(c("t2"), k(2.0) * (y * y) - k(1.0))
            self.set(c("z1"), (c("t3") * c("t2")) * k(0.8))
        elif s == 3:
            self.set(c("z1"), sin_turns(x * H + k(0.35) * sin_turns(y * k(1.5))))
        elif s == 4:
            self.set(c("xo"), x + k(0.35))
            self.set(c("z1"), sin_turns((c("xo") * c("xo") + (y * y) * k(0.6)) * k(1.5)))
        elif s == 5:
            self.set(c("ea"), (sin_turns(x * H) * k(4.0)) * sin_turns(y * Q + Q))
            self.set(c("z1"), c("ea") * recip(k(1.0) + ab(c("ea"))))
        elif s == 6:
            self.set(c("z1"), sin_turns((x * y) * k(2.0) + x * k(0.75)))
        else:
            self.set(c("tx"), x * k(4.0) + H)
            self.set(c("xq"), (c("tx") - frac(c("tx"))) * Q)
            self.set(c("ty"), y * k(3.0) + H)
            self.set(c("yq"), (c("ty") - frac(c("ty"))) * k(LV.THIRD))
            self.set(c("z1"), sin_turns(c("xq") * H) * sin_turns(c("yq") * H + Q))

    def surface(self, word: str) -> None:
        """z1 = the surface whose number is in the int word WORD"""
        for s in range(8):
            self.icmp(Mv("a", self.L.C[word], isint=True), "EQ", s, lambda s=s: self.rt(f"c_s{s}", lambda: self.surf(s)))

    # -- live.Voice.block --------------------------------------------------------------------------------
    def render(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c, q, e = self.V, self.c, self.q, self.e
        H, Q = k(0.5), k(0.25)
        self.set(c("hz"), note_hz(c("nn") + (e("TUNE") - k(64.0)) * k(0.375)))
        self.set(c("ix"), c("hz") * k(LV.DT))
        # RATIO's ratio: the table's entry RATIO >> 3 (at most 15)
        self.ld(0, e("RATIO"))
        p.trunc(0, 0)
        p.lsh(0, 0, -3)
        p.iconst(12, 15)
        p.iop(0, 0, "MIN", 12)
        p.lsh(0, 0, 2)
        p.iconst(12, L.tables + 4 * TAB["RAT"][0])
        p.iop(0, 12, "+", 0)
        p.seti(3, 0)
        p.ldi(0, 0, 3)
        p.st(C["rat"], 0)
        self.set(c("iy"), c("ix") * c("rat"))
        self.set(c("sx"), q("SIZX"))
        self.set(c("sy"), q("SIZY"))
        self.set(c("cx"), (e("CNTX") - k(64.0)) * k(LV.INV64))
        self.set(c("cy"), (e("CNTY") - k(64.0)) * k(LV.INV64))
        self.set(c("rq"), q("ROT"))
        self.set(c("ca"), sin_turns(c("rq") * H + Q))
        self.set(c("sa"), sin_turns(c("rq") * H))
        self.set(c("dq"), q("DRFT"))
        self.set(c("drft"), (c("dq") * c("dq")) * k(0.6))
        # SURF: s0 = trunc(SURF / 16), s1 the next (mod 8)
        self.set(c("sf"), e("SURF") * k(0.0625))
        self.ld(0, c("sf"))
        p.trunc(0, 0)
        p.st(C["s0"], 0)
        p.iconst(12, 1)
        p.iop(0, 12, "+", 0)
        p.iconst(12, 7)
        p.iop(0, 0, "AND", 12)
        p.st(C["s1"], 0)
        self.set(c("mo"), q("MORPH"))
        self.set(c("warp"), q("WARP") * k(0.8))
        self.set(c("fold"), q("FOLD") * k(3.0))
        self.set(c("fold1"), k(1.0) + c("fold"))
        self.set(c("fm"), q("FM") * k(1.5))
        self.set(c("fb"), q("FDBK") * k(0.25))     # v0.26: FDBK's original range again (owner)
        self.ld(0, e("GRIT"))
        p.trunc(0, 0)
        p.lsh(0, 0, -3)
        p.iconst(12, 0)
        p.float_(0, 0, 12)
        p.st(C["grit"], 0)
        self.set(c("lev"), q("LEV") * k(0.8))
        p.ld(9, L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, BUFFERS)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.st(C["outp"], 0)

        # v0.20: above LV.IXREF with feedback, the feedback follows the pitch and the orbit takes
        # 2 or 4 steps a sample (live.py)
        self.set(c("nsub"), k(1.0))
        p.iconst(0, 1)
        p.st(C["nsi"], 0)

        def high():
            self.set(c("fb"), c("fb") * (c("ix") * k(LV.INV_IXREF)))
            self.set(c("nsub"), k(2.0))
            self.set(c("hn"), k(0.5))
            p.iconst(0, 2)
            p.st(C["nsi"], 0)

            def four():
                self.set(c("nsub"), k(4.0))
                self.set(c("hn"), k(0.25))
                p.iconst(0, 4)
                p.st(C["nsi"], 0)
            self.cmp(c("ix"), "GT", k(LV.IXREF2), four)
            self.set(c("ixs"), c("ix") * c("hn"))
            self.set(c("iys"), c("iy") * c("hn"))
            self.set(c("fbs"), c("fb") * c("hn"))
            self.set(c("ids"), k(LV.ID_DRIFT) * c("hn"))
        self.cmp(c("fb"), "GT", k(0.0), lambda: self.cmp(c("ix"), "GT", k(LV.IXREF), high))

        def step(ix, iy, fb, ids):
            self.set(V("px"), frac(V("px") + (ix + fb * V("z"))))
            self.set(V("py"), frac(V("py") + (iy + fb * V("z"))))
            self.set(V("pd"), frac(V("pd") + ids))
            self.set(c("dr"), c("drft") * sin_turns(V("pd")))
            self.set(c("uy"), sin_turns((V("py") + Q) + c("dr")))
            self.set(c("ux"), sin_turns((V("px") + c("fm") * c("uy")) + c("dr")))
            self.set(c("x0"), c("sx") * c("ux"))
            self.set(c("y0"), c("sy") * c("uy"))
            self.set(c("x"), (c("x0") * c("ca") - c("y0") * c("sa")) + c("cx"))
            self.set(c("y"), (c("x0") * c("sa") + c("y0") * c("ca")) + c("cy"))
            self.set(c("x"), c("x") + c("warp") * (c("y") * c("y")))
            self.surface("s0")
            self.set(c("zz"), c("z1"))

            def morph():
                self.surface("s1")
                self.set(c("zz"), c("zz") + c("mo") * (c("z1") - c("zz")))
            self.cmp(c("mo"), "GT", k(0.0), morph)
            self.cmp(c("fold"), "GT", k(0.0), lambda: self.set(c("zz"), sin_turns((c("zz") * c("fold1")) * Q)))
            self.set(V("z"), c("zz"))

        def tail():
            self.cmp(V("gc"), "GT", k(0.0), lambda: self.set(V("gc"), V("gc") - k(1.0)),
                     lambda: (self.set(V("hold"), c("zz")), self.set(V("gc"), c("grit"))))
            self.set(c("yy"), (V("hold") - V("dcx")) + k(LV.DC_R) * V("dcy"))
            self.set(V("dcx"), V("hold"))
            self.set(V("dcy"), c("yy"))
            self.set(c("y1"), c("yy") * c("lev"))
            self.ptr(4, "outp")
            self.ld(0, c("y1"))
            p.sti(0, 4, 0)
            self.bump("outp", 4)

        def one():
            step(c("ix"), c("iy"), c("fb"), k(LV.ID_DRIFT))
            tail()

        def subs():
            # for (cnt1 = nsi; cnt1; cnt1--) step(): Prog.loop's, its count from the word nsi
            p.ld(0, C["nsi"])
            p.st(C["cnt1"], 0)
            top = p.label("csub")
            p.place(top)
            while True:
                step(c("ixs"), c("iys"), c("fbs"), c("ids"))
                p.ld(0, C["cnt1"])
                p.iconst(12, 1)
                p.iop(0, 0, "-", 12)
                p.st(C["cnt1"], 0)
                if not p.run:
                    p.jump("NE", top)
                    break
                if p.r[0] == 0:
                    break

        def many():
            p.loop(C["cnt0"], BLOCK, lambda: (subs(), tail()))
        self.cmp(c("nsub"), "GT", k(1.5), many, lambda: p.loop(C["cnt0"], BLOCK, one))


def voice(p, L: Layout, t: int | None = None) -> CG:
    g = CG(p, L)
    saved = p.scr_on
    p.iconst(0, L.base5)
    p.seti(5, 0, "the scratch's base + WIN words")
    p.scr_on = True
    g.voice(t)
    p.scr_on = saved
    return g


def run_voice(L: Layout, read, t: int, mem=None):
    mem = mem or Mem(read)
    p = FP_.FProg("run", mem=mem)
    p.pool = {}
    p.spill = None
    p.scr = (L.scratch, L.scratch_end, L.base5)
    voice(p, L, t)
    return p, mem


# v0.20: a voice with feedback can take 4 steps a sample (above B4): its worst block on the unit, cycles
# (instructions + 0.95 x (4 L2 + 10 DDR)), measured in the runner (rcost holds it to this).
# RIFT v0.27 (the owner, 2026-11-25: "contour is having a very hard time playing more than 1 voice"): the
# guard expected CTR_PEAK on every block of every voice whose FDBK was up, whatever its note, so a second
# CONTOUR voice with feedback seldom fitted beside the first. Now only on the block that triggers the voice
# (the one block its last cost says nothing about), and by the steps its pitch will take: CTR_PEAK from half
# a semitone under B4 (4 steps), CTR_MID from half a semitone under B3 (2 steps), the walk's floor below
# (1 step, as a voice without feedback). On every other block the voice's own last cost x 1.25 speaks (a
# bend or an LFO across B3 or B4 mid-note is under by one step's cost for one block: inside the limit's
# P/8). The pitch here: the frame's note word and the TUNE record, never under the voice's own.
CTR_PEAK = 110_000
CTR_MID = 64_000


def guard_expect(t_word: int):
    """G.around's EXPECT for CONTOUR (the shared walk: R10 is not 0 on a block that triggers this slot):
    R9 = max(R9, CTR_MID or CTR_PEAK) on a trigger block when this slot's FDBK frame word is not 0, by the
    pitch. Keeps R8; clobbers R0, R1, R4, R10..R13, I1."""
    from ..fascia import program as FP_
    from .machines import SLOTS
    assert SLOTS["TUNE"][2] == 0 and SLOTS["TUNE"][3] == 120      # the record 0..120 is the knob 0..127

    def pitch(p):
        PP.half(p, 13, 168 + 2 * SLOTS["TUNE"][1], 11)
        p.lsh(13, 13, -8)                      # the record, 0..120: the knob is 127/120 of it, a knob step
        p.lsh(10, 13, 6)                       # 0.375 semitones: 101.6 / 256 of a semitone a record step
        p.lsh(4, 13, 5)                        # (102 here: never under)
        p.iop(10, 10, "+", 4)
        p.lsh(4, 13, 2)
        p.iop(10, 10, "+", 4)
        p.lsh(4, 13, 1)
        p.iop(13, 10, "+", 4)                  # R13 = 102 x the record
        p.ld(10, t_word)
        p.iop(10, 10, "+", 10)
        PP.half(p, 4, FP_.NOTE_OFFSET, 10)     # the note << 8 | fine
        p.iop(13, 13, "+", 4)
        p.iconst(12, 64 * 96)                  # the knob's middle
        p.e("R13 = R13 - R12;", "the pitch, 1/256 semitones")
        p.iconst(12, int(58.5 * 256))
        p.iconst(10, CTR_MID)
        p.if_(13, "GE", 12, lambda: p.iop(9, 9, "MAX", 10), kind="i")
        p.iconst(12, int(70.5 * 256))
        p.iconst(10, CTR_PEAK)
        p.if_(13, "GE", 12, lambda: p.iop(9, 9, "MAX", 10), kind="i")

    def triggered(p):
        p.ld(10, t_word)
        PP.t146(p, 11, 10)
        PP.half(p, 4, 168 + 2 * SLOTS["FDBK"][1], 11)
        p.ifz(4, "NE", lambda: pitch(p))

    def expect(p):
        p.ifz(10, "NE", lambda: triggered(p))
    return expect


