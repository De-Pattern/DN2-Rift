"""CONTOUR's DSP program (machine type 25): `dnfw.contour.live.Voice` on the SHARC, in PERC's two-backend
DSL on FASCIA's expression compiler with ORGAN's leaves (sin_turns) and FASCIA's frac, as DIGIDRUM's.
The same calls are the assembly text and, run in Python, its exact model; test_contour_program holds the
run mode to live.Voice bit for bit.

**Where it runs.** Inside FASCIA's program (fascia.asm), as ORGAN, SILT, LIGATURE and DIGIDRUM do:
FASCIA's walk renders a slot whose frame type word is 25 with this, under the same guard. Its voice
lives in the slot's FASCIA state; the walk's type change clears its magic.

**The block.** The sixteen knobs (KREC, DIGIDRUM's loop); at a trig, the voice's start; once a block,
the orbit's and the land's constants; then 32 samples: the phases, the orbit, the surface (s0, and s1
blended by MORPH: a routine each, `c_s<n>`, called with x and y in words), FOLD, GRIT, the DC blocker
and LEV, into the slot's buffer.
"""
