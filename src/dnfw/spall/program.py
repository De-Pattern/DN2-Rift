from ..perc import program as PP
from ..perc.dsl import Mem, f32, bits
from . import live as LV

F = np.float32
TYPE = 26
NK = 16
MAGIC = 0x53504C21                     # 'SPL!'
assert BLOCK == LV.BLOCK
CTRL = LV.CONTROLS

VOICE = St().w("on", "pending", "fading")
assert [VOICE[x] for x in ("on", "pending", "fading")] == [FP_.VOICE[x] for x in ("on", "pending", "fading")]
VOICE.w("magic", "rng", "seed").w("ph", n=6)
VOICE.w("clock", "env", "ek", "lp", "burst", "ticks", "scan", "age", "osc", "ra1", "ra2", "rb1", "rb2")
VOICE_WORDS = VOICE.n
assert VOICE.n < FP_.VOICE["FO"] + FP_.FORM["wetok"]
assert 4 * VOICE_WORDS <= STRIDE

TAB = {"KREC": (0, 4 * NK), "LOG2K": (4 * NK, 6)}
TABLE_WORDS = 4 * NK + 6
OPTIONS = {"TYPE": len(LV.TYPES), "ALG": len(LV.ALGS)}


def _krec() -> list[int]:
    from . import machines as SM
    from ..fascia import machines as FM
    out = []
    for cn in SM.CONTROLS:
        _rid, slot, lo, top = FM.SLOTS[SM.RIDES[cn]]
        assert lo == 0
        scale = 0 if top == 127 else bits(f32(254.0 / (200 if top == 100 else 240)))
        out += [168 + 2 * slot, top, OPTIONS.get(cn, 0), scale]
    return out


def tables_bytes() -> bytes:
    ws = _krec() + [bits(x) for x in LV.LOG2K]
    assert len(ws) == TABLE_WORDS
    return struct.pack(f"<{TABLE_WORDS}I", *ws)


def write_ddr_json() -> None:
    import json
    from . import ddr
    words = [f"{x:08x}" for x in struct.unpack(f"<{TABLE_WORDS}I", tables_bytes())]
    ddr.DDR_JSON.write_text(json.dumps({"note": "generated by scripts/gen_fascia_asm.py from dnfw.spall; do not edit",
                                        "words": words}) + "\n", encoding="utf-8", newline="\n")


def k(x) -> Kc:
    return Kc(float(F(x)))


SLEAF = {"sbi": _xs_leaf("sbi", 2, VOICE["rng"], "bi")}


def u_bi() -> E:
    return Fn("sbi", Kc(0.0))


INV12 = float(F(F(1.0) / F(12.0)))
FS = float(F(LV.FS))
LN_60DB = float(F(6.9078))


def note_hz(n) -> E:
    return k(440.0) * exp2f((n - k(69.0)) * k(INV12))


def decay(t) -> E:
    return expf(k(0.0) - recip(t * k(FS)))


def t60(t) -> E:
    return expf(k(0.0) - k(LN_60DB) * recip(t * k(FS)))


_SRC = pathlib.Path(__file__).read_text(encoding="utf-8")
WORDS = tuple(sorted(set(re.findall(r'\bc\("([A-Za-z_0-9]+)"\)', _SRC))
                     | {"trig", "nn", "vv", "k146", "cnt0", "cnt1", "krp", "kep", "vba", "outp", "ty", "alg", "oi",
                        "o1"}))
ARRAYS = {"eff": NK, "inc": 6}


class Layout:
    def __init__(self, fascia: FP_.Layout, tables: int):
        self.fl = fascia
        self.state, self.state2 = fascia.state, fascia.state2
        self.t_word = fascia.C["t"]
        self.stolen, self.strikes = fascia.stolen, fascia.strikes
        self.tables = tables
        at = fascia.arrays
        self.C = {}
        for name in WORDS:
            self.C[name] = at
            at += 4
        self.A = {}
        for name, n in ARRAYS.items():
            self.A[name] = at
            at += 4 * n
        self.words_end = at
        assert at <= fascia.scratch_end, (at - fascia.scratch_end, "SPALL's words must fit in FASCIA's arrays")
        self.scratch, self.scratch_end, self.base5 = fascia.scratch, fascia.scratch_end, fascia.base5
        self.rets = fascia.rets


class SG(OP.OG):
    """FASCIA's compiler with ORGAN's leaves and SPALL's noise"""

    def call_at(self, name: str, r: int) -> None:
        if name not in SLEAF:
            return super().call_at(name, r)
        p = self.p
        if r == 0:
            SLEAF[name](self)
            return
        p.fpass(r + 1, 0)
        p.fpass(0, r)
        SLEAF[name](self)
        p.fpass(r, 0)
        p.fpass(0, r + 1)

    def c(self, name) -> Mv:
        return Mv("a", self.L.C[name])

    def ci(self, name) -> Mv:
        return Mv("a", self.L.C[name], isint=True)

    def V(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j)

    def Vi(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j, isint=True)

    def e(self, cn) -> Mv:
        return Mv("a", self.L.A["eff"] + 4 * CTRL.index(cn))

    def q(self, cn) -> E:
        return self.e(cn) * k(LV.INV127)

    def bump(self, word: str, by: int) -> None:
        p, C = self.p, self.L.C
        p.ld(13, C[word])
        p.iconst(12, by)
        p.iop(13, 12, "+", 13)
        p.st(C[word], 13)

    def ptr(self, ireg: int, word: str) -> None:
        self.p.ld(12, self.L.C[word])
        self.p.seti(ireg, 12)

    def ivloop(self, cnt: str, body) -> None:
        FP_.FP.ivloop(self, cnt, body)

    def wrap1(self, m: Mv, e) -> None:
        self.set(m, e)
        self.cmp(m, "GE", k(1.0), lambda: self.set(m, m - k(1.0)))

    def sat(self, dst: Mv, x: Mv) -> None:
        """dst = digidrum.live.sat(x)"""
        c = self.c

        def mid():
            self.set(c("x2"), x * x)
            self.set(dst, (x * (k(27.0) + c("x2"))) * recip(k(27.0) + k(9.0) * c("x2")))
        self.cmp(x, "GE", k(3.0), lambda: self.set(dst, k(1.0)),
                 lambda: self.cmp(x, "LE", k(-3.0), lambda: self.set(dst, k(-1.0)), mid))

    def u01(self) -> E:
        return (u_bi() + k(1.0)) * k(0.5)

    # -- the voice's block ---------------------------------------------------------------------------
    def voice(self, t: int | None) -> None:
        p, C, L = self.p, self.L.C, self.L
        V = self.V
        if p.run:
            p.iconst(9, t)
            p.st(L.t_word, 9)
        self.vbase()
        self.read_note()
        self.ld(0, V("magic"))
        p.iconst(1, MAGIC)
        p.if_(0, "NE", 1, self.fresh, kind="i")
        self.stolen_check()
        self.read_knobs()

        def note_on():
            self.new_note()
            self.iset(V("on"), 1)
            self.ld(0, self.Vi("rng"))
            self.st(self.Vi("seed"), 0)
            for wd in ("clock", "burst", "ticks", "scan", "env", "lp", "ra1", "ra2", "rb1", "rb2"):
                self.fz(V(wd))
        p.ld(0, C["trig"])
        p.ifz(0, "NE", note_on)
        self.icmp(V("on"), "EQ", 0, self.zeros, lambda: self.rt("s_render", self.render))

    def vbase(self) -> None:
        OP.OG.vbase(self)
        self.p.st(self.L.C["vba"], 12)

    def stolen_check(self) -> None:
        p = self.p
        self._slot_word(self.L.stolen)
        p.ldi(0, 0, 1)

        def rest():
            p.iconst(0, 0)
            p.sti(0, 1, 0)
            self.iset(self.V("on"), 0)
        p.ifz(0, "NE", rest)

    def fresh(self) -> None:
        """live.Voice(t): every word zero, the noise's seed 0x2545F491 + t, the magic"""
        p, L = self.p, self.L
        p.ld(12, L.C["vba"])
        p.seti(4, 12)
        p.fconst(5, 0.0)
        p.loop_r(10, VOICE_WORDS, lambda: p.stpost(4, 5), one=11)
        p.ld(9, L.t_word)
        p.iconst(12, 0x2545F491)
        p.iop(0, 9, "+", 12)
        self.st(self.Vi("rng"), 0)
        self.st(self.Vi("seed"), 0)
        p.iconst(0, MAGIC)
        self.st(self.V("magic"), 0)

    def read_knobs(self) -> None:
        """the sixteen knobs: DIGIDRUM's loop over KREC (TYPE and ALG options)"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, L.t_word)
        PP.t146(p, 10, 9)
        p.st(C["k146"], 10)
        p.iconst(0, NK)
        p.st(C["cnt1"], 0)
        p.iconst(0, L.tables + 4 * TAB["KREC"][0])
        p.st(C["krp"], 0)
        p.iconst(0, L.A["eff"])
        p.st(C["kep"], 0)

        def one():
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(10, 0, 3)
            p.ld(12, C["k146"])
            p.iop(10, 12, "+", 10)
            PP.half(p, 4, 0, 10)
            p.lsh(4, 4, -8)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 1, 3)
            p.iop(4, 4, "MIN", 12)
            p.ldi(5, 3, 3)

            def scaled():
                p.iconst(12, 0)
                p.float_(4, 4, 12)
                p.fop(4, 4, "*", 5)
                p.fconst(6, 0.502)
                p.fop(4, 4, "+", 6)
                p.trunc(4, 4)
            p.ifz(5, "NE", scaled)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 2, 3)

            def opt():
                p.mul_ssi(4, 4, 12)
                p.lsh(4, 4, -7)
                p.iconst(13, 1)
                p.iop(12, 12, "-", 13)
                p.iop(4, 4, "MIN", 12)
            p.ifz(12, "NE", opt)
            p.iconst(12, 0)
            p.float_(4, 4, 12)
            p.ld(12, C["kep"])
            p.seti(3, 12)
            p.sti(0, 3, 4)
            self.bump("krp", 16)
            self.bump("kep", 4)
        self.ivloop("cnt1", one)

    def zeros(self) -> None:
        OP.OG.zeros(self)

    def to_int(self, word: str, e) -> None:
        """the int word WORD = trunc(e)"""
        p = self.p
        self.set(self.c("tf"), e)
        self.ld(0, self.c("tf"))
        p.trunc(0, 0)
        p.st(self.L.C[word], 0)

    def event(self) -> None:
        """live.Voice.event: the level, the decay, SCAN's oscillator"""
        V, c = self.V, self.c
        self.set(V("env"), self.u01() * k(0.5) + k(0.5))
        self.set(V("ek"), c("size_k"))
        self.fz(V("age"))
        self.set(V("osc"), V("scan"))
        self.set(c("sn"), V("scan") + k(1.0))
        self.cmp(c("sn"), "GE", k(6.0), lambda: self.fz(V("scan")), lambda: self.set(V("scan"), c("sn")))

    def pick(self, dst: str, which) -> None:
        """c(dst) = ph[which] (which: an int word 0..5)"""
        for j in range(6):
            self.icmp(self.ci(which), "EQ", j, lambda j=j: self.set(self.c(dst), self.V("ph", j)))

    # -- live.Voice.block --------------------------------------------------------------------------------
    def render(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c, q, e = self.V, self.c, self.q, self.e
        self.to_int("ty", e("TYPE"))
        self.to_int("alg", e("ALG"))
        self.set(c("size_k"), decay(k(0.00005) * exp2f(q("SIZE") * k(12.0))))
        self.set(c("ginc"), (k(0.25) * exp2f(q("DENS") * k(11.0))) * k(LV.DT))
        self.set(c("binc"), c("ginc") * k(LV.CLUMP_RATE))
        self.set(c("gap"), q("GAP") * k(0.95))
        self.set(c("tq"), e("CLMP") * k(0.0625))
        self.to_int("oi", c("tq"))
        self.ld(0, self.ci("oi"))
        p.iconst(12, 0)
        p.float_(0, 0, 12)
        p.st(C["nclump"], 0)
        self.set(c("tq"), e("MEM") * k(0.125))
        self.to_int("oi", c("tq"))
        self.ld(0, self.ci("oi"))
        p.iconst(12, 0)
        p.float_(0, 0, 12)
        p.st(C["mem"], 0)
        self.set(c("edge"), exp2f((q("EDGE") - k(1.0)) * k(8.0)))
        self.set(c("base"), note_hz(c("nn") + (e("TUNE") - k(64.0)) * k(0.375)) * k(LV.DT))
        self.set(c("ex"), k(1.0) + q("SPRD") * k(1.5))
        for j in range(6):
            inc = Mv("a", L.A["inc"] + 4 * j)
            self.set(inc, mn(c("base") * exp2f(k(LV.LOG2K[j]) * c("ex")), k(LV.OSC_MAX)))
        self.set(c("rr"), t60(k(0.005) * exp2f(q("RING") * k(10.0))))
        self.set(c("r2"), c("rr") * c("rr"))
        for nm, kn in (("a", "FRQA"), ("b", "FRQB")):
            self.set(c("w"), (k(30.0) * exp2f(q(kn) * k(9.0))) * k(LV.DT))
            self.set(c("c" + nm), (k(2.0) * c("rr")) * sin_turns(c("w") + k(0.25)))
            self.set(c("g" + nm), sin_turns(c("w")) * k(LV.RES_GAIN))
        self.set(c("coup"), q("COUP") * k(0.9))
        self.set(c("mix"), q("MIX"))
        self.set(c("dry"), k(1.0) - c("mix"))
        self.set(c("lev"), (q("LEV") * k(1.27)) * k(LV.OUT_GAIN))
        p.ld(0, C["trig"])
        p.ifz(0, "NE", self.event)
        p.ld(9, L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, BUFFERS)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.st(C["outp"], 0)
        p.loop(C["cnt0"], BLOCK, lambda: self.rt("s_tick", self.tick))

    def tick(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c, e = self.V, self.c, self.e

        def clump():
            self.set(V("clock"), V("clock") + c("binc"))

            def fire():
                self.set(V("clock"), V("clock") - k(1.0))
                self.set(V("burst"), V("burst") - k(1.0))
                self.rt("s_event", self.event)
            self.cmp(V("clock"), "GE", k(1.0), fire)

        def free():
            def run():
                self.set(V("clock"), V("clock") + c("ginc"))

                def tick():
                    self.set(V("clock"), V("clock") - k(1.0))

                    def remember():
                        self.set(V("ticks"), V("ticks") + k(1.0))

                        def again():
                            self.fz(V("ticks"))
                            self.ld(0, self.Vi("seed"))
                            self.st(self.Vi("rng"), 0)
                        self.cmp(V("ticks"), "GE", c("mem"), again)
                    self.cmp(c("mem"), "GT", k(0.0), remember)
                    self.set(c("u"), self.u01())

                    def sound():
                        self.rt("s_event", self.event)
                        self.set(V("burst"), c("nclump"))
                    self.cmp(c("u"), "GE", c("gap"), sound)
                self.cmp(V("clock"), "GE", k(1.0), tick)
            self.cmp(e("DENS"), "GT", k(0.0), run)
        self.cmp(V("burst"), "GT", k(0.0), clump, free)
        for j in range(6):
            self.wrap1(V("ph", j), V("ph", j) + Mv("a", L.A["inc"] + 4 * j))

        # the particle into x
        def imp():
            self.fz(c("x"))
            self.cmp(V("age"), "EQ", k(0.0), lambda: self.set(c("x"), V("env")))

        def dust():
            self.set(c("x"), u_bi() * V("env"))

        def tonal():
            self.to_int("oi", V("osc"))
            self.ld(0, self.ci("oi"))
            p.iconst(12, 1)
            p.iop(1, 12, "+", 0)
            p.iconst(12, 6)
            p.if_(1, "GE", 12, lambda: p.iconst(1, 0), kind="i")
            p.st(C["o1"], 1)

            def chip():
                self.pick("pa", "oi")
                self.pick("pb", "o1")
                self.set(c("sa"), sin_turns(c("pa")))
                self.set(c("sb"), sin_turns(c("pb")))
                self.cmp(c("sa"), "GE", k(0.0), lambda: self.set(c("sa"), k(1.0)), lambda: self.set(c("sa"), k(-1.0)))
                self.cmp(c("sb"), "GE", k(0.0), lambda: self.set(c("sb"), k(1.0)), lambda: self.set(c("sb"), k(-1.0)))
                self.set(c("s"), c("sa") * c("sb"))

            def tone():
                def sum_():
                    self.fz(c("s"))
                    for j in range(6):
                        self.set(c("s"), c("s") + sin_turns(V("ph", j)))
                    self.set(c("s"), c("s") * k(LV.INV3))

                def ring():
                    self.pick("pa", "oi")
                    self.pick("pb", "o1")
                    self.set(c("s"), sin_turns(c("pa")) * sin_turns(c("pb")))

                def scan():
                    self.pick("pa", "oi")
                    self.set(c("s"), sin_turns(c("pa")))
                self.icmp(self.ci("alg"), "EQ", 0, sum_,
                          lambda: self.icmp(self.ci("alg"), "EQ", 1, ring, scan))
            self.icmp(self.ci("ty"), "EQ", 3, chip, tone)
            self.set(c("x"), (c("s") * k(LV.TONE_GAIN)) * V("env"))
        self.icmp(self.ci("ty"), "EQ", 0, imp,
                  lambda: self.icmp(self.ci("ty"), "EQ", 1, dust, lambda: self.rt("s_tonal", tonal)))
        self.set(V("env"), V("env") * V("ek"))
        self.set(V("age"), V("age") + k(1.0))
        # EDGE, the rings, the mix
        self.set(V("lp"), V("lp") + c("edge") * (c("x") - V("lp")))
        self.set(c("v"), (V("lp") + c("ca") * V("ra1")) - c("r2") * V("ra2"))
        self.set(V("ra2"), V("ra1"))
        self.set(V("ra1"), c("v"))
        self.set(c("ya"), c("v") * c("ga"))
        self.set(c("v"), ((V("lp") + c("coup") * c("ya")) + c("cb") * V("rb1")) - c("r2") * V("rb2"))
        self.set(V("rb2"), V("rb1"))
        self.set(V("rb1"), c("v"))
        self.set(c("yb"), c("v") * c("gb"))
        self.set(c("y"), (c("dry") * V("lp")) + c("mix") * (c("ya") + c("yb")))
        self.set(c("y"), c("y") * c("lev"))
        self.sat(c("y"), c("y"))
        self.set(c("y"), c("y") * k(LV.OUT_GAIN))
        self.ptr(4, "outp")
        self.ld(0, c("y"))
        p.sti(0, 4, 0)
        self.bump("outp", 4)


def voice(p, L: Layout, t: int | None = None) -> SG:
    g = SG(p, L)
    saved = p.scr_on
    p.iconst(0, L.base5)
    p.seti(5, 0, "the scratch's base + WIN words")
    p.scr_on = True
    g.voice(t)
    p.scr_on = saved
    return g


def run_voice(L: Layout, read, t: int, mem=None):
    mem = mem or Mem(read)
    p = FP_.FProg("run", mem=mem)
    p.pool = {}
    p.spill = None
    p.scr = (L.scratch, L.scratch_end, L.base5)
    voice(p, L, t)
    return p, mem


def layout() -> Layout:
    from ..waverider import dsp
    return Layout(FP_.layout(), dsp.SPALL_TABLES_DDR)
