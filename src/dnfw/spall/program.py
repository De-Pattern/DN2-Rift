"""SPALL's DSP program (machine type 26): `dnfw.spall.live.Voice` on the SHARC, in PERC's two-backend DSL on
FASCIA's expression compiler with ORGAN's leaves and DIGIDRUM's noise, as CONTOUR's and DIGIDRUM's are. The
same calls are the assembly text and, run in Python, its exact model; test_spall_program holds the run mode
to live.Voice bit for bit.

**Where it runs.** Inside FASCIA's program (fascia.asm): FASCIA's walk renders a slot whose frame type word is
26 with this, under the same guard. Its voice lives in the slot's FASCIA state; the walk's type change clears
its magic.

**The block.** The sixteen knobs (KREC; TYPE and ALG as options); at a trig, the voice's start and the first
event; once a block the clock's, the oscillators' and the rings' constants; then 32 samples (`s_tick`): the
clock, the six oscillators, the particle (a routine a type), EDGE, the two rings, the mix and LEV.
"""
