def _krec() -> list[int]:
    from ..fascia import machines as FM
    from ..organ import live as OL
    out = []
    for j, ride in enumerate(OL.RIDES):
        _rid, slot, lo, top = FM.SLOTS[ride]
        assert lo == 0
        n = LV.NP if j == 0 else 0
        scale = 0 if top == 127 else bits(f32(254.0 / (200 if top == 100 else 240)))
        out += [168 + 2 * slot, top, n, scale]
    return out


def _patch_words() -> list[int]:
    out = []
    for kk in range(LV.NP):
        rows, outb, bm = LV.patch_rows(kk)
        for (ty, sa, aa, sb, ab, d1, d2) in rows:
            out += [ty, sa, sb, bits(f32(F(aa) * F(0.01))), bits(f32(F(ab) * F(0.01))),
                    bits(f32(float(d1))), bits(f32(float(d2))), 0]
        out += [outb - 1, bm]
    return out


def tables_bytes() -> bytes:
    vals = _krec() + [bits(f32(float(x))) for x in LV.RATIO] + _patch_words()
    assert len(vals) == TABLE_WORDS
    return struct.pack(f"<{len(vals)}I", *vals)


