"""LIGATURE's DSP program (machine type 21): `dnfw.ligature.live.SlotVoice` on the SHARC, in PERC's
two-backend DSL on FASCIA's expression compiler with ORGAN's leaves (exp2f, sin_turns, sinf): the same
calls are the assembly text and, run in Python, its exact model. test_ligature_program holds the run
mode to live.SlotVoice bit for bit; the SHARC runner's `ligature` part holds the assembled code to the
run mode.

**Where it runs.** Inside FASCIA's program (fascia.asm, `wr_fsc`), as ORGAN and SILT do: FASCIA's walk
renders a slot whose frame type word is 21 with this, under the same frame guard and steal bookkeeping.
Its voice lives in the slot's FASCIA state (the life words FASCIA's first three); the walk's type change
clears its magic, so the next block is a fresh voice.

**The voice** is live.Voice. Each block (of the patch's 12) runs its 32 samples in turn: its inputs A
and B are first copied, times their amounts, into the scratch arrays `ain` and `bin` (with TRIG's in
`tg`), then its kernel (a routine per kind of block) reads them sample by sample and writes the block's
buffer in the voice (12 x 32 words): a cord from a block not yet run this block reads what that block
made the block before. The patch table, the knobs' records and the ratios are in DDR (LIG_TABLES).
"""
