def k(x) -> Kc:
    return Kc(float(F(x)))


def _lsh_by(p, d: int, s: int) -> None:
    """Rd = LSHIFT Rd BY Rs, Rs either sign (a negative count shifts right, logically)"""
    p.e(f"R{d} = LSHIFT R{d} BY R{s};")
    if p.run:
        n = p.r[s] & 0xFF
        n = n - 256 if n >= 128 else n
        x = p.r[d] & 0xFFFFFFFF
        p.setR(d, (x << n if n < 32 else 0) if n >= 0 else (x >> -n if -n < 32 else 0))


