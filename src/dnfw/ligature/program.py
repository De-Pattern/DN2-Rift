class Layout:
    def __init__(self, fascia: FP_.Layout, tables: int):
        self.fl = fascia
        self.state, self.state2 = fascia.state, fascia.state2
        self.t_word = fascia.C["t"]
        self.stolen, self.strikes = fascia.stolen, fascia.strikes
        self.tables = tables
        at = fascia.arrays
        self.C = {}
        for name in WORDS:
            if name in ("tanh_x", "tanh_n"):
                continue
            self.C[name] = at
            at += 4
        for name in ("tanh_x", "tanh_n"):      # FASCIA's leaves' own words
            self.C[name] = fascia.C[name]
        self.A = {}
        for name, n in ARRAYS.items():
            self.A[name] = at
            at += 4 * n
        self.words_end = at
        assert at <= fascia.scratch_end, (at - fascia.scratch_end, "LIGATURE's words must fit in FASCIA's arrays")
        self.scratch, self.scratch_end, self.base5 = fascia.scratch, fascia.scratch_end, fascia.base5
        self.rets = fascia.rets


LLEAF = {"lnz": _xs_leaf("lnz", 2, VOICE["rng"], "u01"),
         "lrg": _xs_leaf("lrg", 2, VOICE["rng2"], "u01")}


def u_nz() -> E:
    return Fn("lnz", Kc(0.0))


def u_rg() -> E:
    return Fn("lrg", Kc(0.0))


class LG(OP.OG):
    """FASCIA's compiler with ORGAN's leaves and LIGATURE's"""

    def c(self, name) -> Mv:
        return Mv("a", self.L.C[name])

    def call_at(self, name: str, r: int) -> None:
        if name not in LLEAF:
            return super().call_at(name, r)
        p = self.p
        if r == 0:
            LLEAF[name](self)
            return
        p.fpass(r + 1, 0)
        p.fpass(0, r)
        LLEAF[name](self)
        p.fpass(r, 0)
        p.fpass(0, r + 1)

    def V(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j)

    def B(self, name) -> Mv:
        """the running block's word (I3 = its words in the voice)"""
        return Mv("i", 3, BOFF[name])

    def a(self, arr, j) -> Mv:
        return Mv("a", self.L.A[arr] + 4 * j)

    # the sample's words: I4 = ain + 4 j (bin and tg follow it), I0 = the block's buffer + 4 j
    def A_(self) -> Mv:
        return Mv("i", 4, 0)

    def B_(self) -> Mv:
        return Mv("i", 4, BLOCK)

    def TG(self) -> Mv:
        return Mv("i", 4, 2 * BLOCK)

    def ivloop(self, cnt: str, body) -> None:
        FP_.FP.ivloop(self, cnt, body)

    def tabw(self, d: int, word: str, base_word: str, off: int) -> None:
        """Rd = DM(table word at C[base_word] + 4 off), I1"""
        p = self.p
        p.ld(12, self.L.C[base_word])
        p.iconst(13, 4 * off)
        p.iop(12, 12, "+", 13)
        p.seti(1, 12)
        p.ldi(d, 0, 1)

    def bump(self, word: str, by: int) -> None:
        p, C = self.p, self.L.C
        p.ld(13, C[word])
        p.iconst(12, by)
        p.iop(13, 12, "+", 13)
        p.st(C[word], 13)

    def samples(self, body) -> None:
        """BODY for each of the block's 32 samples, with I4 and I0 set (the pointer words sp, yp)"""
        p, C = self.p, self.L.C

        def one():
            p.ld(12, C["sp"])
            p.seti(4, 12)
            p.ld(12, C["yp"])
            p.seti(0, 12)
            body()
            self.bump("sp", 4)
            self.bump("yp", 4)
            p.ld(9, C["jj"])
            p.iconst(12, 1)
            p.iop(9, 9, "+", 12)
            p.st(C["jj"], 9)
        p.iconst(0, self.L.A["ain"])
        p.st(C["sp"], 0)
        p.ld(0, C["ybuf"])
        p.st(C["yp"], 0)
        p.iconst(0, 0)
        p.st(C["jj"], 0)
        p.loop(C["cnt0"], BLOCK, one)

    def out_(self, e) -> None:
        """the sample's output (I0)"""
        self.ev(w(e), 0)
        self.p.sti(0, 0, 0)

    def out_w(self, m: Mv) -> None:
        self.ld(0, m)
        self.p.sti(0, 0, 0)

    def clamp(self, m: Mv, lo: float, hi: float) -> None:
        """live.clampf(m, lo, hi) in place"""
        self.cmp(m, "LT", k(lo), lambda: self.set(m, k(lo)),
                 lambda: self.cmp(m, "GT", k(hi), lambda: self.set(m, k(hi))))

    def rise(self, x: E, prev: Mv, thr: E) -> None:
        """c('e') = x > thr and prev <= thr; prev = x"""
        c = self.c
        self.set(c("rx"), x)
        self.iset(c("e"), 0)
        self.cmp(c("rx"), "GT", thr, lambda: self.cmp(prev, "LE", thr, lambda: self.iset(c("e"), 1)))
        self.set(prev, c("rx"))

    def wrap(self, m: Mv) -> None:
        """live.wwrap, in place"""
        p, c = self.p, self.c

        def floor_sub():
            self.ld(0, m)
            p.fpass(15, 0)
            OP._floor_f(p, 15, 14)
            p.fop(0, 0, "-", 14)
            self.st(m, 0)

        def hi():
            self.set(m, m - k(1.0))
            self.cmp(m, "GE", k(1.0), floor_sub)

        def lo():
            self.set(m, m + k(1.0))
            self.cmp(m, "LT", k(0.0), floor_sub)
        self.cmp(m, "GE", k(1.0), hi, lambda: self.cmp(m, "LT", k(0.0), lo))

    def wn(self, dst: str, x: E, n: int) -> None:
        """the int word dst = live.WN(x, n)"""
        p = self.p
        self.ev(w(x) * k(127.0) + k(0.5), 0)
        p.trunc(0, 0)
        p.iconst(12, 0)
        p.iop(0, 0, "MAX", 12)
        p.iconst(12, n - 1)
        p.iop(0, 0, "MIN", 12)
        p.st(self.L.C[dst], 0)

    def wk(self, dst: str, T: E) -> None:
        """c(dst) = live.wk(T)"""
        c = self.c
        self.set(c("wt"), T)
        self.cmp(c("wt"), "LE", k(1e-5), lambda: self.set(c("wt"), k(1e-5)))
        self.set(c(dst), k(1.0) - expf(k(-LV.DT) * recip(c("wt"))))

    def wtime(self, x: E) -> E:
        return k(0.0005) * exp2f(w(x) * k(14.0))

    def sat(self, dst: str, x: E) -> None:
        """c(dst) = live.sat(x) (a routine on sx)"""
        c = self.c
        self.set(c("sx"), x)
        self.rt("l_sat", self.sat_body)
        self.set(c(dst), c("sy"))

    def sat_body(self) -> None:
        c = self.c

        def mid():
            self.cmp(c("sx"), "LT", k(-3.0), lambda: self.set(c("sy"), k(-1.0)), mid2)

        def mid2():
            self.set(c("sx2"), c("sx") * c("sx"))
            self.set(c("sy"), (c("sx") * (k(27.0) + c("sx2"))) * recip(k(27.0) + k(9.0) * c("sx2")))
        self.cmp(c("sx"), "GT", k(3.0), lambda: self.set(c("sy"), k(1.0)), mid)

    # -- the voice's block ----------------------------------------------------------------------
    def voice(self, t: int | None) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c = self.V, self.c
        if p.run:
            p.iconst(9, t)
            p.st(L.t_word, 9)
        self.vbase()
        self.read_note()
        p.ld(0, OFF_WORD)
        p.iconst(1, 1)
        p.ld(9, L.t_word)
        PP._shift_by(p, 1, 9)
        p.iop(0, 0, "AND", 1)
        p.st(C["off"], 0)
        self.read_knobs()
        self.ld(0, V("magic"))
        p.iconst(1, MAGIC)
        p.if_(0, "NE", 1, self.fresh, kind="i")
        self.stolen_check()
        # the LFOs: a sine each, 0.05 .. 25 Hz, moving whether a note plays or not
        for q in range(2):
            self.set(c("hzq"), k(0.05) * exp2f((self.a("eff", 3 + q) * k(LV.INV127)) * k(9.0)))
            self.set(V(f"lfo{q}"), V(f"lfo{q}") + (c("hzq") * k(LV.DT)) * k(float(BLOCK)))
            self.wrap(V(f"lfo{q}"))

        def note_on():
            self.new_note()
            p.ld(9, L.t_word)
            p.iop(10, 9, "+", 9)
            PP.half(p, 4, FP_.VEL_OFFSET, 10)
            p.lsh(4, 4, -8)
            p.iconst(12, 127)
            p.iop(4, 4, "MIN", 12)
            p.iconst(12, 0)
            p.float_(4, 4, 12)
            p.fconst(5, float(LV.INV127))
            p.fop(4, 4, "*", 5)
            p.st(C["tvel"], 4)
            self.icmp(V("on"), "EQ", 0, self.reset)
            self.iset(V("on"), 1)
            self.iset(V("trig"), 1)
            p.fconst(0, 1.0)
            self.st(V("gate"), 0)
            p.ld(0, C["nn"])
            self.st(V("note"), 0)
            p.ld(0, C["tvel"])
            self.st(V("vel"), 0)
            self.iset(V("quiet"), 0)
        p.ld(0, C["trig"])
        p.ifz(0, "NE", note_on)
        p.ld(0, C["off"])
        p.ifz(0, "NE", lambda: self.fz(V("gate")))

        def silent():
            self.iset(V("trig"), 0)
            self.zeros()
        self.icmp(V("on"), "EQ", 0, silent, lambda: self.rt("l_render", self.render))

    def vbase(self) -> None:
        OP.OG.vbase(self)
        self.p.st(self.L.C["vba"], 12)

    def stolen_check(self) -> None:
        """the guard left this voice out twice in one note (perc.guard.around): it rests"""
        p = self.p
        self._slot_word(self.L.stolen)
        p.ldi(0, 0, 1)

        def rest():
            p.iconst(0, 0)
            p.sti(0, 1, 0)
            self.iset(self.V("on"), 0)
        p.ifz(0, "NE", rest)

    def fresh(self) -> None:
        """live.SlotVoice(t): every word zero, the seeds, lastp -1"""
        p, L = self.p, self.L
        V = self.V
        p.ld(12, self.L.C["vba"])
        p.seti(4, 12)
        p.fconst(5, 0.0)
        p.loop_r(10, VOICE_WORDS, lambda: p.stpost(4, 5), one=11)
        # seed = 0x6c696700 + 0x01000193 (t + 1); rng2 = seed ^ 0x5bd1e995, or 1
        p.ld(9, L.t_word)
        p.iconst(12, 1)
        p.iop(9, 9, "+", 12)
        p.iconst(12, 0x01000193)
        p.mul_ssi(0, 9, 12)
        p.ipass(8, 0)
        p.iconst(12, 0x6C696700)
        p.iop(0, 8, "+", 12)
        self.st(V("rng"), 0)
        p.iconst(12, 0x5BD1E995)
        p.ipass(1, 0)
        # xor = (a OR b) - (a AND b)
        p.iop(2, 1, "AND", 12)
        p.iop(1, 1, "OR", 12)
        p.iop(1, 1, "-", 2)
        p.ifz(1, "EQ", lambda: p.iconst(1, 1))
        self.st(V("rng2"), 1)
        p.iconst(0, -1)
        self.st(V("lastp"), 0)
        p.iconst(0, MAGIC)
        self.st(V("magic"), 0)

    def reset(self) -> None:
        """live.Voice.reset: the blocks' words and buffers zero"""
        p = self.p
        p.ld(12, self.L.C["vba"])
        p.iconst(13, 4 * VOICE["blk"])
        p.iop(12, 12, "+", 13)
        p.seti(4, 12)
        p.fconst(5, 0.0)
        p.loop_r(10, NB * BSTRIDE + NB * BLOCK, lambda: p.stpost(4, 5), one=11)

    def read_knobs(self) -> None:
        """the 32 knobs (organ.live.knob_of), PATCH as its patch ((k NP) >> 7): SILT's loop over KREC"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, L.t_word)
        PP.t146(p, 10, 9)
        p.st(C["k146"], 10)
        p.iconst(0, NK)
        p.st(C["cnt1"], 0)
        p.iconst(0, L.tables + 4 * TAB["KREC"][0])
        p.st(C["krp"], 0)
        p.iconst(0, L.A["eff"])
        p.st(C["kep"], 0)

        def one():
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(10, 0, 3)
            p.ld(12, C["k146"])
            p.iop(10, 12, "+", 10)
            PP.half(p, 4, 0, 10)
            p.lsh(4, 4, -8)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 1, 3)
            p.iop(4, 4, "MIN", 12)
            p.ldi(5, 3, 3)

            def scaled():
                p.iconst(12, 0)
                p.float_(4, 4, 12)
                p.fop(4, 4, "*", 5)
                p.fconst(6, 0.502)
                p.fop(4, 4, "+", 6)
                p.trunc(4, 4)
            p.ifz(5, "NE", scaled)
            p.ld(12, C["krp"])
            p.seti(3, 12)
            p.ldi(12, 2, 3)

            def opt():
                p.mul_ssi(4, 4, 12)
                p.lsh(4, 4, -7)
                p.iconst(13, 1)
                p.iop(12, 12, "-", 13)
                p.iop(4, 4, "MIN", 12)
            p.ifz(12, "NE", opt)
            p.iconst(12, 0)
            p.float_(4, 4, 12)
            p.ld(12, C["kep"])
            p.seti(3, 12)
            p.sti(0, 3, 4)
            self.bump("krp", 16)
            self.bump("kep", 4)
        self.ivloop("cnt1", one)

    def zeros(self) -> None:
        OP.OG.zeros(self)

    # -- live.Voice.block, when on ----------------------------------------------------------------
    def render(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c = self.V, self.c
        # the patch (eff[0] is its number already), and a new one starts clean
        self.ev(self.a("eff", 0), 0)
        p.trunc(0, 0)
        p.st(C["pk"], 0)
        self.ld(1, V("lastp"))
        p.if_(0, "NE", 1, lambda: (self.icmp(V("lastp"), "GE", 0, self.reset),
                                   p.ld(0, C["pk"]), self.st(V("lastp"), 0)), kind="i")
        # the patch's table: tables + 4 (PATCH + PROW pk)
        p.ld(0, C["pk"])
        p.iconst(12, PROW)
        p.mul_ssi(0, 0, 12)
        p.lsh(0, 0, 2)
        p.ipass(8, 0)
        p.iconst(12, L.tables + 4 * TAB["PATCH"][0])
        p.iop(0, 8, "+", 12)
        p.st(C["prow"], 0)
        # TUNE, FINE, the note, hz
        self.set(c("tune"), (self.a("eff", 1) - k(64.0)) * k(24.0 / 63.0))
        self.set(c("fine"), (self.a("eff", 2) - k(64.0)) * k(50.0 / 63.0))
        self.set(c("nn2"), (V("note") + c("tune")) + c("fine") * k(0.01))
        self.set(c("hz"), k(440.0) * exp2f((c("nn2") - k(69.0)) * k(1.0 / 12.0)))
        self.cmp(c("hz"), "GE", k(12000.0), lambda: self.set(c("hz"), k(12000.0)))
        # the sources
        self.set(c("spitch"), ((V("note") + c("tune")) - k(60.0)) * k(1.0 / 48.0))
        self.set(c("slfo1"), sin_turns(V("lfo0")))
        self.set(c("slfo2"), sin_turns(V("lfo1")))
        for j in range(BLOCK):
            self.set(self.a("nz", j), u_nz() * k(2.0) - k(1.0))
        # the blocks
        p.iconst(0, 0)
        p.st(C["bi"], 0)
        p.iconst(0, NB)
        p.st(C["cnt2"], 0)

        def one():
            self.block_i()
            self.bump("prow", 4 * ROW)
            p.ld(9, C["bi"])
            p.iconst(12, 1)
            p.iop(9, 9, "+", 12)
            p.st(C["bi"], 9)
        self.ivloop("cnt2", one)
        self.output()

    def block_i(self) -> None:
        """block bi: its row, its settings, its inputs, its kernel"""
        p, C = self.p, self.L.C
        V, c = self.V, self.c
        self.tabw(0, "ty", "prow", 0)
        p.st(C["ty"], 0)

        def run():
            # I3 = the block's words; ybuf = its buffer
            p.ld(9, C["bi"])
            p.iconst(12, 4 * BSTRIDE)
            p.mul_ssi(0, 9, 12)
            p.ipass(8, 0)
            p.ld(12, C["vba"])
            p.iop(0, 8, "+", 12)
            p.iconst(12, 4 * VOICE["blk"])
            p.ipass(8, 0)
            p.iop(0, 8, "+", 12)
            p.st(C["bwp"], 0)
            p.ld(9, C["bi"])
            p.lsh(0, 9, 7)                     # 4 x 32 bi
            p.ipass(8, 0)
            p.ld(12, C["vba"])
            p.iop(0, 8, "+", 12)
            p.iconst(12, 4 * VOICE["buf"])
            p.ipass(8, 0)
            p.iop(0, 8, "+", 12)
            p.st(C["ybuf"], 0)
            # x1, x2: the patch's settings plus the knobs' offsets, 0..1
            for q, (col, knob) in enumerate(((5, "kx1"), (6, "kx2"))):
                self.tabw(0, "d", "prow", col)
                p.st(C["dd"], 0)
                p.ld(9, C["bi"])
                p.lsh(9, 9, 3)                 # 4 x 2 bi
                p.iconst(12, self.L.A["eff"] + 4 * (8 + q))
                p.iop(9, 9, "+", 12)
                p.seti(1, 9)
                p.ldi(0, 0, 1)
                p.st(C[knob], 0)
                xn = f"x{q + 1}"
                self.set(c(xn), (c("dd") + (c(knob) - k(64.0))) * k(LV.INV127))
                self.clamp(c(xn), 0.0, 1.0)
            for col, nm in ((1, "sa"), (2, "sb")):
                self.tabw(0, nm, "prow", col)
                p.st(C[nm], 0)
            self.tabw(0, "ka", "prow", 3)
            p.st(C["ka"], 0)
            self.tabw(0, "kb", "prow", 4)
            p.st(C["kb"], 0)
            # B MOVES: B's first sample on setting 2 (with its own amount), and the block sees no B
            self.moves_bit()
            self.iset(c("ac"), 0)
            self.icmp(c("sa"), "NE", 0, lambda: self.iset(c("ac"), 1))
            self.iset(c("bc"), 0)

            def bconn():
                self.icmp(c("mv"), "EQ", 0, lambda: self.iset(c("bc"), 1))
            self.icmp(c("sb"), "NE", 0, bconn)

            def moves():
                self.src_first("sb", "kb")
                self.set(c("x2"), c("x2") + c("b0"))
                self.clamp(c("x2"), 0.0, 1.0)
            self.icmp(c("mv"), "NE", 0, lambda: self.icmp(c("sb"), "NE", 0, moves))
            self.icmp(c("bc"), "EQ", 0, lambda: self.fz(c("kb")))
            self.fill("sa", "ka", 0)
            self.fill("sb", "kb", BLOCK)
            self.trig_row()
            p.ld(12, C["bwp"])
            p.seti(3, 12)
            self.dispatch()
        self.icmp(c("ty"), "NE", 0, run)

    def moves_bit(self) -> None:
        """c('mv') = (BMOVE >> bi) & 1 (BMOVE: the patch's last word)"""
        p, C = self.p, self.L.C
        # the patch's base: prow - 4 ROW bi
        p.ld(9, C["bi"])
        p.lsh(9, 9, 5)                         # 4 x 8 bi
        p.ld(12, C["prow"])
        p.iop(0, 12, "-", 9)
        p.iconst(12, 4 * (NB * ROW + 1))
        p.ipass(8, 0)
        p.iop(0, 8, "+", 12)
        p.seti(1, 0)
        p.ldi(0, 0, 1)
        p.ld(9, C["bi"])
        p.iconst(12, 0)
        p.iop(9, 12, "-", 9)
        _lsh_by(p, 0, 9)
        p.iconst(12, 1)
        p.iop(0, 0, "AND", 12)
        p.st(C["mv"], 0)

    def src_addr(self, sname: str) -> None:
        """R0 = the address of source SNAME's 32 samples, or 0 for a constant (its value in sval)"""
        p, C = self.p, self.L.C
        c, V = self.c, self.V
        p.ld(0, C[sname])

        def blockbuf():
            # buf + 4 x 32 (s - 1)
            p.ld(9, C[sname])
            p.iconst(12, 1)
            p.iop(9, 9, "-", 12)
            p.lsh(9, 9, 7)
            p.ld(12, C["vba"])
            p.iop(0, 9, "+", 12)
            p.iconst(12, 4 * VOICE["buf"])
            p.ipass(8, 0)
            p.iop(0, 8, "+", 12)
            p.st(C["saddr"], 0)

        def other():
            self.iset(c("saddr"), 0)
            self.fz(c("sval"))
            for s_, val in ((LV.S_PITCH, c("spitch")), (LV.S_GATE, V("gate")), (LV.S_VEL, V("vel")),
                            (LV.S_LFO1, c("slfo1")), (LV.S_LFO2, c("slfo2"))):
                self.icmp(c(sname), "EQ", s_, lambda val=val: self.set(c("sval"), val))
            self.icmp(c(sname), "EQ", LV.S_NOISE, lambda: self.iset(c("saddr"), self.L.A["nz"]))
            self.icmp(c(sname), "EQ", LV.S_TRIG, lambda: self.iset(c("saddr"), -1))
        self.ld(0, c(sname))
        p.iconst(1, 1)
        p.if_(0, "GE", 1, lambda: (p.ld(0, C[sname]), p.iconst(1, NB),
                                   p.if_(0, "LE", 1, blockbuf, other, kind="i")), other, kind="i")

    def src_first(self, sname: str, kname: str) -> None:
        """c('b0') = the source's first sample times the amount"""
        p, C = self.p, self.L.C
        c, V = self.c, self.V
        self.src_addr(sname)

        def buf():
            p.ld(12, C["saddr"])
            p.seti(1, 12)
            p.ldi(0, 0, 1)
            p.st(C["tmp0"], 0)
            self.set(c("b0"), c("tmp0") * c(kname))

        def trigv():
            self.fz(c("tmp0"))
            self.icmp(V("trig"), "NE", 0, lambda: self.set(c("tmp0"), k(1.0)))
            self.set(c("b0"), c("tmp0") * c(kname))
        self.icmp(c("saddr"), "EQ", -1, trigv,
                  lambda: self.icmp(c("saddr"), "EQ", 0, lambda: self.set(c("b0"), c("sval") * c(kname)), buf))

    def fill(self, sname: str, kname: str, at: int) -> None:
        """the scratch array ain (at 0) or bin (at 32) = the source's 32 samples times the amount"""
        p, C = self.p, self.L.C
        c, V = self.c, self.V
        self.src_addr(sname)
        p.iconst(0, self.L.A["ain"] + 4 * at)
        p.st(C["dp"], 0)

        def buf():
            def one():
                p.ld(12, C["saddr"])
                p.seti(1, 12)
                p.ldi(0, 0, 1)
                p.st(C["tmp0"], 0)
                p.ld(12, C["dp"])
                p.seti(4, 12)
                self.set(Mv("i", 4, 0), c("tmp0") * c(kname))
                self.bump("saddr", 4)
                self.bump("dp", 4)
            p.loop(C["cnt0"], BLOCK, one)

        def trigv():
            # TRIG: 1 at the first sample of a trig's block, else 0, times the amount
            self.fz(c("tmp0"))
            self.icmp(V("trig"), "NE", 0, lambda: self.set(c("tmp0"), k(1.0)))
            self.set(self.a("ain", at), c("tmp0") * c(kname))
            self.set(c("tmp1"), k(0.0) * c(kname))
            for j in range(1, BLOCK):
                self.set(self.a("ain", at + j), c("tmp1"))

        def const():
            self.set(c("tmp1"), c("sval") * c(kname))
            for j in range(BLOCK):
                self.set(self.a("ain", at + j), c("tmp1"))
        self.icmp(c("saddr"), "EQ", -1, trigv, lambda: self.icmp(c("saddr"), "EQ", 0, const, buf))

    def trig_row(self) -> None:
        """tg: TRIG's 32 samples (1 at the first of a trig's block)"""
        V = self.V
        for j in range(BLOCK):
            self.fz(self.a("tg", j))
        self.icmp(V("trig"), "NE", 0, lambda: self.set(self.a("tg", 0), k(1.0)))

    def dispatch(self) -> None:
        c = self.c
        LVm = LV
        table = ((LVm.PHASE, "l_phase", self.k_phase), (LVm.WAVE, "l_wave", self.k_wave),
                 (LVm.SLOPE, "l_slope", self.k_slope), (LVm.SLEW, "l_slope", self.k_slope),
                 (LVm.CYCLE, "l_cycle", self.k_cycle),
                 (LVm.LP, "l_filt", self.k_filt), (LVm.BP, "l_filt", self.k_filt), (LVm.HP, "l_filt", self.k_filt),
                 (LVm.ADD, "l_arith", self.k_arith), (LVm.MULT, "l_arith", self.k_arith),
                 (LVm.MIX, "l_arith", self.k_arith), (LVm.FOLD, "l_fold", self.k_fold),
                 (LVm.COMP, "l_logic", self.k_logic), (LVm.XOR, "l_logic", self.k_logic),
                 (LVm.FLIP, "l_logic", self.k_logic), (LVm.HOLD, "l_hold", self.k_hold),
                 (LVm.SKIN, "l_modes", self.k_modes), (LVm.BAR, "l_modes", self.k_modes),
                 (LVm.SAT, "l_satk", self.k_sat), (LVm.RUNGLER, "l_rung", self.k_rung),
                 (LVm.IMPULSE, "l_impl", self.k_impulse), (LVm.CREASE, "l_creas", self.k_crease))
        for ty, name, body in table:
            self.icmp(c("ty"), "EQ", ty, lambda name=name, body=body: self.rt(name, body))

    # -- the kernels (live.Voice._run) ---------------------------------------------------------
    def k_phase(self) -> None:
        p, C = self.p, self.L.C
        c, B = self.c, self.B
        self.wn("ri", c("x1"), 16)
        p.ld(0, C["ri"])
        p.lsh(0, 0, 2)
        p.ipass(8, 0)
        p.iconst(12, self.L.tables + 4 * TAB["RATIO"][0])
        p.iop(0, 8, "+", 12)
        p.seti(1, 0)
        p.ldi(0, 0, 1)
        p.st(C["rat"], 0)
        self.set(c("c1"), ((c("hz") * c("rat")) * exp2f((((c("x2") * k(127.0 / 64.0)) - k(1.0))) * k(1.0 / 12.0))) * k(LV.DT))

        def body():
            self.set(B("ph"), B("ph") + c("c1") * (k(1.0) + k(8.0) * self.A_()))
            self.wrap(B("ph"))

            def reset():
                self.rise(self.B_(), B("prevb"), k(0.0))
                self.icmp(c("e"), "NE", 0, lambda: self.fz(B("ph")))
            self.icmp(c("bc"), "NE", 0, reset)
            self.out_(B("ph") * k(2.0) - k(1.0))
        self.samples(body)

    def k_wave(self) -> None:
        p, C = self.p, self.L.C
        c, B = self.c, self.B
        self.set(c("kw"), k(0.5) + ((c("x2") * k(127.0 / 64.0)) - k(1.0)) * k(0.5))
        self.clamp(c("kw"), 0.03, 0.97)
        self.set(c("rk"), k(0.5) * recip(c("kw")))
        self.set(c("rk1"), k(0.5) * recip(k(1.0) - c("kw")))
        self.set(c("s3"), c("x1") * k(3.0))
        self.ev(c("s3"), 0)
        p.trunc(0, 0)
        p.iconst(12, 2)
        p.iop(0, 0, "MIN", 12)
        p.st(C["seg"], 0)
        self.set(c("fr"), c("s3") - fi(self.ci("seg")))
        self.set(c("inc"), c("hz") * k(LV.DT))

        def body():
            def from_a():
                self.set(c("pp"), (self.A_() * k(0.5)) + k(0.5))

            def own():
                self.set(B("ph"), B("ph") + c("inc"))
                self.wrap(B("ph"))
                self.set(c("pp"), B("ph"))
            self.icmp(c("ac"), "NE", 0, from_a, own)
            self.set(c("pp"), c("pp") + self.B_() * k(0.5))
            self.wrap(c("pp"))
            self.cmp(c("pp"), "LT", c("kw"), lambda: self.set(c("pp"), c("pp") * c("rk")),
                     lambda: self.set(c("pp"), k(0.5) + (c("pp") - c("kw")) * c("rk1")))
            self.shape("v", "seg", 0)

            def blend():
                self.shape("v2", "seg", 1)
                self.set(c("v"), c("v") + (c("v2") - c("v")) * c("fr"))
            self.cmp(c("fr"), "GT", k(0.0), blend)
            self.out_(c("v"))
        self.samples(body)

    def shape(self, dst: str, seg: str, plus: int) -> None:
        """c(dst) = live.shape_k(seg + plus, pp)"""
        c = self.c
        pp = c("pp")

        def k0():
            self.set(c(dst), sin_turns(pp))

        def k1():
            self.cmp(pp, "LT", k(0.25), lambda: self.set(c(dst), k(4.0) * pp),
                     lambda: self.cmp(pp, "LT", k(0.75), lambda: self.set(c(dst), k(2.0) - k(4.0) * pp),
                                      lambda: self.set(c(dst), k(4.0) * pp - k(4.0))))

        def k2():
            self.set(c(dst), k(2.0) * pp - k(1.0))

        def k3():
            self.cmp(pp, "LT", k(0.5), lambda: self.set(c(dst), k(1.0)), lambda: self.set(c(dst), k(-1.0)))
        ks = (k0, k1, k2, k3)
        for v in range(4):
            sv = v - plus
            if sv < 0:
                continue
            self.icmp(c(seg), "EQ", sv, ks[v])

    def k_slope(self) -> None:
        p, C = self.p, self.L.C
        c, B, V = self.c, self.B, self.V
        self.wk("kr", self.wtime(c("x1")))
        self.wk("kf", self.wtime(c("x2")))

        def body():
            self.set(c("sc"), k(1.0))
            self.icmp(c("bc"), "NE", 0, lambda: self.set(c("sc"), exp2f((-self.B_()) * k(4.0))))

            def slope():
                self.icmp(c("ac"), "NE", 0, lambda: self.set(c("gg"), self.A_()), lambda: self.set(c("gg"), V("gate")))
                self.rise(c("gg"), B("prev"), k(0.5))

                def start():
                    self.iset(B("st"), 1)
                self.icmp(c("e"), "NE", 0, start,
                          lambda: self.icmp(c("ac"), "EQ", 0, lambda: self.cmp(self.TG(), "GT", k(0.0), start)))

                def st1():
                    self.set(c("kk"), c("kr") * c("sc"))
                    self.clamp(c("kk"), 0.0, 1.0)
                    self.set(B("y"), B("y") + (k(1.25) - B("y")) * c("kk"))
                    self.cmp(B("y"), "GE", k(1.0), lambda: (self.set(B("y"), k(1.0)), self.iset(B("st"), 2)))

                def st2():
                    self.cmp(c("gg"), "LE", k(0.5), lambda: self.iset(B("st"), 0))
                self.icmp(B("st"), "EQ", 1, st1, lambda: self.icmp(B("st"), "EQ", 2, st2))

                def fall():
                    self.set(c("kk"), c("kf") * c("sc"))
                    self.clamp(c("kk"), 0.0, 1.0)
                    self.set(B("y"), B("y") - B("y") * c("kk"))
                self.icmp(B("st"), "EQ", 0, fall)

            def slew():
                self.set(c("rr"), self.A_())
                self.cmp(c("rr"), "GT", B("y"), lambda: self.set(c("kk"), c("kr") * c("sc")),
                         lambda: self.set(c("kk"), c("kf") * c("sc")))
                self.clamp(c("kk"), 0.0, 1.0)
                self.set(B("y"), B("y") + (c("rr") - B("y")) * c("kk"))
            self.icmp(c("ty"), "EQ", LV.SLOPE, slope, slew)
            self.out_w(B("y"))
        self.samples(body)

    def k_cycle(self) -> None:
        c, B = self.c, self.B
        self.set(c("c1"), (k(0.02) * exp2f(c("x1") * k(17.0))) * k(LV.DT))
        self.set(c("kw"), c("x2"))
        self.clamp(c("kw"), 0.01, 0.99)
        self.set(c("rk"), recip(c("kw")))
        self.set(c("rk1"), recip(k(1.0) - c("kw")))

        def body():
            self.icmp(c("ac"), "NE", 0, lambda: self.set(c("inc"), c("c1") * exp2f(self.A_() * k(5.0))),
                      lambda: self.set(c("inc"), c("c1")))
            self.set(B("ph"), B("ph") + c("inc"))
            self.wrap(B("ph"))

            def reset():
                self.rise(self.B_(), B("prevb"), k(0.0))
                self.icmp(c("e"), "NE", 0, lambda: self.fz(B("ph")))
            self.icmp(c("bc"), "NE", 0, reset)
            self.cmp(B("ph"), "LT", c("kw"), lambda: self.set(c("v"), B("ph") * c("rk")),
                     lambda: self.set(c("v"), (k(1.0) - B("ph")) * c("rk1")))
            self.out_(c("v") * k(2.0) - k(1.0))
        self.samples(body)

    def k_filt(self) -> None:
        p, C = self.p, self.L.C
        c, B = self.c, self.B
        self.set(c("c1"), k(20.0) * exp2f(c("x1") * k(10.0)))
        self.set(c("R2"), k(2.0) * ((k(2.0) - k(1.96) * c("x2")) * k(0.5)))
        self.set(c("fc"), c("c1"))
        self.clamp(c("fc"), 20.0, 18000.0)
        self.set(c("tx"), (k(3.14159265) * c("fc")) * k(LV.DT))
        self.tanf("g", "tx")
        self.set(c("d"), recip((k(1.0) + c("R2") * c("g")) + c("g") * c("g")))

        def body():
            self.set(c("gg"), c("g"))
            self.set(c("dd"), c("d"))

            def bmod():
                def every4():
                    self.set(c("fc"), c("c1") * exp2f(self.B_() * k(5.0)))
                    self.clamp(c("fc"), 20.0, 18000.0)
                    self.set(c("tx"), (k(3.14159265) * c("fc")) * k(LV.DT))
                    self.tanf("tg2", "tx")
                    self.set(B("g2"), c("tg2"))
                    self.set(B("d2"), recip((k(1.0) + c("R2") * B("g2")) + B("g2") * B("g2")))
                p.ld(0, C["jj"])
                p.iconst(1, 3)
                p.iop(0, 0, "AND", 1)
                p.ifz(0, "EQ", every4)
                self.set(c("gg"), B("g2"))
                self.set(c("dd"), B("d2"))
            self.icmp(c("bc"), "NE", 0, bmod)
            self.set(c("hp"), ((self.A_() - (c("R2") + c("gg")) * B("s1")) - B("s2")) * c("dd"))
            self.set(c("bp"), c("gg") * c("hp") + B("s1"))
            self.set(B("s1"), c("gg") * c("hp") + c("bp"))
            self.set(c("lp"), c("gg") * c("bp") + B("s2"))
            self.set(B("s2"), c("gg") * c("bp") + c("lp"))
            self.icmp(c("ty"), "EQ", LV.LP, lambda: self.set(c("v"), c("lp")),
                      lambda: self.icmp(c("ty"), "EQ", LV.BP, lambda: self.set(c("v"), c("bp") * c("R2")),
                                        lambda: self.set(c("v"), c("hp"))))

            def blown():
                self.fz(B("s1"))
                self.fz(B("s2"))
                self.fz(c("v"))
            self.cmp(c("v"), "GT", k(-8.0), lambda: self.cmp(c("v"), "LT", k(8.0), None, blown), blown)
            self.out_w(c("v"))
        self.samples(body)

    def k_arith(self) -> None:
        c = self.c
        self.set(c("o"), ((c("x1") * k(127.0 / 64.0)) - k(1.0)) * k(2.0))
        self.set(c("gn"), c("x2") * k(127.0 / 64.0))

        def body():
            def add():
                self.out_(((self.A_() + self.B_()) + c("o")) * c("gn"))

            def mult():
                self.icmp(c("bc"), "NE", 0, lambda: self.set(c("v"), self.B_() + c("o")),
                          lambda: self.set(c("v"), k(1.0) + c("o")))
                self.out_((self.A_() * c("v")) * c("gn"))

            def mix():
                self.set(c("v"), self.A_())
                self.out_((c("v") + (self.B_() - c("v")) * c("x1")) * c("gn"))
            self.icmp(c("ty"), "EQ", LV.ADD, add, lambda: self.icmp(c("ty"), "EQ", LV.MULT, mult, mix))
        self.samples(body)

    def k_fold(self) -> None:
        c = self.c
        self.set(c("dr"), k(1.0) + c("x1") * k(15.0))
        self.set(c("o"), (c("x2") * k(127.0 / 64.0)) - k(1.0))
        self.samples(lambda: self.out_(sin_turns((((self.A_() * c("dr")) * (k(1.0) + self.B_())) + c("o")) * k(0.25))))

    def k_logic(self) -> None:
        c, B = self.c, self.B
        self.set(c("thr"), (c("x2") * k(127.0 / 64.0)) - k(1.0))

        def body():
            self.iset(c("r"), 0)

            def comp():
                self.cmp(self.A_(), "GT", self.B_() + c("thr"), lambda: self.iset(c("r"), 1))

            def xor():
                self.iset(c("ta"), 0)
                self.cmp(self.A_(), "GT", c("thr"), lambda: self.iset(c("ta"), 1))
                self.iset(c("tb"), 0)
                self.cmp(self.B_(), "GT", c("thr"), lambda: self.iset(c("tb"), 1))
                self.ld(0, c("ta"))
                self.ld(1, c("tb"))
                self.p.if_(0, "NE", 1, lambda: self.iset(c("r"), 1), kind="i")

            def flip():
                self.rise(self.A_(), B("prev"), c("thr"))

                def tog():
                    self.ld(0, B("st"))
                    self.p.iconst(1, 1)
                    self.p.iop(2, 0, "AND", 1)
                    self.p.iop(0, 0, "OR", 1)
                    self.p.iop(0, 0, "-", 2)
                    self.st(B("st"), 0)
                self.icmp(c("e"), "NE", 0, tog)

                def breset():
                    self.rise(self.B_(), B("prevb"), c("thr"))
                    self.icmp(c("e"), "NE", 0, lambda: self.iset(B("st"), 0))
                self.icmp(c("bc"), "NE", 0, breset)
                self.icmp(B("st"), "EQ", 1, lambda: self.iset(c("r"), 1))
            self.icmp(c("ty"), "EQ", LV.COMP, comp, lambda: self.icmp(c("ty"), "EQ", LV.XOR, xor, flip))
            self.icmp(c("r"), "NE", 0, lambda: self.out_w(c("x1")), lambda: self.out_(-c("x1")))
        self.samples(body)

    def k_hold(self) -> None:
        p = self.p
        c, B = self.c, self.B
        self.set(c("kh"), k(1.0))
        self.cmp(c("x2"), "GT", k(0.0), lambda: self.wk("kh", self.wtime(c("x2") * k(0.8))))
        self.set(c("lv"), k(2.0) + c("x1") * k(30.0))
        self.set(c("rl"), recip(c("lv")))

        def body():
            def by_b():
                self.rise(self.B_(), B("prevb"), k(0.0))

            def by_trig():
                self.iset(c("e"), 0)
                self.cmp(self.TG(), "GT", k(0.0), lambda: self.iset(c("e"), 1))
            self.icmp(c("bc"), "NE", 0, by_b, by_trig)

            def take():
                self.set(c("qv"), self.A_())

                def steps():
                    self.ev(((c("qv") * k(0.5)) + k(0.5)) * c("lv") + k(0.5), 0)
                    p.fpass(15, 0)
                    OP._floor_f(p, 15, 14)
                    p.st(self.L.C["tmp0"], 14)
                    self.set(c("qv"), ((c("tmp0") * c("rl")) * k(2.0)) - k(1.0))
                self.cmp(c("x1"), "GT", k(0.0), steps)
                self.set(B("hold"), c("qv"))
            self.icmp(c("e"), "NE", 0, take)
            self.set(B("y"), B("y") + (B("hold") - B("y")) * c("kh"))
            self.out_w(B("y"))
        self.samples(body)

    def k_modes(self) -> None:
        """SKIN, BAR: six modes per block, then the 32 samples mode by mode into the buffer"""
        p, C = self.p, self.L.C
        c, B = self.c, self.B
        self.fz(c("pm"))
        self.icmp(c("bc"), "NE", 0, lambda: self.set(c("pm"), self.a("bin", 0)))
        self.set(c("base"), c("hz") * exp2f(c("pm")))
        self.set(c("dark"), k(1.0) - c("x2"))
        self.set(c("T0"), k(0.002) * exp2f(c("x1") * k(12.0)))

        def coefs(ty):
            for m in range(LV.NM):
                self.set(c("fm"), c("base") * k(LV.MODES[ty][m]))
                self.set(c("Tm"), c("T0") * exp2f(((-c("dark")) * k(1.2)) * k(LV.L2REL[ty][m])))
                self.set(c("rm"), expf((k(-6.9078) * k(LV.DT)) * recip(c("Tm"))))
                self.set(c("gm"), exp2f(((-c("dark")) * k(1.5)) * k(LV.L2K[m])) * k(0.5))
                self.set(c("xm"), c("fm") * k(LV.DT))

                def zero(m=m):
                    for q in range(3):
                        self.fz(self.a("mc", 3 * m + q))

                def pole(m=m):
                    self.set(self.a("mc", 3 * m), (k(2.0) * c("rm")) * sin_turns(c("xm") + k(0.25)))
                    self.set(self.a("mc", 3 * m + 1), -(c("rm") * c("rm")))
                    self.set(self.a("mc", 3 * m + 2), sin_turns(c("xm")) * c("gm"))
                self.cmp(c("xm"), "GT", k(0.45), zero, lambda: self.cmp(c("xm"), "LE", k(0.0), zero, pole))
        self.icmp(c("ty"), "EQ", LV.SKIN, lambda: coefs(LV.SKIN), lambda: coefs(LV.BAR))
        # the buffer = 0, then each mode adds its 32 samples
        p.ld(12, C["ybuf"])
        p.seti(4, 12)
        p.fconst(5, 0.0)
        p.loop_r(10, BLOCK, lambda: p.stpost(4, 5), one=11)
        for m in range(LV.NM):
            def body(m=m):
                self.set(c("yk"), ((self.a("mc", 3 * m) * B(f"z{2 * m}")) + (self.a("mc", 3 * m + 1) * B(f"z{2 * m + 1}")))
                         + (self.a("mc", 3 * m + 2) * self.A_()))
                self.set(B(f"z{2 * m + 1}"), B(f"z{2 * m}"))
                self.set(B(f"z{2 * m}"), c("yk"))
                self.ld(0, Mv("i", 0, 0))
                self.ld(1, c("yk"))
                p.fop(0, 0, "+", 1)
                p.sti(0, 0, 0)
            self.samples(body)
        # blown up anywhere: the modes start over, silent this block
        self.iset(c("bad"), 0)

        def chk():
            self.cmp(Mv("i", 0, 0), "GT", k(-16.0), lambda: self.cmp(Mv("i", 0, 0), "LT", k(16.0), None,
                                                                      lambda: self.iset(c("bad"), 1)),
                     lambda: self.iset(c("bad"), 1))
        self.samples(chk)

        def blown():
            for j in range(2 * LV.NM):
                self.fz(B(f"z{j}"))
            p.ld(12, C["ybuf"])
            p.seti(4, 12)
            p.fconst(5, 0.0)
            p.loop_r(10, BLOCK, lambda: p.stpost(4, 5), one=11)
        self.icmp(c("bad"), "NE", 0, blown)

    def k_sat(self) -> None:
        c = self.c
        self.set(c("dr"), k(1.0) + c("x1") * k(15.0))
        self.set(c("o"), (c("x2") * k(127.0 / 64.0)) - k(1.0))

        def body():
            self.set(c("m"), k(1.0))
            self.icmp(c("bc"), "NE", 0, lambda: self.set(c("m"), exp2f(self.B_() * k(2.0))))
            self.sat("v", (((self.A_() * c("dr")) * c("m")) + c("o")) * k(0.8))
            self.out_w(c("v"))
        self.samples(body)

    def k_impulse(self) -> None:
        p = self.p
        c, B = self.c, self.B
        self.set(c("d"), (k(0.02) * exp2f((-c("x1")) * k(9.0))) * k(48000.0))
        self.set(c("r"), k(1.0) - c("x2"))
        self.clamp(c("r"), 0.01, 1.0)

        def bmod():
            self.set(c("bb"), self.a("bin", 0))
            self.clamp(c("bb"), -1.0, 1.0)
            self.set(c("d"), c("d") * exp2f((-c("bb")) * k(3.0)))
        self.icmp(c("bc"), "NE", 0, bmod)
        self.cmp(c("d"), "LE", k(2.0), lambda: self.set(c("d"), k(2.0)))
        self.set(c("rd"), c("r") * c("d"))
        self.cmp(c("rd"), "LE", k(1.0), lambda: self.set(c("rd"), k(1.0)))
        self.set(c("up"), k(2.0) * recip(c("rd")))

        def dn_r():
            self.set(c("rd"), (k(1.0) - c("r")) * c("d"))
            self.cmp(c("rd"), "LE", k(1.0), lambda: self.set(c("rd"), k(1.0)))
            self.set(c("dn"), k(2.0) * recip(c("rd")))
        self.cmp(c("r"), "GE", k(1.0), lambda: self.set(c("dn"), k(2.0)), dn_r)

        def restart():
            self.iset(B("st"), 0)
            self.set(B("y"), k(-1.0))
        self.set(c("tmp1"), FP_.ab(B("y")))
        self.icmp(B("st"), "GT", 2, restart,
                  lambda: self.cmp(c("tmp1"), "GT", k(1.0), restart))
        self.set(c("inc"), c("hz") * k(LV.DT))

        def body():
            def by_a():
                self.rise(self.A_(), B("prev"), k(0.0))

            def own():
                self.set(B("ph"), B("ph") + c("inc"))
                self.iset(c("e"), 0)

                def over():
                    self.iset(c("e"), 1)
                    self.ld(0, B("ph"))
                    p.fpass(15, 0)
                    OP._floor_f(p, 15, 14)
                    p.fop(0, 0, "-", 14)
                    self.st(B("ph"), 0)
                self.cmp(B("ph"), "GE", k(1.0), over)
            self.icmp(c("ac"), "NE", 0, by_a, own)
            self.icmp(c("e"), "NE", 0, lambda: self.icmp(B("st"), "NE", 1, lambda: self.iset(B("st"), 1)))

            def st1():
                self.set(B("y"), B("y") + c("up"))
                self.cmp(B("y"), "GE", k(1.0), lambda: (self.set(B("y"), k(1.0)), self.iset(B("st"), 2)))

            def st2():
                self.set(B("y"), B("y") - c("dn"))
                self.cmp(B("y"), "LE", k(-1.0), lambda: (self.set(B("y"), k(-1.0)), self.iset(B("st"), 0)))
            self.icmp(B("st"), "EQ", 1, st1, lambda: self.icmp(B("st"), "EQ", 2, st2))
            self.out_w(B("y"))
        self.samples(body)

    def k_crease(self) -> None:
        c = self.c
        self.set(c("sh"), c("x1") * k(127.0 / 64.0))
        self.set(c("o"), (c("x2") * k(127.0 / 64.0)) - k(1.0))

        def body():
            self.set(c("v"), (self.A_() + self.B_()) + c("o"))
            self.cmp(c("v"), "LT", k(0.0), lambda: self.out_(c("v") + c("sh")), lambda: self.out_(c("v") - c("sh")))
        self.samples(body)

    def k_rung(self) -> None:
        p, C = self.p, self.L.C
        c, B = self.c, self.B
        self.wn("rl3", c("x2"), 6)              # L - 3
        self.ld(0, c("rl3"))
        p.iconst(12, 3)
        p.ipass(8, 0)
        p.iop(0, 8, "+", 12)
        p.st(C["rL"], 0)                       # L
        p.iconst(1, 1)
        p.ld(9, C["rL"])
        PP._shift_by(p, 1, 9)
        p.iconst(12, 1)
        p.iop(1, 1, "-", 12)
        p.st(C["rmask"], 1)

        def body():
            def by_a():
                self.rise(self.A_(), B("prev"), k(0.0))

            def by_trig():
                self.iset(c("e"), 0)
                self.cmp(self.TG(), "GT", k(0.0), lambda: self.iset(c("e"), 1))
            self.icmp(c("ac"), "NE", 0, by_a, by_trig)

            def step():
                # last = (st >> (L - 1)) & 1
                self.ld(0, B("st"))
                p.ld(9, C["rL"])
                p.iconst(12, 1)
                p.iop(9, 9, "-", 12)
                p.iconst(12, 0)
                p.iop(9, 12, "-", 9)
                _lsh_by(p, 0, 9)
                p.iconst(12, 1)
                p.iop(0, 0, "AND", 12)
                p.st(C["last"], 0)

                def nb_b():
                    self.iset(c("nb"), 0)
                    self.cmp(self.B_(), "GT", k(0.0), lambda: self.iset(c("nb"), 1))

                def nb_r():
                    self.iset(c("nb"), 0)
                    self.cmp(u_rg(), "LT", k(0.5), lambda: self.iset(c("nb"), 1))
                self.icmp(c("bc"), "NE", 0, nb_b, nb_r)
                self.set(c("tmp1"), u_rg() * k(0.999))
                self.cmp(c("tmp1"), "LT", c("x1"), lambda: (p.ld(0, C["last"]), p.st(C["bit"], 0)),
                         lambda: (p.ld(0, C["nb"]), p.st(C["bit"], 0)))
                self.ld(0, B("st"))
                p.lsh(0, 0, 1)
                p.ld(1, C["bit"])
                p.iop(0, 0, "OR", 1)
                p.ld(1, C["rmask"])
                p.iop(0, 0, "AND", 1)
                self.st(B("st"), 0)
            self.icmp(c("e"), "NE", 0, step)
            # y = ((st >> (L - 3)) & 7) 2/7 - 1
            self.ld(0, B("st"))
            p.ld(9, C["rl3"])
            p.iconst(12, 0)
            p.iop(9, 12, "-", 9)
            _lsh_by(p, 0, 9)
            p.iconst(12, 7)
            p.iop(0, 0, "AND", 12)
            p.st(C["ri"], 0)
            self.out_((fi(self.ci("ri")) * k(2.0 / 7.0)) - k(1.0))
        self.samples(body)

    # -- the voice's level and the rest ------------------------------------------------------------
    def output(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c = self.V, self.c
        # the OUT block's buffer
        p.ld(0, C["prow"])                     # past the 12 rows now: OUT's word
        p.seti(1, 0)
        p.ldi(9, 0, 1)
        p.lsh(9, 9, 7)
        p.ld(12, C["vba"])
        p.iop(0, 9, "+", 12)
        p.iconst(12, 4 * VOICE["buf"])
        p.ipass(8, 0)
        p.iop(0, 8, "+", 12)
        p.st(C["sp"], 0)
        self.set(c("vs"), self.a("eff", 5) * k(LV.INV127))
        self.set(c("lvl"), (self.a("eff", 7) * k(LV.INV127)) * ((k(1.0) - c("vs")) + c("vs") * V("vel")))
        self.set(c("dr"), k(1.0) + (self.a("eff", 6) * k(LV.INV127)) * k(7.0))
        self.iset(c("bad"), 0)
        self.fz(c("peak"))
        p.ld(9, L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, BUFFERS)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.st(C["outp"], 0)

        def one():
            p.ld(12, C["sp"])
            p.seti(4, 12)
            self.set(c("v"), Mv("i", 4, 0))

            def good():
                self.sat("o", c("v") * c("dr"))
                self.set(c("o"), (c("o") * c("lvl")) * k(LV.TRIM))
                self.set(c("oa"), FP_.ab(c("o")))
                self.cmp(c("oa"), "GT", c("peak"), lambda: self.set(c("peak"), c("oa")))
            self.cmp(c("v"), "GT", k(-16.0), lambda: self.cmp(c("v"), "LT", k(16.0), good, lambda: self.iset(c("bad"), 1)),
                     lambda: self.iset(c("bad"), 1))
            self.icmp(c("bad"), "NE", 0, lambda: self.fz(c("o")))
            p.ld(12, C["outp"])
            p.seti(4, 12)
            self.ld(0, c("o"))
            p.sti(0, 4, 0)
            self.bump("sp", 4)
            self.bump("outp", 4)
        p.loop(C["cnt0"], BLOCK, one)

        def blown():                           # live: the voice rests, its blocks cleared, silence
            self.iset(V("on"), 0)
            self.reset()
            self.iset(V("trig"), 0)
            self.zeros()

        def fine():
            self.iset(V("trig"), 0)

            def shut():
                def qup():
                    self.ld(0, V("quiet"))
                    p.iconst(12, 1)
                    p.ipass(8, 0)
                    p.iop(0, 8, "+", 12)
                    self.st(V("quiet"), 0)
                self.cmp(c("peak"), "LT", k(LV.REST_AMP), qup, lambda: self.iset(V("quiet"), 0))
                self.icmp(V("quiet"), "GE", LV.REST_BLOCKS, lambda: self.iset(V("on"), 0))
            self.cmp(V("gate"), "EQ", k(0.0), shut)
        self.icmp(c("bad"), "NE", 0, blown, fine)


def voice(p, L: Layout, t: int | None = None) -> LG:
    g = LG(p, L)
    saved = p.scr_on
    p.iconst(0, L.base5)
    p.seti(5, 0, "the scratch's base + WIN words")
    p.scr_on = True
    g.voice(t)
    p.scr_on = saved
    return g


def run_voice(L: Layout, read, t: int, mem=None):
    mem = mem or Mem(read)
    p = FP_.FProg("run", mem=mem)
    p.pool = {}
    p.spill = None
    p.scr = (L.scratch, L.scratch_end, L.base5)
    voice(p, L, t)
    return p, mem


def layout() -> Layout:
    from ..waverider import dsp
    return Layout(FP_.layout(), dsp.LIG_TABLES_DDR)
