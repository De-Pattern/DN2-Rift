def tables_values() -> bytes:
    """org_tab[5][3][256] as floats, the stops' gains, the steal's ramp: what live.Voice reads"""
    t = LV.tables()
    vals = [float(F(int(v))) for v in t.reshape(-1)] + [float(g) for g in LV.GAIN] + \
        [float(x) for x in LV.fade_ramp()]
    assert len(vals) == TABLE_WORDS
    return struct.pack(f"<{TABLE_WORDS}I", *[bits(f32(v)) for v in vals])


def write_ddr_json() -> None:
    import json
    from . import ddr
    words = [f"{w:08x}" for w in struct.unpack(f"<{TABLE_WORDS}I", tables_values())]
    ddr.DDR_JSON.write_text(json.dumps({"note": "generated by scripts/gen_fascia_asm.py from dnfw.organ.live; do not edit",
                                        "words": words}) + "\n", encoding="utf-8", newline="\n")


