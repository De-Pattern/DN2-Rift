    # -- a block (live.Organ.render, x TRIM, and the steal's ramp) ----------------------------
    def render(self) -> None:
        """a block: live.Organ.render x TRIM (x the steal's ramp when the word `fade` is 1)"""
        p, C, L = self.p, self.L.C, self.L
        V, c = self.V, self.c
        e = lambda j: c(f"e{j}")              # noqa: E731
        dt = k(F(F(LV.SUB) * LV.DT))
        self.set(c("speech"), k(0.01) * exp2f(e(9) * kd(3.9, 127.0)))
        self.set(c("chiffk"), e(8) * kd(1.0, 127.0))
        self.set(c("air"), e(11) * kd(0.06, 127.0))
        self.set(c("windk"), e(12) * kd(1.0, 127.0))
        self.set(c("trem"), e(13) * kd(1.0, 127.0))
        self.set(c("trem_hz"), k(3.0) * exp2f(e(14) * kd(1.6, 127.0)))
        self.set(c("celeste"), e(15) * kd(14.0, 127.0))
        self.fz(c("tot"))
        self.fz(c("onset"))
        p.iconst(0, 0)
        p.st(C["nr"], 0)
        self.set(V("wind_v"), V("wind_v") + ((bi() - V("wind_v")) * dt) * k(3.0))
        self.set(V("wind"), V("wind") + ((V("wind_v") - V("wind")) * dt) * k(1.5))
        self.set(V("trem_ph"), V("trem_ph") + c("trem_hz") * dt)
        self.set(c("tmp0"), V("trem_ph"))
        self.ld(0, c("tmp0"))
        p.fpass(15, 0)
        _floor(p, 15, 14, 13, 12)
        p.fop(0, 0, "-", 14)
        self.st(V("trem_ph"), 0)
        self.set(c("tr"), c("trem") * sin_turns(V("trem_ph")))
        self.set(c("wob"), V("wind") * c("windk"))
        self.blocks_v05(dt)
        # the 32-sample sum: zeros
        p.iconst(0, L.A["yb"])
        p.seti(4, 0)
        p.fconst(5, 0.0)
        p.loop_r(10, BLOCK, lambda: p.stpost(4, 5), one=11)
        # the ranks, in order: their coefficients, and each one sounding summed into yb at once
        # (live: every coefficient first, then the ranks in the same order: the same sums)
        for kk in range(8):
            self.rank_call(kk)
        # the level
        def big():
            self.set(c("tot"), (k(0.55) * recip(sqrtf(c("tot")))))
        self.cmp(c("tot"), "GT", k(1.0), big, lambda: self.set(c("tot"), k(0.55)))
        p.ld(0, C["stop"])
        p.iconst(12, 4)
        p.iop(0, 0, "MIN", 12)
        p.iconst(12, 0)
        p.iop(0, 0, "MAX", 12)
        p.lsh(0, 0, 2)
        p.iconst(12, L.tables + 4 * GAIN_AT)
        p.iop(0, 12, "+", 0)
        p.seti(1, 0)
        p.ldi(1, 0, 1)
        self.ld(0, c("tot"))
        p.fop(0, 0, "*", 1)
        p.st(C["tot"], 0)
        # the chiff's SVF: set(min(f 3, 9000), 5)
        self.set(c("hz"), V("f") * k(3.0))
        self.cmp(c("hz"), "LT", k(9000.0), None, lambda: self.set(c("hz"), k(9000.0)))
        # clampf(hz, 10, 0.9 NYQ): hz if 10 < hz < top, else top if hz > 10, else 10
        top = float(F(LV.NYQ * F(0.9)))

        def clamp_out():
            self.cmp(c("hz"), "GT", k(10.0), lambda: self.set(c("hz"), k(top)),
                     lambda: self.set(c("hz"), k(10.0)))
        self.cmp(c("hz"), "GT", k(10.0), lambda: self.cmp(c("hz"), "LT", k(top), None, clamp_out), clamp_out)
        self.set(c("tmp0"), (k(3.14159265) * c("hz")) * k(LV.DT))
        self.tanf("gt", "tmp0")
        self.set(c("a1"), recip(k(1.0) + c("gt") * (c("gt") + kd(1.0, 5.0))))
        self.set(c("a2"), c("gt") * c("a1"))
        self.set(c("a3"), c("gt") * c("a2"))
        # the onset's mean
        p.ld(0, C["nr"])

        def mean():
            p.ld(0, C["nr"])
            p.st(C["lo"], 0)
            self.set(c("ons"), c("onset") * recip(fi(self.ci("lo"))))
        p.ifz(0, "NE", mean, lambda: self.fz(c("ons")))
        self.set(c("ka"), k(0.3) + k(0.7) * c("ons"))
        self.post_setup(dt)
        # the samples: the noise, the chiff, the air, the level, TRIM, the ramp; the output test
        p.iconst(0, 0)
        p.st(C["bad"], 0)
        p.iconst(0, L.A["yb"])
        p.st(C["ybp"], 0)
        p.ld(9, L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, BUFFERS)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.st(C["outp"], 0)
        p.iconst(0, L.tables + 4 * RAMP_AT)
        p.st(C["lo"], 0)

        def sample():
            p.ld(12, C["ybp"])
            p.seti(4, 12)
            self.set(c("tmp0"), bi())
            # the SVF's band-pass on the noise
            self.set(c("tmp1"), c("tmp0") - V("ic2"))                                  # v3
            self.set(c("g"), c("a1") * V("ic1") + c("a2") * c("tmp1"))                 # v1
            self.set(c("lv"), (V("ic2") + c("a2") * V("ic1")) + c("a3") * c("tmp1"))  # v2
            self.set(V("ic1"), k(2.0) * c("g") - V("ic1"))
            self.set(V("ic2"), k(2.0) * c("lv") - V("ic2"))
            self.set(V("air_lp"), V("air_lp") + (c("tmp0") - V("air_lp")) * k(0.08))
            y = Mv("i", 4, 0) * kd(1.0, 127.0)
            y = y + ((((c("g") * c("chiffk")) * V("chiff")) * k(0.5)) + (V("air_lp") * c("air")) * c("ka"))
            y = (y * c("tot")) * k(LV.TRIM)
            self.ev(y, 0)
            p.st(C["yv"], 0)
            self.post_sample()
            p.ld(0, C["yv"])

            def ramp():
                p.ld(12, C["lo"])
                p.seti(3, 12)
                p.ldi(1, 0, 3)
                p.fop(0, 0, "*", 1)
            p.ld(1, C["fade"])
            p.ifz(1, "NE", ramp)
            p.ld(12, C["outp"])
            p.seti(3, 12)
            p.sti(0, 3, 0)
            p.iconst(1, 0x7F800000)
            p.iop(2, 0, "AND", 1)
            p.if_(2, "EQ", 1, lambda: (p.iconst(3, 1), p.st(C["bad"], 3)), kind="i")
            self.set(V("chiff"), V("chiff") * k(0.9992))
            self.cmp(V("chiff"), "LT", k(LV.CHIFF_FLOOR), lambda: self.fz(V("chiff")))
            for word in ("ybp", "outp", "lo"):
                p.ld(13, C[word])
                p.iconst(12, 4)
                p.iop(13, 12, "+", 13)
                p.st(C[word], 13)
        self.p.loop(C["cnt0"], BLOCK, sample)
        self.set(V("t"), V("t") + dt)

        def blown():                           # live._check: silence, the voice off, its state cleared
            self.zeros()
            self.iset(V("on"), 0)
            self.iset(V("fading"), 0)
            self.iset(V("magic"), 0)
        p.ld(0, C["bad"])
        p.ifz(0, "NE", blown)

    # -- v0.5: pages 3 and 4, the block's part (live.Organ.render after `wob`) ---------------
    def blocks_v05(self, dt) -> None:
        p, C = self.p, self.L.C
        V, c = self.V, self.c
        e = lambda j: c(f"e{j}")              # noqa: E731
        # CELESTE's fade
        def cel_on():
            def up():
                self.set(V("cel_g"), V("cel_g") + k(LV.CEL_STEP))
                self.cmp(V("cel_g"), "GT", k(1.0), lambda: self.set(V("cel_g"), k(1.0)))
            self.cmp(V("cel_g"), "LT", k(1.0), up)

        def cel_off():
            def down():
                self.set(V("cel_g"), V("cel_g") - k(LV.CEL_STEP))
                self.cmp(V("cel_g"), "LT", k(0.0), lambda: self.fz(V("cel_g")))
            self.cmp(V("cel_g"), "GT", k(0.0), down)
        self.cmp(c("celeste"), "GT", k(0.01), cel_on, cel_off)
        # the rotor
        self.set(c("rot"), e(22) * kd(1.0, 127.0))
        self.fz(c("rotc"))
        self.fz(V("rs"))

        def rotor():
            self.set(c("tgt"), k(0.6) * exp2f(e(23) * kd(3.55, 127.0)))
            self.cmp(V("rhz"), "LE", k(0.0), lambda: self.set(V("rhz"), c("tgt")),
                     lambda: self.set(V("rhz"), V("rhz") + ((c("tgt") - V("rhz")) * dt) * k(LV.ROT_SLEW)))
            self.set(V("rph"), V("rph") + V("rhz") * dt)
            self.wrap(V("rph"))
            self.set(V("rs"), sin_turns(V("rph")))
            self.set(c("rotc"), (c("rot") * k(8.0)) * sin_turns(V("rph") + k(0.25)))
        self.cmp(c("rot"), "GT", k(0.0), rotor)
        # the jet, the pressure, the break
        self.set(c("bb"), e(24) * kd(1.0, 127.0))
        self.set(c("brk"), e(26) * kd(1.0, 127.0))
        self.set(c("edge"), e(30) * kd(1.0, 127.0))
        self.set(c("tgt"), (e(28) * kd(1.0, 127.0)) + (e(31) * kd(1.0, 127.0)) * (V("pvel") - k(0.5)))
        self.clamp01("tgt")
        self.set(V("press"), c("tgt"))
        self.fz(V("jj"))

        def jet():
            self.set(c("fc"), k(1.5) * exp2f(e(25) * kd(5.3, 127.0)))
            self.set(c("aa"), (c("fc") * k(LV.TWO_PI)) * dt)
            self.cmp(c("aa"), "GT", k(1.0), lambda: self.set(c("aa"), k(1.0)))
            self.set(V("jv1"), V("jv1") + (jbi() - V("jv1")) * c("aa"))
            self.set(V("jv2"), V("jv2") + (V("jv1") - V("jv2")) * c("aa"))
            self.set(V("jj"), (V("jv2") * sqrtf(recip(c("aa")))) * k(3.5))
            self.clamp("jj", -float(LV.J_CLIP), float(LV.J_CLIP), voice=True)
        self.any_gt0(("bb", "brk", "edge"), jet)
        self.set(c("rotc"), c("rotc") + ((c("bb") * k(50.0)) * V("jj") + V("press") * k(15.0)))

        def brk_on():
            self.set(c("tgt"), ((V("jj") + V("press") * k(1.5)) - (k(2.2) - c("brk") * k(2.4))) * k(2.0))
            self.clamp01("tgt")
            self.cmp(c("tgt"), "GT", V("bk"), lambda: self.set(V("bk"), V("bk") + (c("tgt") - V("bk")) * k(LV.BK_UP)),
                     lambda: self.set(V("bk"), V("bk") + (c("tgt") - V("bk")) * k(LV.BK_DOWN)))
        self.cmp(c("brk"), "GT", k(0.0), brk_on, lambda: self.fz(V("bk")))
        self.set(V("dep"), V("bk") * (k(0.35) + e(27) * kd(1.0, 127.0)))

    # -- v0.5: live.Organ.post (pages 3 and 4, after the level and TRIM) ---------------------
    def flag(self, name: str, val: int) -> None:
        self.p.iconst(0, val)
