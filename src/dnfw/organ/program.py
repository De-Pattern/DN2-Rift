def k(x) -> Kc:
    """a float32 constant, as live.py computes it"""
    return Kc(float(F(x)))


def kd(a, b) -> Kc:
    """F(F(a) / F(b)), live.py's constant quotients"""
    return Kc(float(F(F(a) / F(b))))


class Layout:
    def __init__(self, fascia: FP_.Layout, tables: int):
        self.fl = fascia
        self.state, self.state2 = fascia.state, fascia.state2
        self.t_word = fascia.C["t"]
        self.stolen, self.strikes = fascia.stolen, fascia.strikes
        self.tables = tables
        at = fascia.arrays                     # FASCIA's transient arrays (its pool sits before them)
        self.C = {}
        for name in WORDS:
            self.C[name] = at
            at += 4
        self.A = {"yb": at}
        at += 4 * BLOCK
        self.words_end = at
        assert at <= fascia.scratch_end, "ORGAN's words must fit in FASCIA's arrays"
        # I5 and the scratch range are FASCIA's: the leaves are emitted once, for both machines,
        # and address their words (sq_x) and the constant pool from FASCIA's I5
        self.scratch, self.scratch_end, self.base5 = fascia.scratch, fascia.scratch_end, fascia.base5
        self.rets = fascia.rets                # ORGAN calls no routines (Gen.rt): unused


# -- Ravel's maths, as leaves (F15 in and out; R12-R15, I1, I12 clobbered) -----------------------
EXP2_C = [1.0, 0.693146929, 0.240230502, 0.0554804263, 0.00968458045, 0.00123878215, 0.000218775048]
SIN_C = [-1.66666667e-1, 8.33333333e-3, -1.98412698e-4, 2.75573192e-6, -2.50521084e-8]


def _floor(p, src: int, dst: int, ri: int, tmp: int) -> None:
    """Fdst = floorf(Fsrc) (Ravel: the truncation, one less when above), Rri = it as an int"""
    p.trunc(ri, src)
    p.iconst(tmp, 0)
    p.float_(dst, ri, tmp)

    def down():
        p.fconst(tmp, 1.0)
        p.fop(dst, dst, "-", tmp)
        p.iconst(tmp, 1)
        p.iop(ri, ri, "-", tmp)
    p.if_(src, "LT", dst, down)


def _sin_r(p) -> None:
    """F15 = _sin_r(F15) (turns, folded into -0.25..0.25)"""
    def hi():
        p.fconst(12, 0.5)
        p.fop(15, 12, "-", 15)

    def lo():
        p.fconst(12, -0.25)

        def neg():
            p.fconst(12, -0.5)
            p.fop(15, 12, "-", 15)
        p.if_(15, "LT", 12, neg)
    p.fconst(12, 0.25)
    p.if_(15, "GT", 12, hi, lo)
    p.fconst(12, float(LV.TWO_PI))
    p.fop(15, 15, "*", 12)                     # x
    p.fop(14, 15, "*", 15)                     # x2
    _horner(p, 13, 14, SIN_C)                  # p
    p.fop(14, 15, "*", 14)                     # x x2
    p.fop(14, 14, "*", 13)
    p.fop(15, 15, "+", 14)


def _o_exp2(g) -> None:
    p = g.p

    def body():
        def rest():
            p.fconst(12, 127.0)
            p.fop(15, 15, "MIN", 12)
            _floor(p, 15, 14, 13, 12)          # F14 = n, R13 = n
            p.fop(15, 15, "-", 14)             # f
            _horner(p, 14, 15, EXP2_C)
            p.iconst(12, 127)
            p.iop(13, 13, "+", 12)
            p.lsh(13, 13, 23)                  # 2^n
            p.fop(15, 14, "*", 13)
        p.fconst(12, -126.0)
        p.if_(15, "LT", 12, lambda: p.fconst(15, 0.0), rest)
    _leaf(p, "o_exp2", body)


def _o_sint(g) -> None:
    """sin_turns: _sin_r(ph - floorf(ph + 0.5))"""
    p = g.p

    def body():
        p.fconst(12, 0.5)
        p.fop(14, 15, "+", 12)
        _floor(p, 14, 13, 12, 12)
        p.fop(15, 15, "-", 13)
        _sin_r(p)
    _leaf(p, "o_sint", body)


def _o_sinf(g) -> None:
    p = g.p

    def body():
        p.fconst(12, 0.159154943)
        p.fop(14, 15, "*", 12)
        p.fconst(12, 0.5)
        p.fop(14, 14, "+", 12)
        _floor(p, 14, 13, 12, 12)              # F13 = k
        p.fconst(12, 6.28125)
        p.fop(14, 13, "*", 12)
        p.fop(15, 15, "-", 14)
        p.fconst(12, 1.93530718e-3)
        p.fop(14, 13, "*", 12)
        p.fop(15, 15, "-", 14)
        p.fconst(12, 0.159154943)
        p.fop(15, 15, "*", 12)
        _sin_r(p)
    _leaf(p, "o_sinf", body)


def _o_sqrt(g) -> None:
    """Ravel's sqrtf: 0 for x <= 0; the seed 0x1fbd1df5 + bits >> 1, three Newton steps (recip)"""
    p, C = g.p, g.L.C

    def body():
        def rest():
            p.st(C["sq_x"], 15)
            p.lsh(14, 15, -1)
            p.iconst(12, 0x1FBD1DF5)
            p.iop(14, 12, "+", 14)             # y
            for _ in range(3):
                _recip_body(p, 14, 13, 15)     # F13 = recip(y)
                p.ld(15, C["sq_x"])
                p.fop(13, 15, "*", 13)
                p.fop(13, 14, "+", 13)
                p.fconst(12, 0.5)
                p.fop(14, 12, "*", 13)
            p.fpass(15, 14)
        p.fconst(12, 0.0)
        p.if_(15, "LE", 12, lambda: p.fconst(15, 0.0), rest)
    _leaf(p, "o_sqrt", body)


OLEAF = {"o_exp2": _o_exp2, "o_sint": _o_sint, "o_sinf": _o_sinf, "o_sqrt": _o_sqrt,
         "obi": _xs_leaf("obi", 2, VOICE["ns"], "bi")}


def exp2f(x) -> E:
    return Fn("o_exp2", x)


def expf(x) -> E:
    return Fn("o_exp2", w(x) * k(LV.LOG2E))


def sin_turns(x) -> E:
    return Fn("o_sint", x)


def sinf(x) -> E:
    return Fn("o_sinf", x)


def sqrtf(x) -> E:
    return Fn("o_sqrt", x)


def bi() -> E:
    return Fn("obi", Kc(0.0))


class OG(Gen):
    """FASCIA's compiler with ORGAN's leaves"""

    def call_at(self, name: str, r: int) -> None:
        if name not in OLEAF:
            return super().call_at(name, r)
        p = self.p
        if r == 0:
            OLEAF[name](self)
            return
        p.fpass(r + 1, 0)
        p.fpass(0, r)
        OLEAF[name](self)
        p.fpass(r, 0)
        p.fpass(0, r + 1)

    def V(self, name, j: int = 0) -> Mv:
        return Mv("i", 2, VOICE[name] + j)

    # -- the voice's block ------------------------------------------------------------------
    def voice(self, t: int | None) -> None:
        p, C, L = self.p, self.L.C, self.L
        V = self.V
        if p.run:
            p.iconst(9, t)
            p.st(L.t_word, 9)
        self.vbase()
        self.stolen_check()
        self.read_note()
        # the life words: exactly 1, or 0; and the state's magic, or the voice is off
        for f in ("on", "pending", "fading"):
            self.ld(0, V(f))
            p.iconst(1, 1)
            p.if_(0, "NE", 1, lambda f=f: (p.iconst(0, 0), self.st(V(f), 0)), kind="i")
        self.ld(0, V("magic"))
        p.iconst(1, MAGIC)
        p.if_(0, "NE", 1, lambda: (self.iset(V("on"), 0), self.iset(V("fading"), 0)), kind="i")

        def note_on():
            self.new_note()
            p.ld(0, C["nn"])
            self.st(V("pnote"), 0)
            self.iset(V("pending"), 1)
            self.ld(0, V("on"))
            self.st(V("fading"), 0)
        p.ld(0, C["trig"])
        p.ifz(0, "NE", note_on)
        self.ld(0, V("on"))
        self.ld(1, V("pending"))
        p.iop(0, 0, "OR", 1)
        p.ifz(0, "NE", self.read_knobs)
        self.ld(0, V("fading"))
        self.ld(1, V("on"))
        p.iop(0, 0, "AND", 1)

        def fade():
            self.iset(V("fading"), 0)
            self.iset(V("on"), 0)
            self.iset(self.c("fade"), 1)
            self.rt("o_render", self.render)

        def normal():
            self.icmp(V("pending"), "EQ", 1, self.strike)
            self.iset(self.c("fade"), 0)
            self.iflag(V("on"), lambda: self.rt("o_render", self.render), self.zeros)
        p.ifz(0, "NE", fade, normal)

    def vbase(self) -> None:
        """I2 = the slot's state: STATE + STRIDE t (t < 8), STATE2 + STRIDE (t - 8)"""
        p, L = self.p, self.L
        assert STRIDE == 4096 - 128
        p.ld(9, L.t_word)
        p.iconst(12, 7)
        p.iop(13, 9, "AND", 12)
        p.lsh(12, 13, 12)
        p.lsh(13, 13, 7)
        p.iop(12, 12, "-", 13)
        p.iconst(11, L.state)
        p.iconst(13, 8)
        p.if_(9, "GE", 13, lambda: p.iconst(11, L.state2), kind="i")
        p.iop(12, 11, "+", 12)
        p.seti(2, 12, "this slot's ORGAN voice")

    def _slot_word(self, base: int) -> None:
        p = self.p
        p.ld(9, self.L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, base)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)

    def stolen_check(self) -> None:
        """the guard left this voice out twice in one note (perc.guard.around): it rests"""
        p = self.p
        self._slot_word(self.L.stolen)
        p.ldi(0, 0, 1)

        def rest():
            p.iconst(0, 0)
            p.sti(0, 1, 0)
            self.iset(self.V("on"), 0)
            self.iset(self.V("fading"), 0)
        p.ifz(0, "NE", rest)

    def new_note(self) -> None:
        """a trig: the guard's strikes against this slot start again"""
        p = self.p
        self._slot_word(self.L.strikes)
        p.iconst(0, 0)
        p.sti(0, 1, 0)

    def read_note(self) -> None:
        """the trig bit and the note (the frame's header word 2 + 2t, / 256), as FASCIA's"""
        p, C, L = self.p, self.L.C, self.L
        p.ld(0, TRIG_WORD)
        p.lsh(0, 0, -16)
        p.iconst(1, 1)
        p.ld(9, L.t_word)
        PP._shift_by(p, 1, 9)
        p.iop(0, 0, "AND", 1)
        p.st(C["trig"], 0)
        p.ld(9, L.t_word)
        p.iop(10, 9, "+", 9)
        PP.half(p, 8, NOTE_OFFSET, 10)
        p.iconst(12, -8)
        p.float_(8, 8, 12)
        p.st(C["nn"], 8)

    def read_knobs(self) -> None:
        """the 16 knobs from FASCIA's records' frame words (live.knob_of), and eff (live.eff_of)"""
        from ..fascia import machines as FM
        p, C, L = self.p, self.L.C, self.L
        p.ld(9, L.t_word)
        PP.t146(p, 10, 9)
        p.st(C["k146"], 10)
        for j, ride in enumerate(LV.RIDES):
            _rid, slot, lo, top = FM.SLOTS[ride]
            assert lo == 0
            p.ld(10, C["k146"])
            PP.half(p, 4, 168 + 2 * slot, 10)
            p.lsh(4, 4, -8)
            p.iconst(12, top)
            p.iop(4, 4, "MIN", 12)
            if top != 127:
                p.iconst(12, 0)
                p.float_(4, 4, 12)
                p.fconst(6, 254.0 / (200 if top == 100 else 240))
                p.fop(4, 4, "*", 6)
                p.fconst(6, 0.502)
                p.fop(4, 4, "+", 6)
                p.trunc(4, 4)
            p.st(C[f"q{j}"], 4)
            if j == 0:                         # STOP: the option, (k 5) >> 7, at most 4
                p.lsh(12, 4, 2)
                p.iop(4, 12, "+", 4)
                p.lsh(4, 4, -7)
                p.iconst(12, 4)
                p.iop(4, 4, "MIN", 12)
                p.st(C["stop"], 4)
            p.iconst(12, 0)
            p.float_(4, 4, 12)
            p.st(C[f"e{j}"], 4)

    # -- the strike (live.Voice: organ_note) ------------------------------------------------
    def strike(self) -> None:
        p, C, L = self.p, self.L.C, self.L
        V, c = self.V, self.c
        self.iset(V("pending"), 0)
        self.ld(0, V("pnote"))
        p.lsh(12, 0, -23)
        p.iconst(13, 0xFF)
        p.iop(12, 12, "AND", 13)
        p.if_(12, "EQ", 13, lambda: p.fconst(0, 0.0), kind="i")
        p.st(C["tmp0"], 0)
        # note_hz: 440 exp2f((n - 69) (1/12))
        self.set(V("f"), k(440.0) * exp2f((c("tmp0") - k(69.0)) * kd(1.0, 12.0)))

        def fresh():                           # Organ(): every word zero, then the magic
            p.iconst(0, 0)
            for name in ("ns", "t", "chiff", "air_lp", "wind", "wind_v", "trem_ph", "ic1", "ic2"):
                self.st(V(name), 0)
            for name in ("ph", "dly", "cents"):
                for j in range(8):
                    self.st(V(name, j), 0)
            p.iconst(0, MAGIC)
            self.st(V("magic"), 0)
        self.ld(0, V("magic"))
        p.iconst(1, MAGIC)
        p.if_(0, "NE", 1, fresh, kind="i")
        # organ_note
        e = lambda j: c(f"e{j}")              # noqa: E731
        self.set(c("spread"), e(10) * kd(0.035, 127.0))
        self.set(c("windn"), e(12) * kd(4.0, 127.0))

        def seed():                            # ns = rng | 1, rng = 0x2545f491 + slot
            p.ld(9, L.t_word)
            p.iconst(12, 0x2545F491)
            p.iop(0, 12, "+", 9)
            p.iconst(12, 1)
            p.iop(0, 0, "OR", 12)
            self.st(V("ns"), 0)
        self.ld(0, V("ns"))
        p.ifz(0, "EQ", seed)
        self.fz(V("t"))
        p.fconst(0, 1.0)
        self.st(V("chiff"), 0)
        for j in range(8):
            self.set(V("dly", j), c("spread") * (bi() * k(0.5) + k(0.5)))
            self.set(V("cents", j), (c("windn") * k(0.5)) * bi())
            self.set(V("ph", j), bi() * k(0.5) + k(0.5))
        self.iset(V("on"), 1)

    # -- a block (live.Organ.render, x TRIM, and the steal's ramp) ----------------------------
    def render(self) -> None:
        """a block: live.Organ.render x TRIM (x the steal's ramp when the word `fade` is 1)"""
        p, C, L = self.p, self.L.C, self.L
        V, c = self.V, self.c
        e = lambda j: c(f"e{j}")              # noqa: E731
        dt = k(F(F(LV.SUB) * LV.DT))
        self.set(c("speech"), k(0.01) * exp2f(e(9) * kd(3.9, 127.0)))
        self.set(c("chiffk"), e(8) * kd(1.0, 127.0))
        self.set(c("air"), e(11) * kd(0.06, 127.0))
        self.set(c("windk"), e(12) * kd(1.0, 127.0))
        self.set(c("trem"), e(13) * kd(1.0, 127.0))
        self.set(c("trem_hz"), k(3.0) * exp2f(e(14) * kd(1.6, 127.0)))
        self.set(c("celeste"), e(15) * kd(14.0, 127.0))
        self.fz(c("tot"))
        self.fz(c("onset"))
        p.iconst(0, 0)
        p.st(C["nr"], 0)
        self.set(V("wind_v"), V("wind_v") + ((bi() - V("wind_v")) * dt) * k(3.0))
        self.set(V("wind"), V("wind") + ((V("wind_v") - V("wind")) * dt) * k(1.5))
        self.set(V("trem_ph"), V("trem_ph") + c("trem_hz") * dt)
        self.set(c("tmp0"), V("trem_ph"))
        self.ld(0, c("tmp0"))
        p.fpass(15, 0)
        _floor(p, 15, 14, 13, 12)
        p.fop(0, 0, "-", 14)
        self.st(V("trem_ph"), 0)
        self.set(c("tr"), c("trem") * sin_turns(V("trem_ph")))
        self.set(c("wob"), V("wind") * c("windk"))
        # the 32-sample sum: zeros
        p.iconst(0, L.A["yb"])
        p.seti(4, 0)
        p.fconst(5, 0.0)
        p.loop_r(10, BLOCK, lambda: p.stpost(4, 5), one=11)
        # the ranks, in order: their coefficients, and each one sounding summed into yb at once
        # (live: every coefficient first, then the ranks in the same order: the same sums)
        for kk in range(8):
            self.rank_call(kk)
        # the level
        def big():
            self.set(c("tot"), (k(0.55) * recip(sqrtf(c("tot")))))
        self.cmp(c("tot"), "GT", k(1.0), big, lambda: self.set(c("tot"), k(0.55)))
        p.ld(0, C["stop"])
        p.iconst(12, 4)
        p.iop(0, 0, "MIN", 12)
        p.iconst(12, 0)
        p.iop(0, 0, "MAX", 12)
        p.lsh(0, 0, 2)
        p.iconst(12, L.tables + 4 * GAIN_AT)
        p.iop(0, 12, "+", 0)
        p.seti(1, 0)
        p.ldi(1, 0, 1)
        self.ld(0, c("tot"))
        p.fop(0, 0, "*", 1)
        p.st(C["tot"], 0)
        # the chiff's SVF: set(min(f 3, 9000), 5)
        self.set(c("hz"), V("f") * k(3.0))
        self.cmp(c("hz"), "LT", k(9000.0), None, lambda: self.set(c("hz"), k(9000.0)))
        # clampf(hz, 10, 0.9 NYQ): hz if 10 < hz < top, else top if hz > 10, else 10
        top = float(F(LV.NYQ * F(0.9)))

        def clamp_out():
            self.cmp(c("hz"), "GT", k(10.0), lambda: self.set(c("hz"), k(top)),
                     lambda: self.set(c("hz"), k(10.0)))
        self.cmp(c("hz"), "GT", k(10.0), lambda: self.cmp(c("hz"), "LT", k(top), None, clamp_out), clamp_out)
        self.set(c("tmp0"), (k(3.14159265) * c("hz")) * k(LV.DT))
        self.tanf("gt", "tmp0")
        self.set(c("a1"), recip(k(1.0) + c("gt") * (c("gt") + kd(1.0, 5.0))))
        self.set(c("a2"), c("gt") * c("a1"))
        self.set(c("a3"), c("gt") * c("a2"))
        # the onset's mean
        p.ld(0, C["nr"])

        def mean():
            p.ld(0, C["nr"])
            p.st(C["lo"], 0)
            self.set(c("ons"), c("onset") * recip(fi(self.ci("lo"))))
        p.ifz(0, "NE", mean, lambda: self.fz(c("ons")))
        self.set(c("ka"), k(0.3) + k(0.7) * c("ons"))
        # the samples: the noise, the chiff, the air, the level, TRIM, the ramp; the output test
        p.iconst(0, 0)
        p.st(C["bad"], 0)
        p.iconst(0, L.A["yb"])
        p.st(C["ybp"], 0)
        p.ld(9, L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, BUFFERS)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.st(C["outp"], 0)
        p.iconst(0, L.tables + 4 * RAMP_AT)
        p.st(C["lo"], 0)

        def sample():
            p.ld(12, C["ybp"])
            p.seti(4, 12)
            self.set(c("tmp0"), bi())
            # the SVF's band-pass on the noise
            self.set(c("tmp1"), c("tmp0") - V("ic2"))                                  # v3
            self.set(c("g"), c("a1") * V("ic1") + c("a2") * c("tmp1"))                 # v1
            self.set(c("lv"), (V("ic2") + c("a2") * V("ic1")) + c("a3") * c("tmp1"))  # v2
            self.set(V("ic1"), k(2.0) * c("g") - V("ic1"))
            self.set(V("ic2"), k(2.0) * c("lv") - V("ic2"))
            self.set(V("air_lp"), V("air_lp") + (c("tmp0") - V("air_lp")) * k(0.08))
            y = Mv("i", 4, 0) * kd(1.0, 127.0)
            y = y + ((((c("g") * c("chiffk")) * V("chiff")) * k(0.5)) + (V("air_lp") * c("air")) * c("ka"))
            y = (y * c("tot")) * k(LV.TRIM)
            self.ev(y, 0)

            def ramp():
                p.ld(12, C["lo"])
                p.seti(3, 12)
                p.ldi(1, 0, 3)
                p.fop(0, 0, "*", 1)
            p.ld(1, C["fade"])
            p.ifz(1, "NE", ramp)
            p.ld(12, C["outp"])
            p.seti(3, 12)
            p.sti(0, 3, 0)
            p.iconst(1, 0x7F800000)
            p.iop(2, 0, "AND", 1)
            p.if_(2, "EQ", 1, lambda: (p.iconst(3, 1), p.st(C["bad"], 3)), kind="i")
            self.set(V("chiff"), V("chiff") * k(0.9992))
            self.cmp(V("chiff"), "LT", k(LV.CHIFF_FLOOR), lambda: self.fz(V("chiff")))
            for word in ("ybp", "outp", "lo"):
                p.ld(13, C[word])
                p.iconst(12, 4)
                p.iop(13, 12, "+", 13)
                p.st(C[word], 13)
        self.p.loop(C["cnt0"], BLOCK, sample)
        self.set(V("t"), V("t") + dt)

        def blown():                           # live._check: silence, the voice off, its state cleared
            self.zeros()
            self.iset(V("on"), 0)
            self.iset(V("fading"), 0)
            self.iset(V("magic"), 0)
        p.ld(0, C["bad"])
        p.ifz(0, "NE", blown)

    def tanf(self, dst: str, src: str) -> None:
        """Ravel's tanf: sinf(x) / cosf(x), the cosine kept at least 1e-7 from 0"""
        c, p = self.c, self.p
        self.set(c("cc"), sinf(c(src) + k(1.57079633)))
        self.set(c("tmp1"), FP_.ab(c("cc")))

        def small():
            self.cmp(c("cc"), "LT", k(0.0), lambda: self.set(c("cc"), k(-1e-7)),
                     lambda: self.set(c("cc"), k(1e-7)))
        self.cmp(c("tmp1"), "LT", k(1e-7), small)
        self.set(c(dst), sinf(c(src)) * recip(c("cc")))

    def rank_call(self, kk: int) -> None:
        """rank KK: its level, its constants and I0 = the voice + KK words, then the routine"""
        p, c = self.p, self.c
        e = lambda j: c(f"e{j}")              # noqa: E731
        if kk < 7:
            self.set(c("lv"), e(1 + kk) * kd(1.0, 127.0))
        else:
            self.cmp(c("celeste"), "GT", k(0.01), lambda: self.set(c("lv"), e(2) * kd(0.8, 127.0)),
                     lambda: self.fz(c("lv")))
        self.set(c("mk"), k(F(F(1.0) - F(F(kk if kk < 7 else 1) * F(0.07)))))
        self.set(c("rat"), k(LV.RATIO[kk]))
        if kk < 7:
            self.fz(c("cx"))
        else:
            self.set(c("cx"), c("celeste"))
        self._i0(kk)
        self.rt("o_rank", self.rank)

    def _i0(self, kk: int) -> None:
        """I0 = I2 + KK words (the slot's base, as vbase computes it, + 4 KK)"""
        p, L = self.p, self.L
        p.ld(9, L.t_word)
        p.iconst(12, 7)
        p.iop(13, 9, "AND", 12)
        p.lsh(12, 13, 12)
        p.lsh(13, 13, 7)
        p.iop(12, 12, "-", 13)
        p.iconst(11, L.state)
        p.iconst(13, 8)
        p.if_(9, "GE", 13, lambda: p.iconst(11, L.state2), kind="i")
        p.iop(12, 11, "+", 12)
        p.iconst(11, 4 * kk)
        p.iop(12, 11, "+", 12)
        p.seti(0, 12, "rank's words")

    def rank(self) -> None:
        """a rank's coefficients (live.render's first loop) and, if it sounds, its samples (I0: the
        voice + the rank's index in words; lv, mk, rat, cx its level and constants)"""
        p, C, L = self.p, self.L.C, self.L
        V, c = self.V, self.c
        R = lambda name: Mv("i", 0, VOICE[name])      # noqa: E731  (this rank's word)
        self.set(c("age"), V("t") - R("dly"))
        self.set(c("tmp1"), c("speech") * c("mk"))                                       # sp

        def sounds():
            def onset():
                self.set(c("g"), k(1.0) - expf((-c("age")) * recip(c("tmp1"))))
            self.cmp(c("age"), "LE", k(0.0), lambda: self.fz(c("g")), onset)
            cents = (((R("cents") - (k(1.0) - c("g")) * k(18.0)) + c("wob") * k(3.0)) + c("tr") * k(6.0)) + c("cx")
            self.set(c("cents"), cents)
            self.set(c("fr"), (V("f") * c("rat")) * exp2f(c("cents") * kd(1.0, 1200.0)))
            self.cmp(c("fr"), "GT", k(F(F(0.45) * F(LV.FS))), None, keep)

        def keep():
            self.set(c("lvl"), (c("lv") * c("g")) * ((k(1.0) + c("tr") * k(0.22)) + c("wob") * k(0.03)))
            self.set(c("inc"), (c("fr") * k(LV.DT)) * k(float(LV.ORG_N)))
            self.set(c("room"), k(F(F(0.45) * F(LV.FS))) * recip(c("fr")))

            def mid():
                self.set(c("sh"), (k(24.0) - c("room")) * k(LV.INV20))

            def low():
                self.set(c("tmp0"), (k(4.0) - c("room")) * k(LV.INV3))

                def pos():
                    self.cmp(c("tmp0"), "LT", k(1.0), None, lambda: self.set(c("tmp0"), k(1.0)))
                self.cmp(c("tmp0"), "GT", k(0.0), pos, lambda: self.fz(c("tmp0")))
                self.set(c("sh"), k(1.0) + c("tmp0"))
            self.cmp(c("room"), "GE", k(24.0), lambda: self.fz(c("sh")),
                     lambda: self.cmp(c("room"), "GE", k(4.0), mid, low))
            self.set(c("tot"), c("tot") + c("lv"))
            self.set(c("onset"), c("onset") + c("g"))
            p.ld(0, C["nr"])
            p.iconst(12, 1)
            p.iop(0, 12, "+", 0)
            p.st(C["nr"], 0)
            p.iconst(0, 0)
            p.st(C["lo"], 0)
            self.cmp(c("sh"), "LT", k(1.0), None, lambda: (p.iconst(0, 1), p.st(C["lo"], 0)))
            self.set(c("sh"), c("sh") - fi(self.ci("lo")))
            self.samples()
        self.cmp(c("lv"), "LT", k(0.002), None, sounds)

    def samples(self) -> None:
        """the rank's 32 samples (I0: its words) into yb: the table read (and the next table's, crossfaded)"""
        p, C, L = self.p, self.L.C, self.L
        # R8 = ta, R9 = tb: tables + 4 x 256 (3 stop + lo), + 1024
        p.ld(0, C["stop"])
        p.iconst(12, 4)
        p.iop(0, 0, "MIN", 12)
        p.iconst(12, 0)
        p.iop(0, 0, "MAX", 12)
        p.lsh(1, 0, 1)
        p.ipass(12, 1)
        p.iop(0, 12, "+", 0)                   # 3 stop
        p.ld(1, C["lo"])
        p.ipass(12, 1)
        p.iop(0, 12, "+", 0)
        p.lsh(0, 0, 10)
        p.iconst(12, L.tables)
        p.iop(8, 12, "+", 0)
        p.iconst(12, 4 * LV.ORG_N)
        p.iop(9, 8, "+", 12)
        p.ldi(0, VOICE["ph"], 0)               # ph
        p.ld(1, C["inc"])                      # dp
        p.ld(2, C["lvl"])                      # lv
        p.ld(3, C["sh"])                       # sh

        def body(xf: bool):
            def one():
                p.fop(0, 0, "+", 1)
                p.fconst(4, float(LV.ORG_N))
                p.if_(0, "GE", 4, lambda: p.fop(0, 0, "-", 4))
                p.trunc(12, 0)
                p.iconst(13, LV.ORG_N - 1)
                p.iop(12, 12, "AND", 13)       # i0
                p.iconst(13, 0)
                p.float_(4, 12, 13)
                p.fop(4, 0, "-", 4)            # fr
                p.iconst(13, 1)
                p.iop(13, 13, "+", 12)
                p.iconst(14, LV.ORG_N - 1)
                p.iop(13, 13, "AND", 14)       # i1
                p.lsh(12, 12, 2)
                p.lsh(13, 13, 2)
                p.iop(14, 8, "+", 12)
                p.seti(1, 14)
                p.ldi(5, 0, 1)
                p.iop(14, 8, "+", 13)
                p.seti(1, 14)
                p.ldi(6, 0, 1)
                p.fop(6, 6, "-", 5)
                p.fop(6, 6, "*", 4)
                p.fop(5, 5, "+", 6)            # a
                if xf:
                    p.iop(14, 9, "+", 12)
                    p.seti(1, 14)
                    p.ldi(6, 0, 1)
                    p.iop(14, 9, "+", 13)
                    p.seti(1, 14)
                    p.ldi(7, 0, 1)
                    p.fop(7, 7, "-", 6)
                    p.fop(7, 7, "*", 4)
                    p.fop(6, 6, "+", 7)        # b
                    p.fop(6, 6, "-", 5)
                    p.fop(6, 6, "*", 3)
                    p.fop(5, 5, "+", 6)        # a + (b - a) sh
                p.fop(5, 5, "*", 2)
                p.ldi(6, 0, 4)
                p.fop(6, 6, "+", 5)
                p.stpost(4, 6)
            p.iconst(12, L.A["yb"])
            p.seti(4, 12)
            p.loop_r(10, BLOCK, one, one=11)
        p.fconst(4, 0.001)
        p.if_(3, "GT", 4, lambda: body(True), lambda: body(False))
        p.sti(VOICE["ph"], 0, 0)

    def zeros(self) -> None:
        p, L = self.p, self.L
        p.ld(9, L.t_word)
        p.lsh(12, 9, 2)
        p.iconst(11, BUFFERS)
        p.iop(12, 11, "+", 12)
        p.seti(1, 12)
        p.ldi(0, 0, 1)
        p.seti(4, 0, "the slot's buffer")
        p.fconst(5, 0.0)
        p.loop_r(10, BLOCK, lambda: p.stpost(4, 5), one=11)


def voice(p, L: Layout, t: int | None = None) -> OG:
    """one slot's ORGAN block, inside FASCIA's walk: I5 is FASCIA's scratch base (+ WIN words), as
    FASCIA's own voice sets it; constants may come from FASCIA's pool (filled at the walk's entry)"""
    g = OG(p, L)
    saved = p.scr_on
    p.iconst(0, L.base5)
    p.seti(5, 0, "the scratch's base + WIN words")
    p.scr_on = True
    g.voice(t)
    p.scr_on = saved
    return g


def run_voice(L: Layout, read, t: int, mem=None):
    """the model: one slot's block on memory READ (and MEM's earlier writes). -> (Prog, mem)"""
    mem = mem or Mem(read)
    p = FProg("run", mem=mem)
    p.pool = {}
    p.spill = None
    p.scr = (L.scratch, L.scratch_end, L.base5)
    voice(p, L, t)
    return p, mem


def layout() -> Layout:
    from ..waverider import dsp
    return Layout(FP_.layout(), dsp.ORGAN_TABLES_DDR)
