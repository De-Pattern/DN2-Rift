"""ORGAN's DSP program (machine type 19): `dnfw.organ.live.Voice` on the SHARC, in PERC's two-backend
DSL (dnfw.perc.dsl) on FASCIA's expression compiler (dnfw.fascia.program.Gen): the same calls are the
assembly text and, run in Python, its exact model. test_organ_program holds the run mode to live.Voice
bit for bit; the SHARC runner's `organ` part holds the assembled code to the run mode.

**Where it runs.** Inside FASCIA's program (fascia.asm, `wr_fsc`): FASCIA's walk over the slots (PERC's
voice order, the newest note first) renders a slot whose frame type word is 19 with this, under the
same frame guard (perc.guard.around) and with the same steal bookkeeping. A slot is one machine or the
other, so an ORGAN voice lives in the slot's FASCIA state (STATE + STRIDE t): its life words (on,
pending, fading) are FASCIA's first three, so FASCIA's `off` turns it off too, and the walk clears both
when a slot's type changes (fascia.program LASTTYPE).

**The voice** is live.Voice, statement for statement, with Ravel's own maths as leaves (exp2f,
sin_turns, sinf, sqrtf: rv_math.h) and FASCIA's `recip` for every divide. It plays until the next
note, as the Monomachine's machines (the DN2's amp envelope shapes what is heard): about one table read
or two per sample for each rank sounding, the SVF and the noise per sample, the rest once a block.

**Memory.** The voice's words at the slot's state; the block's words and its 32-sample sum in FASCIA's
transient scratch arrays (FASCIA writes them before it reads them in every block: never its constant
pool), addressed from I5 as FASCIA's are; the pipes (org_tab as floats), the stops' gains and the
steal's ramp in DDR (ORGAN_TABLES).
"""

