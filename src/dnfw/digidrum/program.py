"""DIGIDRUM's DSP program (machine type 22): `dnfw.digidrum.live.Voice` on the SHARC, in PERC's
two-backend DSL on FASCIA's expression compiler with ORGAN's leaves (exp2f, expf, sin_turns), as
RESONATOR's was. The same calls are the assembly text and, run in Python, its exact model;
test_digidrum_program holds the run mode to live.Voice bit for bit.

**Where it runs.** Inside FASCIA's program (fascia.asm), as ORGAN, SILT and LIGATURE do: FASCIA's
walk renders a slot whose frame type word is 22 with this, under the same guard and steal
bookkeeping. Its voice lives in the slot's FASCIA state; the walk's type change clears its magic.

**The block.** The sixteen knobs (KREC); at a trig, the hit's setup for its type (`t_<type>`); the
type's 32 raw samples (`r_<type>`, a routine each) into `raw`; then one pass shared by every type:
PNCH, the velocity, OVER, the type's gain, page 2's tone (EQ, base/width filter, AM, LEV), into the
slot's buffer, and the peak (the voice rests when quiet).
"""
